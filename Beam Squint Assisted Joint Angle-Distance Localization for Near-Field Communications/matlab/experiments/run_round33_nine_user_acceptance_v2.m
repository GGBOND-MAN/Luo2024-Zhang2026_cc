function run_round33_nine_user_acceptance_v2()
%RUN_ROUND33_NINE_USER_ACCEPTANCE_V2 Compare against a fresh R32 replay.
% Historical saved outputs are retained as a separate cross-run diagnostic;
% the frozen numerical tolerances are applied to same-run reference kernels.

project = string(fileparts(fileparts(mfilename("fullpath"))));
addpath(project);
raw = r31.loadRound30Raw(project);
controlFile = fullfile(project, "results", "full_spectrum", ...
    "round31_angle_controls_v2", "result.mat");
control = load(controlFile, "identity", "results");
protocol = r33.config();
cfg = raw.pilot.expected.cfg;
scan = fsjad.prepareScan(cfg);
rowIndex = selectedRows(raw.pilot.design, protocol.development);
rows = table();
failure = emptyFailures();

for localUser = 1:numel(rowIndex)
    index = rowIndex(localUser);
    design = raw.pilot.design(index, :);
    try
        replay = fsjad.replayRound27Data(cfg, scan, design);
        fresh = r33.sharedRegressionSet(cfg, replay.observation, ...
            replay.snapshots, scan, protocol, UseFastResponse=false, ...
            UseGram=false);
        historical = historicalReference(raw, control, index);
        for variant = protocol.variants
            [useFastResponse, useGram] = variantOptions(variant);
            fast = r33.sharedRegressionSet(cfg, replay.observation, ...
                replay.snapshots, scan, protocol, ...
                UseFastResponse=useFastResponse, UseGram=useGram);
            rows = [rows; compareVariant(design, variant, fast, fresh, ...
                historical, protocol.validation)]; %#ok<AGROW>
        end
    catch exception
        failure = [failure; table(design.seed, design.snrDb, ...
            string(exception.identifier), string(getReport(exception, ...
            "extended", "hyperlinks", "off")), 'VariableNames', ...
            failure.Properties.VariableNames)]; %#ok<AGROW>
    end
end

summary = summarizeVariants(rows, protocol.variants);
variantPass = table();
for variant = protocol.variants
    selected = rows.variant == variant;
    pass = nnz(selected) == 4*numel(rowIndex) ...
        && all(rows.pass(selected)) ...
        && isempty(failure);
    variantPass = [variantPass; table(variant, pass, nnz(selected), ...
        sum(rows.fallbackCount(selected)), 'VariableNames', ...
        {'variant', 'pass', 'completedMethodRuns', ...
        'totalFallbackCount'})]; %#ok<AGROW>
end

folder = fullfile(project, "results", "full_spectrum", ...
    "round33_equivalent_acceleration_v1", "nine_user_acceptance_v2");
if ~isfolder(folder)
    mkdir(folder);
end
writetable(rows, fullfile(folder, "per_method_comparisons.csv"));
writetable(summary, fullfile(folder, "variant_maxima.csv"));
writetable(variantPass, fullfile(folder, "variant_pass.csv"));
writetable(failure, fullfile(folder, "failures.csv"));
source = r33.manifest(project);
writetable(source, fullfile(folder, "source_hashes.csv"));
identity = struct(version="R33-nine-existing-user-acceptance-v2", ...
    reference="fresh-same-process-R32-kernels", ...
    historicalUse="cross-run-output-diagnostic-only", ...
    protocol=protocol, design=raw.pilot.design(rowIndex, :), ...
    pilotHash=raw.pilotHash, baselineHash=raw.baselineHash, ...
    controlIdentity=control.identity, supersedesResultOnly= ...
    "nine_user_acceptance-v1-reference-contract-error");
save(fullfile(folder, "result.mat"), "identity", "rows", ...
    "summary", "variantPass", "failure", "source", "-v7.3");
if ~all(variantPass.pass)
    error("r33:NineUserAcceptanceV2Failed", ...
        "At least one frozen equivalent implementation did not pass v2.");
end
fprintf("ROUND33_NINE_USER_ACCEPTANCE_V2_COMPLETE runs=%d fallbacks=%d\n", ...
    height(rows), sum(rows.fallbackCount));
end

function output = emptyFailures()
output = table('Size', [0, 4], ...
    'VariableTypes', {'double', 'double', 'string', 'string'}, ...
    'VariableNames', {'seed', 'snrDb', 'errorIdentifier', 'errorMessage'});
end

function rowIndex = selectedRows(design, development)
rowIndex = zeros(numel(development.snrDb)*development.usersPerSnr, 1);
cursor = 1;
for snrDb = development.snrDb
    found = find(design.snrDb == snrDb, ...
        development.usersPerSnr, "first");
    rowIndex(cursor:cursor+numel(found)-1) = found;
    cursor = cursor+numel(found);
end
end

function historical = historicalReference(raw, control, index)
baseline = raw.baselines.results{index, raw.l06BaselineIndex};
historical.C_enhanced = struct(thetaDeg=control.results{index}.thetaDeg(1), ...
    rangeM=control.results{index}.rangeM(1));
historical.H_A = struct(thetaDeg=control.results{index}.thetaDeg(2), ...
    rangeM=control.results{index}.rangeM(2));
historical.P_A = struct(thetaDeg=control.results{index}.thetaDeg(3), ...
    rangeM=control.results{index}.rangeM(3));
historical.C_public = struct( ...
    thetaDeg=baseline.publicBaseline.estimate.thetaDeg, ...
    rangeM=baseline.publicBaseline.estimate.rangeM);
end

function [useFastResponse, useGram] = variantOptions(variant)
useFastResponse = variant ~= "B_gram_subspace";
useGram = variant ~= "A_response_invariants";
end

function rows = compareVariant( ...
    design, variant, fast, fresh, historical, tolerance)
[frontDifference, frontPass] = compareFront( ...
    fast.front, fresh.front, tolerance);
methods = ["C_enhanced", "H_A", "P_A", "C_public"];
rows = table();
for method = methods
    actual = fast.(method);
    expected = fresh.(method);
    old = historical.(method);
    [fastState, referenceState, musicCfg] = states(method, fast, fresh);
    projection = sum(conj(referenceState.signalVectors) ...
        .*fastState.signalVectors, 1);
    projectionDifference = max(abs(1-abs(projection).^2));
    referenceForScore = fastState;
    referenceForScore.signalVectors = referenceState.signalVectors;
    scoreRange = fresh.front.selected.rangeM;
    if method == "C_enhanced" || method == "C_public"
        scoreRange = expected.rangeM;
    end
    scoreDifference = abs(jad.localMusicLogScore(musicCfg, fastState, ...
        expected.thetaDeg, scoreRange) ...
        - jad.localMusicLogScore(musicCfg, referenceForScore, ...
        expected.thetaDeg, scoreRange));
    thetaDifference = abs(actual.thetaDeg-expected.thetaDeg);
    rangeDifference = abs(actual.rangeM-expected.rangeM);
    historicalThetaDifference = abs(expected.thetaDeg-old.thetaDeg);
    historicalRangeDifference = abs(expected.rangeM-old.rangeM);
    [fallbackCount, gramCount, directCount, residual, eigengap] = ...
        stateDiagnostics(method, fast);
    pass = frontPass ...
        && thetaDifference <= tolerance.thetaToleranceDeg ...
        && rangeDifference <= tolerance.rangeToleranceM ...
        && projectionDifference <= tolerance.projectionTolerance ...
        && scoreDifference <= tolerance.profileScoreTolerance;
    rows = [rows; table(design.seed, design.snrDb, variant, method, ...
        thetaDifference, rangeDifference, projectionDifference, ...
        scoreDifference, historicalThetaDifference, ...
        historicalRangeDifference, frontDifference.thetaDeg, ...
        frontDifference.rangeM, frontDifference.bankThetaDeg, ...
        frontDifference.bankRangeM, frontDifference.bankScore, ...
        frontDifference.selectedBankThetaDeg, ...
        frontDifference.selectedBankRangeM, ...
        frontDifference.selectedBankScore, ...
        frontDifference.sameSelectedIndex, ...
        frontDifference.sameBankSize, frontDifference.sameBankSources, ...
        frontDifference.sameSelectedBankSources, fallbackCount, ...
        gramCount, directCount, residual, eigengap, pass, ...
        'VariableNames', {'seed', 'snrDb', 'variant', 'method', ...
        'absoluteThetaDifferenceDeg', 'absoluteRangeDifferenceM', ...
        'signalProjectionDifference', 'musicScoreDifference', ...
        'freshVsHistoricalThetaDifferenceDeg', ...
        'freshVsHistoricalRangeDifferenceM', ...
        'frontThetaDifferenceDeg', 'frontRangeDifferenceM', ...
        'frontBankThetaDifferenceDeg', 'frontBankRangeDifferenceM', ...
        'frontBankScoreDifference', 'selectedBankThetaDifferenceDeg', ...
        'selectedBankRangeDifferenceM', 'selectedBankScoreDifference', ...
        'sameFrontSelectedIndex', 'sameFrontBankSize', ...
        'sameFrontBankSources', 'sameSelectedBankSources', ...
        'fallbackCount', 'gramSuccessCount', 'directCount', ...
        'maximumRelativeResidual', 'minimumRelativeEigengap', 'pass'})]; %#ok<AGROW>
end
end

function [fastState, referenceState, musicCfg] = states(method, fast, fresh)
if method == "C_public"
    fastState = fast.publicState;
    referenceState = fresh.publicState;
    musicCfg = fast.publicCfg;
else
    fastState = fast.enhancedState;
    referenceState = fresh.enhancedState;
    musicCfg = fast.enhancedCfg;
end
end

function [fallback, gram, direct, residual, eigengap] = ...
    stateDiagnostics(method, fast)
if method == "C_public"
    cost = fast.publicStateCost;
else
    cost = fast.enhancedStateCost;
end
fallback = cost.fallbackCount;
gram = cost.gramSuccessCount;
direct = cost.directCount;
residual = cost.maximumRelativeResidual;
eigengap = cost.minimumRelativeEigengap;
end

function [difference, pass] = compareFront(actual, expected, tolerance)
difference = struct(thetaDeg=abs(actual.selected.thetaDeg ...
    - expected.selected.thetaDeg), rangeM=abs(actual.selected.rangeM ...
    - expected.selected.rangeM), bankThetaDeg=inf, bankRangeM=inf, ...
    bankScore=inf, selectedBankThetaDeg=inf, ...
    selectedBankRangeM=inf, selectedBankScore=inf, ...
    sameSelectedIndex=actual.selectedIndex == expected.selectedIndex, ...
    sameBankSize=height(actual.candidateBank) ...
    == height(expected.candidateBank), sameBankSources=false, ...
    sameSelectedBankSources=false);
if difference.sameBankSize
    difference.bankThetaDeg = maximumDifference( ...
        actual.candidateBank.thetaDeg, expected.candidateBank.thetaDeg);
    difference.bankRangeM = maximumDifference( ...
        actual.candidateBank.rangeM, expected.candidateBank.rangeM);
    difference.bankScore = maximumDifference( ...
        actual.candidateBank.subsetLogScore, ...
        expected.candidateBank.subsetLogScore);
    difference.sameBankSources = isequal(actual.candidateBank.source, ...
        expected.candidateBank.source);
end
sameSelectedBankSize = height(actual.selectedBank) ...
    == height(expected.selectedBank);
if sameSelectedBankSize
    difference.selectedBankThetaDeg = maximumDifference( ...
        actual.selectedBank.thetaDeg, expected.selectedBank.thetaDeg);
    difference.selectedBankRangeM = maximumDifference( ...
        actual.selectedBank.rangeM, expected.selectedBank.rangeM);
    difference.selectedBankScore = maximumDifference( ...
        actual.selectedBank.subsetLogScore, ...
        expected.selectedBank.subsetLogScore);
    difference.sameSelectedBankSources = isequal( ...
        actual.selectedBank.source, expected.selectedBank.source);
end
pass = difference.thetaDeg <= tolerance.selectedCandidateTolerance(1) ...
    && difference.rangeM <= tolerance.selectedCandidateTolerance(2) ...
    && difference.bankThetaDeg ...
        <= tolerance.selectedCandidateTolerance(1) ...
    && difference.bankRangeM ...
        <= tolerance.selectedCandidateTolerance(2) ...
    && difference.bankScore <= tolerance.candidateScoreTolerance ...
    && difference.selectedBankThetaDeg ...
        <= tolerance.selectedCandidateTolerance(1) ...
    && difference.selectedBankRangeM ...
        <= tolerance.selectedCandidateTolerance(2) ...
    && difference.selectedBankScore <= tolerance.candidateScoreTolerance ...
    && difference.sameSelectedIndex && difference.sameBankSize ...
    && difference.sameBankSources && difference.sameSelectedBankSources;
end

function value = maximumDifference(left, right)
if isempty(left) && isempty(right)
    value = 0;
else
    value = max(abs(left-right), [], "all");
end
end

function summary = summarizeVariants(rows, variants)
fields = ["absoluteThetaDifferenceDeg", "absoluteRangeDifferenceM", ...
    "signalProjectionDifference", "musicScoreDifference", ...
    "freshVsHistoricalThetaDifferenceDeg", ...
    "freshVsHistoricalRangeDifferenceM", ...
    "frontThetaDifferenceDeg", "frontRangeDifferenceM", ...
    "frontBankThetaDifferenceDeg", "frontBankRangeDifferenceM", ...
    "frontBankScoreDifference", "selectedBankThetaDifferenceDeg", ...
    "selectedBankRangeDifferenceM", "selectedBankScoreDifference", ...
    "fallbackCount"];
summary = table();
for variant = variants
    selected = rows.variant == variant;
    values = zeros(1, numel(fields));
    for field = 1:numel(fields)
        values(field) = max(rows.(fields(field))(selected), [], "all");
    end
    entry = array2table(values, VariableNames=cellstr("max_"+fields));
    entry = addvars(entry, variant, Before=1, NewVariableNames="variant");
    summary = [summary; entry]; %#ok<AGROW>
end
end
