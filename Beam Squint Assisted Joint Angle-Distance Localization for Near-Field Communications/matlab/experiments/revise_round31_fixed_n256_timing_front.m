function revise_round31_fixed_n256_timing_front()
%REVISE_ROUND31_FIXED_N256_TIMING_FRONT Apply the original timing front.

project = string(fileparts(fileparts(mfilename("fullpath"))));
addpath(project);
sourceFolder = fullfile(project, "results", "full_spectrum", ...
    "round31_fixed_n256_timing_v2");
saved = load(fullfile(sourceFolder, "result.mat"), ...
    "identity", "output", "environment");
oldTimingFile = fullfile(project, "results", "full_spectrum", ...
    "round30_complexity_scaling_v1", "timing.csv");
oldTiming = readtable(oldTimingFile);
oldTiming = oldTiming(oldTiming.numAntennas == 256, ...
    {'seed', 'repetition', 'frontSeconds', 'publicMusicSeconds', ...
    'enhancedMusicSeconds'});
oldTiming.Properties.VariableNames(3:5) = ...
    {'originalTimingFrontSeconds', 'publicAssumptionBackendSeconds', ...
    'oldAdaptedL128EnhancedBackendSeconds'};

rows = innerjoin(saved.output, oldTiming, Keys={'seed', 'repetition'});
if height(rows) ~= height(saved.output) ...
        || any(rows.numAntennas ~= 256 | rows.subarraySize ~= 160)
    error("r31:TimingFrontJoinMismatch", ...
        "The original N256 timing front did not join one-to-one.");
end
rows.pilotFrontRuntimeSeconds = rows.frontHistoricalSeconds;
rows.endToEndUsingPilotFrontRuntimeSeconds = ...
    rows.endToEndUsingHistoricalFrontSeconds;
rows.endToEndUsingOriginalTimingFrontSeconds = ...
    rows.backendSeconds+rows.originalTimingFrontSeconds;
rows.publicAssumptionEndToEndSeconds = ...
    rows.originalTimingFrontSeconds+rows.publicAssumptionBackendSeconds;
rows.oldAdaptedL128EnhancedEndToEndSeconds = ...
    rows.originalTimingFrontSeconds ...
    +rows.oldAdaptedL128EnhancedBackendSeconds;

summary = table();
for method = unique(rows.method, "stable").'
    methodRows = rows(rows.method == method, :);
    entry = table(method, height(methodRows), ...
        methodRows.carrierCount(1), mean(methodRows.backendSeconds), ...
        median(methodRows.backendSeconds), ...
        mean(methodRows.originalTimingFrontSeconds), ...
        mean(methodRows.endToEndUsingOriginalTimingFrontSeconds), ...
        median(methodRows.endToEndUsingOriginalTimingFrontSeconds), ...
        mean(methodRows.publicAssumptionEndToEndSeconds), ...
        'VariableNames', {'method', 'nTimingRows', 'carrierCount', ...
        'meanBackendSeconds', 'medianBackendSeconds', ...
        'meanOriginalTimingFrontSeconds', ...
        'meanCorrectedEndToEndSeconds', ...
        'medianCorrectedEndToEndSeconds', ...
        'meanPublicAssumptionEndToEndSeconds'});
    summary = [summary; entry]; %#ok<AGROW>
end

control = rows(rows.method == "C_enhanced", ...
    {'seed', 'repetition', 'backendSeconds', ...
    'endToEndUsingOriginalTimingFrontSeconds'});
control.Properties.VariableNames(3:4) = ...
    {'controlBackendSeconds', 'controlEndToEndSeconds'};
speedup = table();
for method = unique(rows.method, "stable").'
    methodRows = rows(rows.method == method, ...
        {'seed', 'repetition', 'backendSeconds', ...
        'endToEndUsingOriginalTimingFrontSeconds', ...
        'publicAssumptionEndToEndSeconds'});
    methodRows.Properties.VariableNames(3:5) = ...
        {'methodBackendSeconds', 'methodEndToEndSeconds', ...
        'publicEndToEndSeconds'};
    paired = innerjoin(control, methodRows, Keys={'seed', 'repetition'});
    entry = table(method, ...
        mean(paired.controlBackendSeconds./paired.methodBackendSeconds), ...
        median(paired.controlBackendSeconds./paired.methodBackendSeconds), ...
        mean(paired.controlEndToEndSeconds./paired.methodEndToEndSeconds), ...
        median(paired.controlEndToEndSeconds./paired.methodEndToEndSeconds), ...
        mean(paired.publicEndToEndSeconds./paired.methodEndToEndSeconds), ...
        'VariableNames', {'method', 'meanBackendSpeedupVsC', ...
        'medianBackendSpeedupVsC', 'meanEndToEndSpeedupVsC', ...
        'medianEndToEndSpeedupVsC', ...
        'meanEndToEndSpeedupVsPublicAssumption'});
    speedup = [speedup; entry]; %#ok<AGROW>
end

controlRows = rows(rows.method == "C_enhanced", :);
correction = table(mean(controlRows.originalTimingFrontSeconds), ...
    mean(controlRows.publicAssumptionBackendSeconds), ...
    mean(controlRows.oldAdaptedL128EnhancedBackendSeconds), ...
    mean(controlRows.backendSeconds), ...
    mean(controlRows.oldAdaptedL128EnhancedEndToEndSeconds), ...
    mean(controlRows.endToEndUsingOriginalTimingFrontSeconds), ...
    mean(controlRows.backendSeconds) ...
    /mean(controlRows.oldAdaptedL128EnhancedBackendSeconds), ...
    'VariableNames', {'meanOriginalTimingFrontSeconds', ...
    'meanPublicAssumptionBackendSeconds', ...
    'meanOldAdaptedL128EnhancedBackendSeconds', ...
    'meanCorrectedL160EnhancedBackendSeconds', ...
    'meanOldAdaptedL128EnhancedEndToEndSeconds', ...
    'meanCorrectedL160EnhancedEndToEndSeconds', ...
    'correctedToOldEnhancedBackendRatio'});

folder = fullfile(project, "results", "full_spectrum", ...
    "round31_fixed_n256_timing_front_corrected_v3");
if ~isfolder(folder)
    mkdir(folder);
end
source = r31.manifest(project);
inputHashes = fsjad.sourceHashManifest(project, [ ...
    "results/full_spectrum/round31_fixed_n256_timing_v2/result.mat"; ...
    "results/full_spectrum/round30_complexity_scaling_v1/timing.csv"]);
writetable(rows, fullfile(folder, "timing_rows_corrected_front.csv"));
writetable(summary, fullfile(folder, "timing_summary_corrected_front.csv"));
writetable(speedup, fullfile(folder, "paired_speedup_corrected_front.csv"));
writetable(correction, fullfile(folder, "cost_correction.csv"));
writetable(source, fullfile(folder, "source_hashes.csv"));
writetable(inputHashes, fullfile(folder, "input_hashes.csv"));
identity = struct(version="R31-fixed-N256-L160-timing-front-v3", ...
    sourceTimingIdentity=saved.identity, inputHashes=inputHashes, ...
    source=source, correctionOnly=true, noEstimatorRecomputation=true);
environment = saved.environment;
save(fullfile(folder, "aggregate.mat"), "identity", "environment", ...
    "rows", "summary", "speedup", "correction");
fprintf("ROUND31_TIMING_FRONT_REVISION_COMPLETE oldL128=%g correctedL160=%g\n", ...
    correction.meanOldAdaptedL128EnhancedBackendSeconds, ...
    correction.meanCorrectedL160EnhancedBackendSeconds);
end
