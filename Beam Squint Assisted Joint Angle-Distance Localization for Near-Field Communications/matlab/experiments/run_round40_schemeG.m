function source = sourceFromListing(project, listing)
paths = strings(numel(listing), 1);
for index = 1:numel(listing)
    file = string(fullfile(listing(index).folder, listing(index).name));
    paths(index) = replace(extractAfter(file, strlength(project)+1), ...
        string(filesep), "/");
end
source = fsjad.sourceHashManifest(project, sort(unique(paths)));
end

function hash = fileHash(file)
stream = java.security.MessageDigest.getInstance("SHA-256");
input = java.io.FileInputStream(java.io.File(char(file)));
cleanup = onCleanup(@() input.close()); %#ok<NASGU>
buffer = zeros(1, 1024*1024, "int8");
while true
    count = input.read(buffer, 0, numel(buffer));
    if count < 0
        break;
    end
    stream.update(buffer(1:count));
end
hash = lower(join(string(dec2hex(typecast(stream.digest(), ...
    "uint8"), 2)).', ""));
end
