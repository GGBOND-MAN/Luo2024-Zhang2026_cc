function output = run_pfa_postcalibration_matched_timing(options)
%RUN_PFA_POSTCALIBRATION_MATCHED_TIMING Time frozen complete estimators.

arguments
    options.PositionIds (1, :) double {mustBeInteger, mustBePositive} = 1:5
    options.SnrDb (1, 1) double = 0
    options.Repetitions (1, 1) double {mustBeInteger, mustBePositive} = 3
    options.Warmups (1, 1) double {mustBeInteger, mustBeNonnegative} = 1
end

project = string(fileparts(fileparts(mfilename("fullpath"))));
r41.addPaths(project);
calibrationFolder = fullfile(project, "results", "full_spectrum", ...
    "round45_pfa_calibration600_v1");
calibrationFile = fullfile(calibrationFolder, "result.mat");
if ~isfile(calibrationFile)
    error("r45:TimingRequiresCalibration", ...
        "Matched timing requires the completed R45 calibration.");
end
saved = load(calibrationFile, "protocol", "identity", "design", "summary");
if ~saved.identity.calibrationReady || saved.identity.completedRows ~= 600 ...
        || ~saved.summary.calibrationReady
    error("r45:TimingCalibrationNotReady", ...
        "The R45 calibration did not authorize post-calibration timing.");
end
currentDigest = r32.sourceDigest(r45.manifest(project));
if currentDigest ~= saved.identity.sourceDigest
    error("r45:TimingSourceDrift", ...
        "The frozen P_FA calibration source has changed.");
end

selected = ismember(saved.design.positionId, options.PositionIds) ...
    & saved.design.snrDb == options.SnrDb;
design = sortrows(saved.design(selected, :), "positionId");
if height(design) ~= numel(options.PositionIds)
    error("r45:TimingDesignMismatch", ...
        "The requested matched-timing rows are not unique and complete.");
end
folder = fullfile(calibrationFolder, "matched_timing");
if isfolder(folder)
    error("r45:TimingAlreadyExists", ...
        "The R45 matched-timing result cannot be overwritten.");
end
mkdir(folder);

cfg = jad.defaultConfig();
scan = fsjad.prepareScan(cfg);
protocol = saved.protocol;
methods = ["P_FA", "P_A", "G_schur", "C_enhanced"];
rows = table();
for positionIndex = 1:height(design)
    replay = fsjad.replayRound27Data(cfg, scan, design(positionIndex, :));
    for warmup = 1:options.Warmups
        for method = methods
            executeMethod(cfg, scan, replay, method, protocol);
        end
    end
    for repetition = 1:options.Repetitions
        shift = mod(positionIndex+repetition-2, numel(methods));
        order = circshift(methods, -shift);
        for orderIndex = 1:numel(order)
            method = order(orderIndex);
            timer = tic;
            record = executeMethod(cfg, scan, replay, method, protocol);
            wallSeconds = toc(timer);
            entry = table(design.positionId(positionIndex), ...
                design.seed(positionIndex), repetition, orderIndex, ...
                method, wallSeconds, record.reportedSeconds, ...
                record.responseEquivalentCount, ...
                record.musicEvaluationCount, record.evdCount, ...
                record.fullArrayEvaluationCount, record.profilePassCount, ...
                'VariableNames', {'positionId', 'seed', 'repetition', ...
                'orderIndex', 'method', 'wallSeconds', 'reportedSeconds', ...
                'responseEquivalentCount', 'musicEvaluationCount', ...
                'evdCount', 'fullArrayEvaluationCount', 'profilePassCount'});
            rows = [rows; entry]; %#ok<AGROW>
        end
    end
end

summary = table();
for method = methods
    selectedRows = rows(rows.method == method, :);
    entry = table(method, height(selectedRows), ...
        mean(selectedRows.wallSeconds), median(selectedRows.wallSeconds), ...
        std(selectedRows.wallSeconds), mean(selectedRows.reportedSeconds), ...
        mean(selectedRows.responseEquivalentCount), ...
        mean(selectedRows.musicEvaluationCount), ...
        mean(selectedRows.evdCount), ...
        mean(selectedRows.fullArrayEvaluationCount), ...
        mean(selectedRows.profilePassCount), ...
        'VariableNames', {'method', 'n', 'meanWallSeconds', ...
        'medianWallSeconds', 'stdWallSeconds', 'meanReportedSeconds', ...
        'meanResponseEquivalentCount', 'meanMusicEvaluationCount', ...
        'meanEvdCount', 'meanFullArrayEvaluationCount', ...
        'meanProfilePassCount'});
    summary = [summary; entry]; %#ok<AGROW>
end
pfa = summary(summary.method == "P_FA", :);
comparison = table();
for reference = ["P_A", "G_schur", "C_enhanced"]
    baseline = summary(summary.method == reference, :);
    comparison = [comparison; table("P_FA", reference, ...
        pfa.meanWallSeconds/baseline.meanWallSeconds, ...
        100*(1-pfa.meanWallSeconds/baseline.meanWallSeconds), ...
        pfa.medianWallSeconds/baseline.medianWallSeconds, ...
        'VariableNames', {'candidate', 'reference', 'meanRuntimeRatio', ...
        'meanRuntimeReductionPct', 'medianRuntimeRatio'})]; %#ok<AGROW>
end
identity = struct(version="R45-PFA-postcalibration-matched-timing-v1", ...
    calibrationVersion=saved.identity.version, ...
    calibrationSourceDigest=saved.identity.sourceDigest, ...
    calibrationDesignHash=saved.identity.designHash, ...
    performanceTrialsExecuted=0, replayedCalibrationRows=height(design), ...
    newUsersGenerated=0, snrDb=options.SnrDb, ...
    positionIds=options.PositionIds, repetitions=options.Repetitions, ...
    warmups=options.Warmups, serverThroughputUsed=false, ...
    timestamp=string(datetime("now", "TimeZone", "Asia/Shanghai")));
writetable(rows, fullfile(folder, "raw_timing_rows.csv"));
writetable(summary, fullfile(folder, "timing_summary.csv"));
writetable(comparison, fullfile(folder, "runtime_comparison.csv"));
save(fullfile(folder, "result.mat"), "identity", "design", ...
    "rows", "summary", "comparison", "-v7.3");
output = struct(folder=folder, identity=identity, rows=rows, ...
    summary=summary, comparison=comparison);
disp(summary);
disp(comparison);
end

function record = executeMethod(cfg, scan, replay, method, protocol)
if method == "P_FA"
    estimate = r45.estimatePFA(cfg, replay.observation, ...
        replay.snapshots, scan, protocol);
    record = struct(reportedSeconds=estimate.totalOnlineSeconds, ...
        responseEquivalentCount=estimate.responseEquivalentCount, ...
        musicEvaluationCount=0, evdCount=0, ...
        fullArrayEvaluationCount=estimate.fullArrayEvaluationCount, ...
        profilePassCount=estimate.profilePassCount);
elseif method == "G_schur"
    pa = r34.estimate(cfg, replay.observation, replay.snapshots, ...
        scan, "P_A", protocol.r34);
    g = r41.gFromPA(cfg, scan, replay, pa, protocol.r41);
    incremental = g.contextSeconds+g.angle.standaloneAngleSeconds ...
        +g.transport.runtimeSeconds;
    record = baselineRecord(pa);
    record.reportedSeconds = record.reportedSeconds+incremental;
    record.responseEquivalentCount = record.responseEquivalentCount ...
        +g.angle.fullArrayEvaluationCount ...
        +g.transport.addedResponseEvaluationCount;
    record.fullArrayEvaluationCount = g.angle.fullArrayEvaluationCount;
    record.profilePassCount = 1;
else
    estimate = r34.estimate(cfg, replay.observation, replay.snapshots, ...
        scan, method, protocol.r34);
    record = baselineRecord(estimate);
    record.profilePassCount = double(method == "P_A");
end
end

function output = baselineRecord(input)
output = struct(reportedSeconds=input.cost.totalOnlineSeconds, ...
    responseEquivalentCount=input.cost.sparseResponseCalls ...
    +input.cost.frontFullResponseCalls+input.cost.profileResponseCalls, ...
    musicEvaluationCount=input.estimate.evaluationCount, ...
    evdCount=input.cost.directCount, fullArrayEvaluationCount=0, ...
    profilePassCount=0);
end
