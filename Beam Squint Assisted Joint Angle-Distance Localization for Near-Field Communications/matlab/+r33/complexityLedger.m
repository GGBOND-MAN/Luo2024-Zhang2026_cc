function ledger = complexityLedger(cfg, counts)
%COMPLEXITYLEDGER Keep symbolic orders and implementation counts separate.

arguments
    cfg (1, 1) struct
    counts (:, :) table
end

required = ["Es", "Ef", "Er", "G_C", "G_A", "G_public", ...
    "enhancedMatrixFormationMacs", "enhancedEvdCubicUnits", ...
    "enhancedRecoveryMacs", "publicMatrixFormationMacs", ...
    "publicEvdCubicUnits", "publicRecoveryMacs"];
if ~all(ismember(required, string(counts.Properties.VariableNames)))
    error("r33:ComplexityCountsMissing", ...
        "The actual-count table is missing one or more required columns.");
end

protocol = r33.config();
verifyFixedDimensions(cfg, protocol);
ledger.fixedConstants = fixedConstants(cfg, protocol);
ledger.componentFormulas = componentFormulas();
ledger.methodFormulas = methodFormulas();
ledger.actualPerUser = actualRows(cfg, protocol, counts);
ledger.actualSummary = summarizeActual(ledger.actualPerUser);
ledger.subspaceComparison = subspaceComparison(protocol);
ledger.responseMemory = responseMemory(cfg, protocol);
ledger.ratioStatements = table( ...
    ["R32_historical_complete_runtime_reduction"; ...
    "frozen_search_point_reduction"], [35.04; ...
    100*(1-sum(protocol.r32.music.gridSizes) ...
    /sum(protocol.r32.enhancedC.gridSizes.^2))], ...
    ["runtime measurement from R32; superseded by R33 timing"; ...
    "MUSIC score-evaluation count only; not total runtime"], ...
    'VariableNames', {'quantity', 'percent', 'interpretation'});
end

function output = responseMemory(cfg, protocol)
realBytes = 8;
complexBytes = 16;
fullElements = cfg.numAntennas*cfg.numSubcarriers;
sparseElements = cfg.numAntennas*protocol.r32.front.carrierCount;
quantity = ["full_q_only_derivative_arrays_not_constructed"; ...
    "sparse_q_only_derivative_arrays_not_constructed"; ...
    "persistent_conjugate_full_beamformer_context"];
bytes = [fullElements*(2*realBytes+2*complexBytes); ...
    sparseElements*(2*realBytes+2*complexBytes); ...
    fullElements*complexBytes];
scope = ["two real distance derivatives plus two complex response derivatives"; ...
    "same four arrays on Q=513 sparse carriers"; ...
    "reused current-call invariant; not an offline answer cache"];
boundary = repmat( ...
    "analytical array storage only; not measured MATLAB peak memory", 3, 1);
output = table(quantity, bytes, scope, boundary);
end

function verifyFixedDimensions(cfg, protocol)
expected = [256, 2048, 513, 2047, 160, 97, 3083, 93];
actual = [cfg.numAntennas, cfg.numSubcarriers, ...
    protocol.r32.front.carrierCount, protocol.r32.music.carrierCount, ...
    protocol.r32.music.subarraySize, protocol.r32.music.numSubarrays, ...
    sum(protocol.r32.enhancedC.gridSizes.^2), ...
    sum(protocol.r32.music.gridSizes)];
if ~isequal(actual, expected)
    error("r33:ComplexityFixedConfigurationMismatch", ...
        "The complexity ledger only describes the frozen R32 configuration.");
end
end

function output = fixedConstants(cfg, protocol)
names = ["N"; "M"; "Q"; "K"; "L"; "P"; "G_C"; "G_A"];
values = [cfg.numAntennas; cfg.numSubcarriers; ...
    protocol.r32.front.carrierCount; protocol.r32.music.carrierCount; ...
    protocol.r32.music.subarraySize; protocol.r32.music.numSubarrays; ...
    sum(protocol.r32.enhancedC.gridSizes.^2); ...
    sum(protocol.r32.music.gridSizes)];
output = table(names, values, 'VariableNames', {'symbol', 'value'});
end

function output = componentFormulas()
component = ["spectral_front"; "direct_subspace_per_carrier"; ...
    "gram_subspace_per_carrier"; "single_target_music_search"];
order = ["O(E_s*N*Q + E_f*N*M)"; ...
    "O(P*L^2 + L^3)"; "O(L*P^2 + P^3 + L*P)"; "O(K*G*L)"];
boundary = ["E_s and E_f are actual response calls"; ...
    "covariance formation and full L-by-L EVD"; ...
    "P-by-P Gram EVD, vector recovery, with declared fallback"; ...
    "current one-signal-vector inner-product implementation"];
output = table(component, order, boundary);
end

function output = methodFormulas()
method = ["original_paper_full_structure"; "C_enhanced"; ...
    "P_A"; "C_public"];
publishedOrReference = [ ...
    "O(M + K_Z*(P_Z*L_Z^2 + L_Z^3 + G_Z*L_Z^2))"; ...
    "O(E_s*N*Q + E_f*N*M + K*P*L + K*P*L^2 + K*L^3 + K*G_C*L)"; ...
    "O(E_s*N*Q + (E_f+E_r)*N*M + K*P*L + K*P*L^2 + K*L^3 + K*G_A*L)"; ...
    "O(E_s*N*Q + E_f*N*M + K_p*P_p*L_p + K_p*P_p*L_p^2 + K_p*L_p^3 + K_p*G_p*L_p)"];
acceptedAOrder = ["not evaluated: K_Z and G_Z remain symbolic"; ...
    "same asymptotic order; q-only removes two unused N-by-M derivative arrays from pure scoring calls"; ...
    "same asymptotic order; q-only removes two unused N-by-M derivative arrays from pure scoring calls"; ...
    "same asymptotic order; q-only response path applies to the common front"];
attemptedGramOrder = ["not evaluated: K_Z and G_Z remain symbolic"; ...
    "O(E_s*N*Q + E_f*N*M + K*P*L + K*L*P^2 + K*P^3 + K*L*P + K*G_C*L)"; ...
    "O(E_s*N*Q + (E_f+E_r)*N*M + K*P*L + K*L*P^2 + K*P^3 + K*L*P + K*G_A*L)"; ...
