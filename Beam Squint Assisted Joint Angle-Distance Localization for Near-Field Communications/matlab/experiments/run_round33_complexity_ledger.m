function run_round33_complexity_ledger()
%RUN_ROUND33_COMPLEXITY_LEDGER Export symbolic and measured cost ledgers.

project = string(fileparts(fileparts(mfilename("fullpath"))));
addpath(project);
raw = r31.loadRound30Raw(project, IncludeBaselineResults=false);
[counts, inputIdentity, acceptance] = acceptedCounts(project, raw);
ledger = r33.complexityLedger(raw.pilot.expected.cfg, counts);
folder = fullfile(project, "results", "full_spectrum", ...
    "round33_equivalent_acceleration_v1", "complexity_ledger");
if ~isfolder(folder)
    mkdir(folder);
end
writetable(ledger.fixedConstants, fullfile(folder, "fixed_constants.csv"));
writetable(ledger.componentFormulas, fullfile(folder, ...
    "component_formulas.csv"));
writetable(ledger.methodFormulas, fullfile(folder, "method_formulas.csv"));
writetable(ledger.actualPerUser, fullfile(folder, ...
    "per_user_separate_operation_counts.csv"));
writetable(ledger.actualSummary, fullfile(folder, ...
    "operation_count_summary.csv"));
writetable(ledger.subspaceComparison, fullfile(folder, ...
    "direct_vs_gram_subspace_counts.csv"));
writetable(ledger.responseMemory, fullfile(folder, ...
    "response_memory_analytical.csv"));
writetable(ledger.ratioStatements, fullfile(folder, ...
    "ratio_interpretation_boundaries.csv"));
writetable(acceptance, fullfile(folder, ...
    "implementation_acceptance_status.csv"));
source = r33.manifest(project);
writetable(source, fullfile(folder, "source_hashes.csv"));
identity = struct(version="R33-theoretical-complexity-ledger-v1", ...
    sourceRegression=inputIdentity, ...
    countingRule="MAC-EVD-exp-sqrt-and-response-calls-remain-separate", ...
    originalKzGz="symbolic-not-imputed");
save(fullfile(folder, "result.mat"), "identity", "ledger", ...
    "source", "-v7.3");
fprintf("ROUND33_COMPLEXITY_LEDGER_COMPLETE users=%d\n", ...
    height(counts));
end

function [counts, inputIdentity, acceptance] = acceptedCounts(project, raw)
sixtyFile = fullfile(project, "results", "full_spectrum", ...
    "round33_equivalent_acceleration_v1", "sixty_user_equivalence", ...
    "result.mat");
if isfile(sixtyFile)
    input = load(sixtyFile, "identity", "counts");
    if input.identity.passed
        counts = input.counts;
        inputIdentity = input.identity.version;
        acceptance = table("AB_combined", true, ...
            "passed-existing-60-user-equivalence", ...
            'VariableNames', {'variant', 'accepted', 'reason'});
        return;
    end
end
v1File = fullfile(project, "results", "full_spectrum", ...
    "round33_equivalent_acceleration_v1", "nine_user_acceptance", ...
    "per_method_comparisons.csv");
v2File = fullfile(project, "results", "full_spectrum", ...
    "round33_equivalent_acceleration_v1", "nine_user_acceptance_v2", ...
    "result.mat");
if ~isfile(v1File) || ~isfile(v2File)
    error("r33:NineUserLedgerInputMissing", ...
        "The corrected nine-user acceptance and its call counts are required.");
end
v1 = readtable(v1File, TextType="string");
v2 = load(v2File, "variantPass", "identity");
a = v2.variantPass.variant == "A_response_invariants";
if nnz(a) ~= 1 || ~v2.variantPass.pass(a)
    error("r33:AcceptedAImplementationMissing", ...
        "No finite accepted implementation is available for the ledger.");
end
selected = v1.variant == "A_response_invariants" ...
    & v1.method == "P_A";
callRows = v1(selected, :);
protocol = r33.config();
K = protocol.r32.music.carrierCount;
L = protocol.r32.music.subarraySize;
P = protocol.r32.music.numSubarrays;
Kp = protocol.r32.publicC.carrierCount;
Lp = protocol.r32.publicC.subarraySize;
Pp = raw.pilot.expected.cfg.numAntennas-Lp+1;
n = height(callRows);
counts = table(callRows.seed, callRows.snrDb, ...
    callRows.sparseResponseCalls, callRows.frontFullResponseCalls, ...
    nan(n, 1), nan(n, 1), callRows.profileResponseCalls, ...
    repmat(sum(protocol.r32.enhancedC.gridSizes.^2), n, 1), ...
    repmat(sum(protocol.r32.music.gridSizes), n, 1), ...
    repmat(sum(protocol.r32.publicC.gridSizes.^2), n, 1), ...
    zeros(n, 1), zeros(n, 1), zeros(n, 1), zeros(n, 1), ...
    repmat(K*P*L^2, n, 1), repmat(K*L^3, n, 1), zeros(n, 1), ...
    repmat(Kp*Pp*Lp^2, n, 1), repmat(Kp*Lp^3, n, 1), ...
    zeros(n, 1), repmat("direct-L-by-L-EVD-accepted-A", n, 1), ...
    repmat("direct-L-by-L-EVD-public", n, 1), ...
    'VariableNames', {'seed', 'snrDb', 'Es', 'Ef', ...
    'frontDerivativeCalls', 'frontQOnlyCalls', 'Er', 'G_C', 'G_A', ...
    'G_public', 'enhancedFallbackCount', 'publicFallbackCount', ...
    'enhancedGramSuccessCount', 'publicGramSuccessCount', ...
    'enhancedMatrixFormationMacs', 'enhancedEvdCubicUnits', ...
    'enhancedRecoveryMacs', 'publicMatrixFormationMacs', ...
    'publicEvdCubicUnits', 'publicRecoveryMacs', ...
    'enhancedSolver', 'publicSolver'});
inputIdentity = v2.identity.version+"-accepted-A-counts-from-v1-execution";
acceptance = v2.variantPass(:, ["variant", "pass"]);
acceptance.Properties.VariableNames{2} = 'accepted';
acceptance.reason = ["passed-frozen-same-run-reference"; ...
    "failed-spectrum-score-tolerance"; ...
    "failed-because-Gram-component-failed"];
end
