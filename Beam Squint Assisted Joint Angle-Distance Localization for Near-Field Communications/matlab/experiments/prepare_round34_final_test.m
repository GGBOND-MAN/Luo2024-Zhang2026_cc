function prepare_round34_final_test()
%PREPARE_ROUND34_FINAL_TEST Bind the final code and keep it unauthorized.

project = string(fileparts(fileparts(mfilename("fullpath"))));
addpath(project);
protocol = r34.config();
verifyAcceptedR33(project, protocol);
inheritedFile = fullfile(project, "results", "full_spectrum", ...
    "round32_final_test_protocol_v1", "protocol.mat");
if ~isfile(inheritedFile)
    error("r34:MissingInheritedFinalDesign", ...
        "The frozen R32 final design is required.");
end
inherited = load(inheritedFile, "identity", "design");
design = inherited.design;
designHash = r32.designHash(design);
if designHash ~= protocol.finalTest.designHash ...
        || designHash ~= inherited.identity.designHash ...
        || height(design) ~= protocol.finalTest.expectedRows
    error("r34:InheritedFinalDesignDrift", ...
        "The inherited 1400-row final design has changed.");
end
source = r34.manifest(project);
sourceDigest = r32.sourceDigest(source);
identity = struct(version="R34-final-test-prepared-protocol-v1", ...
    protocol=protocol, designHash=designHash, ...
    sourceDigest=sourceDigest, ...
    inheritedDesignVersion=inherited.identity.version, ...
    estimatorVersion=protocol.estimatorVersion, ...
    statisticsVersion=protocol.statisticsVersion, ...
    orchestrationVersion=protocol.orchestrationVersion, ...
    preparedAt=string(datetime("now")), ...
    status="LOCKED-WAITING-FOR-EXPLICIT-USER-AUTHORIZATION", ...
    authorized=false, trialsExecuted=0, ...
    developmentInputsExcluded=true);
folder = fullfile(project, "results", "full_spectrum", ...
    "round34_final_test_protocol_v1");
if ~isfolder(folder)
    mkdir(folder);
end
authorizationFile = fullfile(folder, "FINAL_TEST_AUTHORIZATION.mat");
if isfile(authorizationFile)
    error("r34:UnexpectedAuthorizationFile", ...
        "Preparation refuses to overwrite or retain an authorization file.");
end
writetable(design, fullfile(folder, "frozen_design_1400.csv"));
writetable(source, fullfile(folder, "source_hashes.csv"));
save(fullfile(folder, "protocol.mat"), "identity", "design", ...
    "source", "-v7.3");
writelines([ ...
    "LOCKED: this preparation creates no authorization."; ...
    "Do not run either server command until the user explicitly authorizes."; ...
    "Future authorization command:"; ...
    "authorize_round34_final_test(""I_EXPLICITLY_AUTHORIZE_R34_FINAL_1400"")"; ...
    "Future server 1: run_round34_final_shard(1,2,NumWorkers=32,BatchSize=16,PoolType=""Threads"")"; ...
    "Future server 2: run_round34_final_shard(2,2,NumWorkers=32,BatchSize=16,PoolType=""Threads"")"; ...
    "Future aggregate: aggregate_round34_final_test(2)"], ...
    fullfile(folder, "FUTURE_COMMANDS_AFTER_APPROVAL.txt"));
fprintf("ROUND34_FINAL_TEST_PREPARED_LOCKED rows=%d trials=0\n", ...
    height(design));
end

function verifyAcceptedR33(project, protocol)
file = fullfile(project, "results", "full_spectrum", ...
    "round33_equivalent_acceleration_v1", ...
    "accepted_a_only_implementation", "identity.mat");
if ~isfile(file)
    error("r34:AcceptedR33IdentityMissing", ...
        "The accepted R33 A-only identity is required.");
end
saved = load(file, "identity");
currentR33Digest = r32.sourceDigest(r33.manifest(project));
if saved.identity.version ~= protocol.acceptedIdentity ...
        || saved.identity.implementation ~= protocol.estimatorVersion ...
        || saved.identity.sourceDigest ~= currentR33Digest
    error("r34:AcceptedR33IdentityMismatch", ...
        "The inherited A-only implementation identity or source has drifted.");
end
end
