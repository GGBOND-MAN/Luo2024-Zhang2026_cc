    "jThetaTheta", "jRangeRange", "jThetaRange", ...
    "normalizedCoupling", "effectiveInformationRatio", ...
    "rawStepDeg_G_fixed", "rawStepDeg_G_schur", ...
    "selectedStepDeg_G_fixed", "selectedStepDeg_G_schur", ...
    "stepDifferenceDeg", "rawStepDifferenceDeg", ...
    "accepted_G_fixed", "accepted_G_schur", ...
    "clipped_G_fixed", "clipped_G_schur", ...
    "boundary_G_fixed", "boundary_G_schur", ...
    "predictedReduction_G_fixed", "predictedReduction_G_schur", ...
    "actualReduction_G_fixed", "actualReduction_G_schur", ...
    "fallbackReason_G_fixed", "fallbackReason_G_schur"]);
end

function output = summarizeMechanism(perUser)
output = table();
for snrDb = [unique(perUser.snrDb).', nan]
    if isnan(snrDb)
        selected = true(height(perUser), 1);
        scope = "all-SNR";
    else
        selected = perUser.snrDb == snrDb;
        scope = "per-SNR";
    end
    output = [output; table(scope, snrDb, nnz(selected), ...
        mean(perUser.normalizedCoupling(selected)), ...
        median(perUser.normalizedCoupling(selected)), ...
        mean(abs(perUser.normalizedCoupling(selected))), ...
        mean(perUser.effectiveInformationRatio(selected)), ...
        mean(abs(perUser.stepDifferenceDeg(selected))), ...
        finiteCorrelation(perUser.selectedStepDeg_G_fixed(selected), ...
        perUser.selectedStepDeg_G_schur(selected)), ...
        nnz(abs(perUser.stepDifferenceDeg(selected)) > 1e-15), ...
        nnz(perUser.accepted_G_fixed(selected)), ...
        nnz(perUser.accepted_G_schur(selected)), ...
        nnz(perUser.clipped_G_fixed(selected)), ...
        nnz(perUser.clipped_G_schur(selected)), ...
        nnz(perUser.boundary_G_fixed(selected)), ...
        nnz(perUser.boundary_G_schur(selected)), ...
        mean(perUser.predictedReduction_G_schur(selected)), ...
        mean(perUser.actualReduction_G_schur(selected)), ...
        'VariableNames', {'scope', 'snrDb', 'n', ...
        'meanNormalizedCoupling', 'medianNormalizedCoupling', ...
        'meanAbsoluteNormalizedCoupling', ...
        'meanEffectiveInformationRatio', ...
        'meanAbsoluteSchurFixedStepDifferenceDeg', ...
        'fixedSchurStepCorrelation', 'changedStepCount', ...
        'fixedAcceptedCount', 'schurAcceptedCount', ...
        'fixedClippedCount', 'schurClippedCount', ...
        'fixedBoundaryCount', 'schurBoundaryCount', ...
        'meanSchurPredictedCostReduction', ...
        'meanSchurActualCostReduction'})]; %#ok<AGROW>
end
end

function output = rangeTransportTable(perUser)
base = perUser(:, ["seed", "trialIndex", "snrDb"]);
output = [variantRangeRows(base, perUser, "G_fixed"); ...
    variantRangeRows(base, perUser, "G_schur")];
end

function output = variantRangeRows(base, perUser, variant)
output = base;
output.variant = repmat(variant, height(base), 1);
output.arrayDeltaRangeRawM = perUser.("arrayDeltaRangeRaw_"+variant);
output.arrayDeltaRangeSelectedM = ...
    perUser.("arrayDeltaRangeSelected_"+variant);
output.qDeltaRangeRawM = perUser.("qDeltaRangeRaw_"+variant);
output.qDeltaRangeSelectedM = perUser.("qDeltaRangeSelected_"+variant);
output.qTransportSelected = perUser.("qTransportSelected_"+variant);
output.signAgreement = sign(output.arrayDeltaRangeRawM) ...
    == sign(output.qDeltaRangeRawM);
output.absoluteMagnitudeRatioArrayToQ = abs(output.arrayDeltaRangeRawM) ...
    ./max(abs(output.qDeltaRangeRawM), realmin);
end

function output = summarizeRangeTransport(perUser)
output = table();
for variant = ["G_fixed", "G_schur"]
    arrayStep = perUser.("arrayDeltaRangeRaw_"+variant);
    qStep = perUser.("qDeltaRangeRaw_"+variant);
    for snrDb = [unique(perUser.snrDb).', nan]
        if isnan(snrDb)
            selected = true(height(perUser), 1);
            scope = "all-SNR";
        else
            selected = perUser.snrDb == snrDb;
            scope = "per-SNR";
        end
        currentArray = arrayStep(selected);
        currentQ = qStep(selected);
        nonzero = abs(currentQ) > realmin;
        ratios = abs(currentArray(nonzero))./abs(currentQ(nonzero));
        output = [output; table(variant, scope, snrDb, nnz(selected), ...
            finiteCorrelation(currentArray, currentQ), ...
            mean(sign(currentArray) == sign(currentQ)), ...
            median(ratios, "omitnan"), mean(abs(currentArray)), ...
            mean(abs(currentQ)), ...
            nnz(sign(currentArray) ~= sign(currentQ)), ...
            'VariableNames', {'variant', 'scope', 'snrDb', 'n', ...
            'arrayQRangeStepCorrelation', 'signAgreementFraction', ...
            'medianAbsoluteMagnitudeRatioArrayToQ', ...
            'meanAbsoluteArrayStepM', 'meanAbsoluteQStepM', ...
            'signDisagreementCount'})]; %#ok<AGROW>
    end
end
end

function output = runtimeTable(perUser)
base = perUser(:, ["seed", "trialIndex", "snrDb", ...
    "runtime_P_A", "runtime_C_enhanced"]);
output = [variantRuntimeRows(base, perUser, "G_fixed"); ...
    variantRuntimeRows(base, perUser, "G_schur")];
end

function output = variantRuntimeRows(base, perUser, variant)
output = base;
output.variant = repmat(variant, height(base), 1);
output.contextSeconds = perUser.("contextSeconds_"+variant);
output.fullArrayLinearizationSeconds = ...
    perUser.("linearizationSeconds_"+variant);
output.safeguardSeconds = perUser.("safeguardSeconds_"+variant);
output.qTransportSeconds = perUser.("qTransportSeconds_"+variant);
output.incrementalSeconds = perUser.("incrementalSeconds_"+variant);
output.completeRuntimeSeconds = perUser.("runtime_"+variant);
output.runtimeRatioToPA = output.completeRuntimeSeconds./output.runtime_P_A;
output.runtimeRatioToC = output.completeRuntimeSeconds ...
    ./output.runtime_C_enhanced;
end

function output = engineeringGate(summary, aggregate, perUser, protocol, population)
output = table();
for snrDb = unique(summary.snrDb).'
    g = summary(summary.method == "G_schur" ...
        & summary.snrDb == snrDb, :);
    c = summary(summary.method == "C_enhanced" ...
        & summary.snrDb == snrDb, :);
    pa = summary(summary.method == "P_A" & summary.snrDb == snrDb, :);
    output = [output; gateRow(population, "A1", snrDb, ...
        g.angleMseDeg2/c.angleMseDeg2, ...
        protocol.gate.maximumPerSnrAngleMseRatioToC, true, "<=")]; %#ok<AGROW>
    output = [output; gateRow(population, "R1", snrDb, ...
        g.rangeMseM2/c.rangeMseM2, 1, true, "<")]; %#ok<AGROW>
    output = [output; gateRow(population, "R2", snrDb, ...
        g.rangeMseM2/pa.rangeMseM2, ...
        protocol.gate.maximumPerSnrRangeMseRatioToPA, true, "<=")]; %#ok<AGROW>
end
gAggregate = aggregate(aggregate.method == "G_schur", :);
cAggregate = aggregate(aggregate.method == "C_enhanced", :);
output = [output; gateRow(population, "A2", nan, ...
    gAggregate.angleMseDeg2/cAggregate.angleMseDeg2, ...
    protocol.gate.maximumEqualSnrAngleMseRatioToC, true, "<=")];
output = [output; gateRow(population, "C1", nan, ...
    mean(perUser.runtime_G_schur)/mean(perUser.runtime_C_enhanced), ...
    protocol.gate.maximumRuntimeRatioToC, true, "<=")];
profileDeviation = max(abs(perUser.profilePasses_G_schur ...
    -protocol.gate.requiredProfilePasses));
output = [output; gateRow(population, "Profile", nan, ...
    profileDeviation, 0, true, "<=")];
output = [output; gateRow(population, "Runtime-target", nan, ...
    mean(perUser.runtime_G_schur)/mean(perUser.runtime_P_A), ...
    protocol.gate.targetRuntimeRatioToPA, false, "<=")];
end

function row = gateRow(population, gate, snrDb, observed, limit, hard, op)
if op == "<"
    pass = observed < limit;
else
    pass = observed <= limit;
end
row = table(population, gate, snrDb, observed, limit, op, hard, pass, ...
    'VariableNames', {'population', 'gate', 'snrDb', ...
    'observedRatioOrDeviation', 'limit', 'operator', ...
    'hardGate', 'pass'});
end

function value = finiteCorrelation(first, second)
selected = isfinite(first) & isfinite(second);
first = first(selected);
second = second(selected);
if numel(first) < 2 || std(first) == 0 || std(second) == 0
    value = nan;
else
    matrix = corrcoef(first, second);
    value = matrix(1, 2);
end
end

function value = positionErrorM(theta, rangeM, truthTheta, truthRange)
xError = rangeM.*sind(theta)-truthRange.*sind(truthTheta);
yError = rangeM.*cosd(theta)-truthRange.*cosd(truthTheta);
value = hypot(xError, yError);
end

