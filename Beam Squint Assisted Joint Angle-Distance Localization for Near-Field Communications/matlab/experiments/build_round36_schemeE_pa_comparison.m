function output = build_round36_schemeE_pa_comparison()
%BUILD_ROUND36_SCHEMEE_PA_COMPARISON Build reporting-only comparison figures.

project = string(fileparts(fileparts(mfilename("fullpath"))));
addpath(project);
inputFolder = fullfile(project, "results", "full_spectrum", ...
    "round36_schemeE_calibration600_v1");
outputFolder = fullfile(inputFolder, "pa_comparison_v1");
if ~isfolder(outputFolder)
    mkdir(outputFolder);
end

loaded = load(fullfile(inputFolder, "result.mat"), ...
    "results", "identity");
perUser = readtable(fullfile(inputFolder, "per_user_outputs.csv"), ...
    TextType="string");
validateInput(loaded, perUser);

performance = performanceTable(perUser);
aggregate = aggregateTable(perUser);
complexity = complexityTable(loaded.results, perUser);
writetable(performance, fullfile(outputFolder, ...
    "performance_comparison.csv"));
writetable(aggregate, fullfile(outputFolder, ...
    "aggregate_performance_comparison.csv"));
writetable(complexity, fullfile(outputFolder, ...
    "complexity_comparison.csv"));

notice = "Calibration study – not R34 final confirmation";
files = strings(4, 1);
files(1) = performanceFigure(performance, "all600", ...
    "All 600 calibration rows", outputFolder, ...
    "PA_E_F1_all600_performance.png", notice);
files(2) = performanceFigure(performance, "holdout540", ...
    "Fixed holdout 540 rows", outputFolder, ...
    "PA_E_F2_holdout540_performance.png", notice);
files(3) = relativeChangeFigure(performance, outputFolder, notice);
files(4) = complexityFigure(complexity, outputFolder, notice);
figureManifest = table((1:4).', files, repmat(notice, 4, 1), ...
    'VariableNames', {'figureId', 'file', 'notice'});
writetable(figureManifest, fullfile(outputFolder, ...
    "figure_manifest.csv"));

identity = table("2026-09-12", loaded.identity.algorithmSourceDigest, ...
    loaded.identity.calibrationDataDigest, height(perUser), ...
    nnz(perUser.subset == "holdout540"), false, ...
    "P_A profile + Schur angle step + refreshed profile", notice, ...
    'VariableNames', {'date', 'algorithmDigest', 'dataDigest', ...
    'calibrationRowsRead', 'holdoutRowsRead', 'estimationExecuted', ...
    'schemeEStandaloneRuntimeDefinition', 'studyLabel'});
writetable(identity, fullfile(outputFolder, "comparison_identity.csv"));
source = fsjad.sourceHashManifest(project, ...
    "experiments/build_round36_schemeE_pa_comparison.m");
writetable(source, fullfile(outputFolder, "source_hash.csv"));

output = struct(version="R36-schemeE-PA-comparison-report-v1", ...
    date="2026-09-12", inputFolder=inputFolder, ...
    outputFolder=outputFolder, performance=performance, ...
    aggregate=aggregate, complexity=complexity, ...
    figureManifest=figureManifest, identity=identity, source=source);
save(fullfile(outputFolder, "comparison_result.mat"), ...
    "output", "-v7.3");
fprintf("R36_SCHEME_E_PA_COMPARISON_COMPLETE rows=%d figures=%d " + ...
    "estimation=0\n", height(perUser), height(figureManifest));
end

function validateInput(loaded, perUser)
requiredDigest = ...
    "27879e532e1ffefa1223a7a2ed56a6845ade09ed97e98f58ed56851436ba5908";
pass = loaded.identity.algorithmSourceDigest == requiredDigest ...
    && loaded.identity.calibrationUsersExecuted == 600 ...
    && loaded.identity.finalTrialsExecuted == 0 ...
    && loaded.identity.newUsersGenerated == 0 ...
    && height(perUser) == 600 ...
    && nnz(perUser.subset == "development-overlap60") == 60 ...
    && nnz(perUser.subset == "holdout540") == 540 ...
    && numel(loaded.results) == 600 ...
    && all(cellfun(@(x) x.success, loaded.results));
if ~pass
    error("r36:SchemeEPAComparisonInputMismatch", ...
        "The frozen Scheme E calibration input identity is invalid.");
end
end

function output = performanceTable(perUser)
populations = ["all600", "holdout540"];
snrValues = [-10, 0, 20];
output = table();
for population = populations
    populationMask = populationSelection(perUser, population);
    for snrDb = snrValues
        selected = populationMask & perUser.snrDb == snrDb;
        paAngleMse = mean((perUser.theta_P_A(selected) ...
            -perUser.truthThetaDeg(selected)).^2);
        eAngleMse = mean((perUser.theta_E(selected) ...
            -perUser.truthThetaDeg(selected)).^2);
        paRangeMse = mean((perUser.range_P_A(selected) ...
            -perUser.truthRangeM(selected)).^2);
        eRangeMse = mean((perUser.range_E(selected) ...
            -perUser.truthRangeM(selected)).^2);
        paPositionMse = positionMse(perUser.theta_P_A(selected), ...
            perUser.range_P_A(selected), ...
            perUser.truthThetaDeg(selected), ...
            perUser.truthRangeM(selected));
        ePositionMse = positionMse(perUser.theta_E(selected), ...
            perUser.range_E(selected), ...
            perUser.truthThetaDeg(selected), ...
            perUser.truthRangeM(selected));
        entry = table(population, snrDb, nnz(selected), ...
            sqrt(paAngleMse), sqrt(eAngleMse), ...
            eAngleMse/paAngleMse, ...
            100*(1-sqrt(eAngleMse/paAngleMse)), ...
            sqrt(paRangeMse), sqrt(eRangeMse), ...
            eRangeMse/paRangeMse, ...
            100*(sqrt(eRangeMse/paRangeMse)-1), ...
            sqrt(paPositionMse), sqrt(ePositionMse), ...
            100*(sqrt(ePositionMse/paPositionMse)-1), ...
            'VariableNames', {'population', 'snrDb', 'n', ...
            'angleRmsePA', 'angleRmseSchemeE', 'angleMseRatio', ...
            'angleRmseImprovementPercent', 'rangeRmsePA', ...
            'rangeRmseSchemeE', 'rangeMseRatio', ...
            'rangeRmseChangePercent', 'positionRmsePA', ...
            'positionRmseSchemeE', 'positionRmseChangePercent'});
        output = [output; entry]; %#ok<AGROW>
    end
end
end

function output = aggregateTable(perUser)
populations = ["all600", "holdout540"];
output = table();
for population = populations
    selected = populationSelection(perUser, population);
    current = perUser(selected, :);
    snrValues = unique(current.snrDb).';
    paAngleMse = zeros(numel(snrValues), 1);
    eAngleMse = zeros(numel(snrValues), 1);
    for index = 1:numel(snrValues)
        snrSelected = current.snrDb == snrValues(index);
        paAngleMse(index) = mean((current.theta_P_A(snrSelected) ...
            -current.truthThetaDeg(snrSelected)).^2);
        eAngleMse(index) = mean((current.theta_E(snrSelected) ...
            -current.truthThetaDeg(snrSelected)).^2);
    end
    paRangeMse = mean((current.range_P_A-current.truthRangeM).^2);
    eRangeMse = mean((current.range_E-current.truthRangeM).^2);
    paPositionMse = positionMse(current.theta_P_A, ...
        current.range_P_A, current.truthThetaDeg, current.truthRangeM);
    ePositionMse = positionMse(current.theta_E, ...
        current.range_E, current.truthThetaDeg, current.truthRangeM);
    angleRatio = mean(eAngleMse)/mean(paAngleMse);
    entry = table(population, height(current), ...
        sqrt(mean(paAngleMse)), sqrt(mean(eAngleMse)), angleRatio, ...
        100*(1-sqrt(angleRatio)), 100*(1-angleRatio), ...
        sqrt(paRangeMse), sqrt(eRangeMse), ...
        100*(sqrt(eRangeMse/paRangeMse)-1), ...
        sqrt(paPositionMse), sqrt(ePositionMse), ...
        100*(sqrt(ePositionMse/paPositionMse)-1), ...
        'VariableNames', {'population', 'n', ...
        'equalSnrAngleRmsePA', 'equalSnrAngleRmseSchemeE', ...
        'equalSnrAngleMseRatio', 'angleRmseImprovementPercent', ...
        'angleMseImprovementPercent', 'pooledRangeRmsePA', ...
        'pooledRangeRmseSchemeE', 'pooledRangeRmseChangePercent', ...
        'pooledPositionRmsePA', 'pooledPositionRmseSchemeE', ...
        'pooledPositionRmseChangePercent'});
    output = [output; entry]; %#ok<AGROW>
end
end

function output = complexityTable(results, perUser)
populations = ["all600", "holdout540"];
output = table();
for population = populations
    selected = populationSelection(perUser, population);
    current = results(selected);
    paRuntime = cellfun(@(x) x.P_A.runtimeSeconds, current);
    refinementSeconds = cellfun( ...
        @(x) x.E_one_step.refinementSeconds, current);
    newProfileSeconds = cellfun( ...
        @(x) x.E_one_step.profileSeconds, current);
    correctedERuntime = paRuntime+refinementSeconds+newProfileSeconds;
    paResponse = cellfun( ...
        @(x) x.P_A.responseEvaluationCount, current);
    reportedEResponse = cellfun( ...
        @(x) x.E_one_step.responseEvaluationCount, current);
    newProfileEvaluations = cellfun( ...
        @(x) x.profile.evaluationCount, current);
    baseResponse = reportedEResponse-newProfileEvaluations;
    firstProfileEvaluations = paResponse-baseResponse;
    correctedEResponse = paResponse+newProfileEvaluations;
    paMusic = cellfun(@(x) x.P_A.musicEvaluationCount, current);
    eMusic = cellfun(@(x) x.E_one_step.musicEvaluationCount, current);
    paEvd = cellfun(@(x) x.P_A.evdCount, current);
    eEvd = cellfun(@(x) x.E_one_step.evdCount, current);
    pa = complexityRow(population, "P_A", numel(current), ...
        mean(paRuntime), 1, mean(paResponse), 1, mean(paMusic), 1, ...
        mean(paEvd), 1, 1, mean(firstProfileEvaluations), 0, 0);
    schemeE = complexityRow(population, "Scheme_E", numel(current), ...
        mean(correctedERuntime), ...
        mean(correctedERuntime)/mean(paRuntime), ...
        mean(correctedEResponse), ...
        mean(correctedEResponse)/mean(paResponse), ...
        mean(eMusic), mean(eMusic)/mean(paMusic), ...
        mean(eEvd), mean(eEvd)/mean(paEvd), 2, ...
        mean(firstProfileEvaluations+newProfileEvaluations), ...
        mean(refinementSeconds), mean(newProfileSeconds));
    output = [output; pa; schemeE]; %#ok<AGROW>
end
end

function row = complexityRow(population, method, n, runtime, ...
    runtimeRatio, responses, responseRatio, music, musicRatio, evd, ...
    evdRatio, profilePasses, profileEvaluations, refinementSeconds, ...
    refreshedProfileSeconds)
row = table(population, method, n, runtime, runtimeRatio, responses, ...
    responseRatio, music, musicRatio, evd, evdRatio, profilePasses, ...
    profileEvaluations, refinementSeconds, refreshedProfileSeconds, ...
    'VariableNames', {'population', 'method', 'n', ...
    'meanStandaloneRuntimeSeconds', 'runtimeRatioToPA', ...
    'meanResponseEvaluationCount', 'responseRatioToPA', ...
    'meanAngleSubspaceEvaluationCount', ...
    'angleSubspaceEvaluationRatioToPA', 'meanDirectEvdCount', ...
    'directEvdRatioToPA', 'rangeProfilePassCount', ...
    'meanRangeProfileEvaluationCount', 'meanRefinementSeconds', ...
    'meanRefreshedProfileSeconds'});
end

function mask = populationSelection(perUser, population)
mask = true(height(perUser), 1);
if population == "holdout540"
    mask = perUser.subset == "holdout540";
end
end

function mse = positionMse(theta, rangeM, truthTheta, truthRange)
xError = rangeM.*sind(theta)-truthRange.*sind(truthTheta);
yError = rangeM.*cosd(theta)-truthRange.*cosd(truthTheta);
mse = mean(xError.^2+yError.^2);
end

function file = performanceFigure(performance, population, ...
    populationTitle, folder, name, notice)
rows = performance(performance.population == population, :);
labels = categorical(string(rows.snrDb), string(rows.snrDb));
fig = figure(Visible="off", Color="w", Position=[100 100 1050 480]);
tiledlayout(1, 2, TileSpacing="compact", Padding="compact");

nexttile;
angleValues = [rows.angleRmsePA, rows.angleRmseSchemeE];
bars = bar(labels, angleValues);
setBarColors(bars);
set(gca, YScale="log"); grid on;
ylim([0.7*min(angleValues, [], "all"), ...
    1.4*max(angleValues, [], "all")]);
xlabel("SNR (dB)"); ylabel("Angle RMSE (deg)");
title("Angle performance");
legend(["P_A", "Scheme E"], Location="best");

nexttile;
rangeValues = [rows.rangeRmsePA, rows.rangeRmseSchemeE];
bars = bar(labels, rangeValues);
setBarColors(bars);
set(gca, YScale="log"); grid on;
ylim([0.7*min(rangeValues, [], "all"), ...
    1.4*max(rangeValues, [], "all")]);
xlabel("SNR (dB)"); ylabel("Range RMSE (m)");
title("Range performance");
legend(["P_A", "Scheme E"], Location="best");

sgtitle("P_A versus Scheme E: "+populationTitle+newline+notice);
file = exportFigure(fig, folder, name);
end

function file = relativeChangeFigure(performance, folder, notice)
allRows = performance(performance.population == "all600", :);
holdoutRows = performance(performance.population == "holdout540", :);
labels = categorical(string(allRows.snrDb), string(allRows.snrDb));
fig = figure(Visible="off", Color="w", Position=[100 100 1050 480]);
tiledlayout(1, 2, TileSpacing="compact", Padding="compact");

nexttile;
bars = bar(labels, [allRows.angleRmseImprovementPercent, ...
    holdoutRows.angleRmseImprovementPercent]);
setBarColors(bars);
yline(0, "k--"); grid on;
xlabel("SNR (dB)"); ylabel("Angle RMSE improvement (%)");
title("Angle gain relative to P_A");
legend(["All 600", "Holdout 540"], Location="northwest");

nexttile;
bars = bar(labels, [allRows.rangeRmseChangePercent, ...
    holdoutRows.rangeRmseChangePercent]);
setBarColors(bars);
yline(0, "k--"); grid on;
xlabel("SNR (dB)"); ylabel("Range RMSE change (%)");
title("Range change relative to P_A");
legend(["All 600", "Holdout 540"], Location="northeast");

sgtitle("Relative performance change"+newline+notice);
file = exportFigure(fig, folder, "PA_E_F3_relative_changes.png");
end

function file = complexityFigure(complexity, folder, notice)
rows = complexity(complexity.population == "all600", :);
labels = categorical(["P_A", "Scheme E"], ["P_A", "Scheme E"]);
fig = figure(Visible="off", Color="w", Position=[100 100 1120 700]);
tiledlayout(2, 3, TileSpacing="compact", Padding="compact");
metricTile(labels, rows.meanStandaloneRuntimeSeconds, ...
    "Standalone runtime", "Seconds/user");
metricTile(labels, rows.meanResponseEvaluationCount, ...
    "Response evaluations", "Mean count/user");
metricTile(labels, rows.meanAngleSubspaceEvaluationCount, ...
    "Angle/subspace evaluations", "Mean count/user");
metricTile(labels, rows.meanDirectEvdCount, ...
    "Direct covariance EVD", "Mean count/user");
metricTile(labels, rows.rangeProfilePassCount, ...
    "Conditional range profiles", "Passes/user");
metricTile(labels, rows.meanRangeProfileEvaluationCount, ...
    "Range-profile evaluations", "Mean count/user");
sgtitle("Corrected standalone complexity: P_A versus Scheme E" ...
    +newline+notice);
file = exportFigure(fig, folder, "PA_E_F4_complexity.png");
end

function metricTile(labels, values, tileTitle, yLabel)
nexttile;
bars = bar(labels, values, FaceColor="flat");
bars.CData = [0 0.4470 0.7410; 0.8500 0.3250 0.0980];
ylabel(yLabel); title(tileTitle); grid on;
maximum = max(values);
if maximum <= 0
    maximum = 1;
end
ylim([0, 1.22*maximum]);
for index = 1:numel(values)
    text(index, values(index), sprintf(" %.4g", values(index)), ...
        HorizontalAlignment="center", VerticalAlignment="bottom");
end
end

function setBarColors(bars)
colors = [0 0.4470 0.7410; 0.8500 0.3250 0.0980];
for index = 1:min(numel(bars), size(colors, 1))
    bars(index).FaceColor = colors(index, :);
end
end

function file = exportFigure(fig, folder, name)
file = fullfile(folder, name);
exportgraphics(fig, file, Resolution=200);
close(fig);
end
