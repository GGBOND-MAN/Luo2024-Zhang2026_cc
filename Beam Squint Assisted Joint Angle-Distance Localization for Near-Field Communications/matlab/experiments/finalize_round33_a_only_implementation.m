function finalize_round33_a_only_implementation()
%FINALIZE_ROUND33_A_ONLY_IMPLEMENTATION Freeze the accepted finite variant.
% This records implementation identity only. It creates no final-test
% authorization and executes no new trial.

project = string(fileparts(fileparts(mfilename("fullpath"))));
addpath(project);
root = fullfile(project, "results", "full_spectrum", ...
    "round33_equivalent_acceleration_v1");
acceptanceFile = fullfile(root, "nine_user_acceptance_v2", "result.mat");
timingFile = fullfile(root, "complete_online_timing_a_only", "result.mat");
ledgerFile = fullfile(root, "complexity_ledger", "result.mat");
if ~isfile(acceptanceFile) || ~isfile(timingFile) || ~isfile(ledgerFile)
    error("r33:AOnlyFiniteEvidenceMissing", ...
        "Acceptance, timing, and complexity evidence must all exist.");
end
acceptance = load(acceptanceFile, "variantPass", "identity");
timing = load(timingFile, "identity", "summary", "comparisons", ...
    "environment");
ledger = load(ledgerFile, "identity", "ledger");
historicalTiming = loadHistoricalTiming(project);
a = acceptance.variantPass.variant == "A_response_invariants";
b = acceptance.variantPass.variant == "B_gram_subspace";
ab = acceptance.variantPass.variant == "AB_combined";
if nnz(a) ~= 1 || ~acceptance.variantPass.pass(a) ...
        || any(acceptance.variantPass.pass(b | ab))
    error("r33:UnexpectedFiniteAcceptanceState", ...
        "The final identity expects accepted A and rejected B/AB.");
end
if timing.identity.variant ~= "A_response_invariants"
    error("r33:WrongTimingVariant", ...
        "The timing evidence does not describe the accepted A variant.");
end
source = r33.manifest(project);
sourceDigest = r32.sourceDigest(source);
identity = struct( ...
    version="R33-A-equivalent-implementation-accepted-v1", ...
    statisticalMethodVersion="R32-PA-finite-closeout-v1", ...
    implementation="R33-A-q-only-invariants-direct-EVD-v1", ...
    acceptedScope="nine-existing-users-three-per-SNR-same-run-reference", ...
    numericalTolerance=acceptance.identity.protocol.validation, ...
    rejectedOptimization="smaller-Gram-subspace", ...
    rejectionReason="maximum-spectrum-score-difference-exceeded-1e-12", ...
    sourceDigest=sourceDigest, status="FINITE-IMPLEMENTATION-ACCEPTED", ...
    finalTestStatus="R32-design-remains-locked-and-unauthorized", ...
    newTrialsExecuted=0, finalTrialsExecuted=0, ...
    createdAt=string(datetime("now")));
folder = fullfile(root, "accepted_a_only_implementation");
if ~isfolder(folder)
    mkdir(folder);
end
writetable(source, fullfile(folder, "source_hashes.csv"));
writetable(acceptance.variantPass, fullfile(folder, ...
    "finite_acceptance_status.csv"));
writetable(timing.summary, fullfile(folder, "timing_summary.csv"));
writetable(timing.comparisons, fullfile(folder, "timing_comparisons.csv"));
historicalComparison = compareHistorical(timing.summary, historicalTiming);
writetable(historicalComparison, fullfile(folder, ...
    "r33_a_vs_r32_runtime.csv"));
save(fullfile(folder, "identity.mat"), "identity", "source", ...
    "acceptance", "timing", "ledger", "historicalTiming", ...
    "historicalComparison", "-v7.3");
assertNoAuthorization(project, root);
fprintf("ROUND33_A_ONLY_IMPLEMENTATION_FROZEN finalTrials=0\n");
end

function summary = loadHistoricalTiming(project)
file = fullfile(project, "results", "full_spectrum", ...
    "round32_pa_finite_closeout_v1", "complete_online_timing", ...
    "result.mat");
if ~isfile(file)
    error("r33:R32TimingMissing", ...
        "The historical R32 complete timing is required for comparison.");
end
data = load(file, "summary");
summary = data.summary;
end

function output = compareHistorical(current, historical)
methods = current.method;
output = table();
for method = methods.'
    newRow = current(current.method == method, :);
    oldRow = historical(historical.method == method, :);
    if height(newRow) ~= 1 || height(oldRow) ~= 1
        error("r33:TimingMethodIdentity", ...
            "Every timing method must have one old and one new summary row.");
    end
    output = [output; table(method, oldRow.mean_wallSeconds, ...
        newRow.mean_wallSeconds, ...
        100*(1-newRow.mean_wallSeconds/oldRow.mean_wallSeconds), ...
        oldRow.median_wallSeconds, newRow.median_wallSeconds, ...
        100*(1-newRow.median_wallSeconds/oldRow.median_wallSeconds), ...
        'VariableNames', {'method', 'r32MeanSeconds', 'r33MeanSeconds', ...
        'meanRuntimeReductionPercent', 'r32MedianSeconds', ...
        'r33MedianSeconds', 'medianRuntimeReductionPercent'})]; %#ok<AGROW>
end
end

function assertNoAuthorization(project, root)
files = [fullfile(root, "FINAL_TEST_AUTHORIZATION.mat"), ...
    fullfile(project, "results", "full_spectrum", ...
    "round33_final_test_candidate_protocol_v1", ...
    "FINAL_TEST_AUTHORIZATION.mat"), ...
    fullfile(project, "results", "full_spectrum", ...
    "round32_final_test_protocol_v1", "FINAL_TEST_AUTHORIZATION.mat")];
if any(isfile(files))
    error("r33:UnexpectedFinalAuthorization", ...
        "No final-test authorization may exist in this finite task.");
end
end
