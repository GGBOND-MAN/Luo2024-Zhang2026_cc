function run_round32_baseline_entry_regression()
%RUN_ROUND32_BASELINE_ENTRY_REGRESSION Check C and C_public identities.

project = string(fileparts(fileparts(mfilename("fullpath"))));
addpath(project);
raw = r31.loadRound30Raw(project);
protocol = r32.config();
cfg = raw.pilot.expected.cfg;
scan = fsjad.prepareScan(cfg);
snrValues = [-10, 0, 20];
summary = table();

for snrDb = snrValues
    rowIndex = find(raw.pilot.design.snrDb == snrDb, 1);
    row = raw.pilot.design(rowIndex, :);
    historical = raw.baselines.results{rowIndex, raw.l06BaselineIndex};
    replay = fsjad.replayRound27Data(cfg, scan, row);
    enhanced = r32.estimateC(cfg, replay.observation, ...
        replay.snapshots, scan, protocol);
    public = r32.estimatePublic(cfg, replay.observation, ...
        replay.snapshots, scan, protocol);
    enhancedDelta = [enhanced.estimate.thetaDeg ...
        - historical.enhancedBaseline.estimate.thetaDeg, ...
        enhanced.estimate.rangeM ...
        - historical.enhancedBaseline.estimate.rangeM];
    publicDelta = [public.estimate.thetaDeg ...
        - historical.publicBaseline.estimate.thetaDeg, ...
        public.estimate.rangeM ...
        - historical.publicBaseline.estimate.rangeM];
    enhancedPass = all(abs(enhancedDelta) <= [1e-10, 1e-10]);
    publicPass = all(abs(publicDelta) <= [1e-10, 1e-10]);
    if ~enhancedPass || ~publicPass
        error("r32:BaselineEntryRegression", ...
            "An independent baseline entry changed seed %.0f.", row.seed);
    end
    entry = table(row.seed, row.snrDb, enhancedDelta(1), ...
        enhancedDelta(2), publicDelta(1), publicDelta(2), ...
        enhanced.cost.totalOnlineSeconds, public.cost.totalOnlineSeconds, ...
        enhancedPass, publicPass, 'VariableNames', {'seed', 'snrDb', ...
        'enhancedThetaDeltaDeg', 'enhancedRangeDeltaM', ...
        'publicThetaDeltaDeg', 'publicRangeDeltaM', ...
        'enhancedOnlineSeconds', 'publicOnlineSeconds', ...
        'enhancedPass', 'publicPass'});
    summary = [summary; entry]; %#ok<AGROW>
end

folder = fullfile(project, "results", "full_spectrum", ...
    "round32_pa_finite_closeout_v1", "baseline_entry_regression");
if ~isfolder(folder)
    mkdir(folder);
end
writetable(summary, fullfile(folder, "first_user_each_snr.csv"));
source = r32.manifest(project);
writetable(source, fullfile(folder, "source_hashes.csv"));
identity = struct(version="R32-baseline-entry-regression-v1", ...
    protocol=protocol, pilotHash=raw.pilotHash, ...
    baselineHash=raw.baselineHash);
save(fullfile(folder, "result.mat"), "identity", "summary", ...
    "source", "-v7.3");
fprintf("ROUND32_BASELINE_ENTRY_REGRESSION_COMPLETE users=%d\n", ...
    height(summary));
end
