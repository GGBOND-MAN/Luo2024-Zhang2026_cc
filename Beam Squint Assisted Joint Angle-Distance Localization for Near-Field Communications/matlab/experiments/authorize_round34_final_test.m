function authorize_round34_final_test(approvalPhrase)
%AUTHORIZE_ROUND34_FINAL_TEST Create a future exact authorization token.
% This function is never called by preparation, tests, or preflight.

arguments
    approvalPhrase (1, 1) string
end

project = string(fileparts(fileparts(mfilename("fullpath"))));
addpath(project);
folder = fullfile(project, "results", "full_spectrum", ...
    "round34_final_test_protocol_v1");
file = fullfile(folder, "protocol.mat");
if ~isfile(file)
    error("r34:MissingFinalProtocol", ...
        "Run prepare_round34_final_test before any future authorization.");
end
saved = load(file, "identity", "design");
expected = saved.identity.protocol.finalTest.authorizationPhrase;
if approvalPhrase ~= expected
    error("r34:ExplicitApprovalPhraseRequired", ...
        "The exact explicit approval phrase is required.");
end
sourceDigest = r32.sourceDigest(r34.manifest(project));
if sourceDigest ~= saved.identity.sourceDigest ...
        || r32.designHash(saved.design) ~= saved.identity.designHash
    error("r34:FinalIdentityDriftBeforeAuthorization", ...
        "Source or design changed after review; prepare and review again.");
end
authorization = struct(approved=true, ...
    designHash=saved.identity.designHash, ...
    sourceDigest=saved.identity.sourceDigest, ...
    protocolVersion=saved.identity.protocol.version, ...
    estimatorVersion=saved.identity.protocol.estimatorVersion, ...
    statisticsVersion=saved.identity.protocol.statisticsVersion, ...
    approvedAt=string(datetime("now")), ...
    statement="user-explicitly-authorized-one-frozen-1400-trial-test");
save(fullfile(folder, "FINAL_TEST_AUTHORIZATION.mat"), "authorization");
fprintf("ROUND34_FINAL_TEST_AUTHORIZED design=%s\n", ...
    authorization.designHash);
end
