    "c1476d3b75078a841286bebf6e67812217dd689952b291b4a3213cd915018c5c", ...
    expectedPfaDigest= ...
    "f1483ec49bb59907a9b5b2f70aa95459f11277450a0bbcf715a43b3324439868", ...
    modifyFrozenMethods=false);

% Array-block gain models. The degree-1 (delay) phase direction is exactly
% collinear with the range score, so it is forbidden in every branch except
% the P_FACR_T falsification branch. See research/141 Theorems 1 and 3.
protocol.gain = struct( ...
    primaryModel="one-common-complex-beta", ...
    amplitudeModel="free-real-rho-per-carrier-plus-common-phase", ...
    dispersionModel="common-beta-plus-orthonormal-phase-degrees-2-3", ...
