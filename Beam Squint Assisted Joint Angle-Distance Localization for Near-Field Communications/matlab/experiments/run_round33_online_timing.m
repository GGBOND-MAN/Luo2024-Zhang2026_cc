function run_round33_online_timing(options)
%RUN_ROUND33_ONLINE_TIMING Fair complete timing of all optimized methods.

arguments
    options.Repetitions (1, 1) double {mustBeInteger, mustBePositive} = 3
    options.Variant (1, 1) string {mustBeMember(options.Variant, ...
        ["A_response_invariants", "AB_combined"])} = ...
        "A_response_invariants"
end

project = string(fileparts(fileparts(mfilename("fullpath"))));
addpath(project);
[useFastResponse, useGram, folderName, implementation] = ...
    requireVariantGate(project, options.Variant);
raw = r31.loadRound30Raw(project, IncludeBaselineResults=false);
protocol = r33.config();
cfg = raw.pilot.expected.cfg;
scanTimer = tic;
scan = fsjad.prepareScan(cfg);
scanPreparationSeconds = toc(scanTimer);
positions = raw.pilot.design(raw.pilot.design.snrDb ...
    == protocol.timing.snrDb, :);
positions = positions(1:protocol.timing.positionCount, :);
methods = protocol.timing.methods;
rows = table();
orderRows = table();

for positionIndex = 1:height(positions)
    replay = fsjad.replayRound27Data(cfg, scan, positions(positionIndex, :));
    for method = methods
        runMethod(method, cfg, replay, scan, protocol, ...
            useFastResponse, useGram); % unified warm-up
    end
    for repetition = 1:options.Repetitions
        shift = mod((positionIndex-1)*options.Repetitions ...
            + repetition-1, numel(methods));
        order = circshift(methods, -shift);
        for orderIndex = 1:numel(order)
            method = order(orderIndex);
            memoryBefore = memorySnapshot();
            wallTimer = tic;
            result = runMethod(method, cfg, replay, scan, protocol, ...
                useFastResponse, useGram);
            wallSeconds = toc(wallTimer);
            memoryAfter = memorySnapshot();
            rows = [rows; timingRow(result, method, cfg, protocol, ...
                positions(positionIndex, :), positionIndex, repetition, ...
                orderIndex, wallSeconds, memoryBefore, memoryAfter)]; %#ok<AGROW>
            orderRows = [orderRows; table(positionIndex, repetition, ...
                orderIndex, method)]; %#ok<AGROW>
        end
    end
end

summary = summarizeTiming(rows);
comparisons = timingComparisons(summary);
folder = fullfile(project, "results", "full_spectrum", ...
    "round33_equivalent_acceleration_v1", folderName);
if ~isfolder(folder)
    mkdir(folder);
end
writetable(rows, fullfile(folder, "raw_timing_rows.csv"));
writetable(orderRows, fullfile(folder, "execution_order.csv"));
writetable(summary, fullfile(folder, "timing_summary.csv"));
writetable(comparisons, fullfile(folder, "timing_comparisons.csv"));
source = r33.manifest(project);
writetable(source, fullfile(folder, "source_hashes.csv"));
environment = struct(matlabVersion=version, computer=computer, ...
    execution="sequential-single-MATLAB-process-no-parpool", ...
    warmupsPerMethodPerPosition=protocol.timing.warmupsPerMethod, ...
    repetitions=options.Repetitions, ...
    methodOrderPolicy=protocol.timing.orderPolicy, ...
    scanPreparationSeconds=scanPreparationSeconds, ...
    scanPreparationBoundary=protocol.timing.scanPreparation, ...
    zYReplayExcludedFromOnlineTiming=true, ...
    noSubspaceOrLocationAnswerCache=true, ...
    memoryColumns="process snapshots plus analytical working-set estimates", ...
    timestamp=string(datetime("now")));
identity = struct(version="R33-fair-complete-online-timing-v1", ...
    variant=options.Variant, implementation=implementation, ...
    protocol=protocol, positions=positions, pilotHash=raw.pilotHash);
save(fullfile(folder, "result.mat"), "identity", "rows", ...
    "orderRows", "summary", "comparisons", "environment", ...
    "source", "-v7.3");
fprintf("ROUND33_COMPLETE_ONLINE_TIMING_COMPLETE rows=%d\n", height(rows));
end

function [useFastResponse, useGram, folderName, implementation] = ...
    requireVariantGate(project, variant)
useFastResponse = true;
if variant == "A_response_invariants"
    file = fullfile(project, "results", "full_spectrum", ...
        "round33_equivalent_acceleration_v1", ...
        "nine_user_acceptance_v2", "result.mat");
    if ~isfile(file)
        error("r33:TimingAcceptanceGateMissing", ...
            "The corrected nine-user acceptance is required.");
    end
    data = load(file, "variantPass");
    selected = data.variantPass.variant == variant;
    if nnz(selected) ~= 1 || ~data.variantPass.pass(selected)
        error("r33:TimingAcceptanceGateFailed", ...
            "The response/invariant implementation did not pass.");
    end
    useGram = false;
    folderName = "complete_online_timing_a_only";
    implementation = "R33-A-q-only-invariants-direct-EVD-v1";
else
    file = fullfile(project, "results", "full_spectrum", ...
        "round33_equivalent_acceleration_v1", ...
        "sixty_user_equivalence", "result.mat");
    if ~isfile(file)
        error("r33:TimingEquivalenceGateMissing", ...
            "The 60-user combined equivalence result is required.");
    end
    data = load(file, "identity");
    if ~data.identity.passed
        error("r33:TimingEquivalenceGateFailed", ...
            "The combined implementation did not pass equivalence.");
    end
    useGram = true;
    folderName = "complete_online_timing_ab";
    implementation = "R33-AB-combined-equivalent-fast-v1";
end
end

function result = runMethod(method, cfg, replay, scan, protocol, ...
    useFastResponse, useGram)
result = r33.estimate(cfg, replay.observation, replay.snapshots, scan, ...
    method, protocol, UseFastResponse=useFastResponse, UseGram=useGram);
end

function row = timingRow(result, method, cfg, protocol, position, ...
    positionIndex, repetition, orderIndex, wallSeconds, before, after)
[K, L, P, G, angleHalfWidthDeg, rangeHalfWidthM] = ...
    methodConfiguration(result, method, cfg, protocol);
row = table(position.seed, position.snrDb, positionIndex, repetition, ...
    orderIndex, method, wallSeconds, result.cost.totalOnlineSeconds, ...
    result.cost.frontSeconds, result.cost.geometrySeconds, ...
    result.cost.alignmentSeconds, result.cost.subspaceSeconds, ...
    result.cost.searchSeconds, result.cost.profileSeconds, ...
    result.cost.sparseResponseCalls, ...
    result.cost.frontFullResponseCalls, ...
    result.cost.profileResponseCalls, ...
    result.cost.phaseAlignmentTerms, result.cost.matrixFormationMacs, ...
    result.cost.evdCubicUnits, result.cost.recoveryMacs, ...
    result.cost.fallbackCount, result.cost.gramSuccessCount, ...
    result.cost.directCount, K, L, P, G, cfg.numAntennas, ...
    cfg.numSubcarriers, protocol.r32.front.carrierCount, ...
    angleHalfWidthDeg, rangeHalfWidthM, "41/31/21", ...
    result.cost.responseContextBytes, ...
    result.cost.estimatedPersistentStateBytes, ...
    result.cost.estimatedPeakWorkingBytes, before, after, after-before, ...
    result.thetaDeg, result.rangeM, ...
    'VariableNames', {'seed', 'snrDb', 'positionIndex', 'repetition', ...
    'orderIndex', 'method', 'wallSeconds', 'reportedTotalSeconds', ...
    'frontSeconds', 'geometrySeconds', 'alignmentSeconds', ...
    'subspaceSeconds', 'angleOrJointSeconds', 'profileSeconds', ...
    'Es', 'Ef', 'Er', 'phaseAlignmentTerms', ...
    'subspaceMatrixFormationMacs', 'evdCubicUnits', 'recoveryMacs', ...
    'fallbackCount', 'gramSuccessCount', 'directCount', 'K', 'L', ...
    'P', 'G', 'N', 'M', 'Q', 'angleHalfWidthDeg', 'rangeHalfWidthM', ...
    'gridDescription', 'responseContextBytesEstimate', ...
    'persistentStateBytesEstimate', 'peakStateWorkingBytesEstimate', ...
    'matlabMemoryBeforeBytes', 'matlabMemoryAfterBytes', ...
    'matlabMemoryDeltaBytes', 'thetaDeg', 'rangeM'});
end

function [K, L, P, G, angleHalfWidthDeg, rangeHalfWidthM] = ...
    methodConfiguration(result, method, cfg, protocol)
K = numel(result.carrierIndex);
L = result.musicCfg.subarraySize;
P = cfg.numAntennas-L+1;
G = result.estimate.evaluationCount;
if method == "C_enhanced"
    angleHalfWidthDeg = protocol.r32.enhancedC.angleHalfWidthDeg;
    rangeHalfWidthM = protocol.r32.enhancedC.rangeHalfWidthM;
elseif method == "C_public"
    angleHalfWidthDeg = protocol.r32.publicC.angleHalfWidthDeg;
    rangeHalfWidthM = protocol.r32.publicC.rangeHalfWidthM;
else
    angleHalfWidthDeg = protocol.r32.music.angleHalfWidthDeg;
    if method == "P_A"
        rangeHalfWidthM = protocol.r32.profile.halfWidthM;
    else
        rangeHalfWidthM = 0;
    end
end
end

function bytes = memorySnapshot()
bytes = nan;
try
    usage = memory;
    if isfield(usage, "MemUsedMATLAB")
        bytes = usage.MemUsedMATLAB;
    end
catch
    % Memory snapshots are platform-dependent and remain NaN if unavailable.
end
end

function summary = summarizeTiming(rows)
metrics = ["wallSeconds", "reportedTotalSeconds", "frontSeconds", ...
    "geometrySeconds", "alignmentSeconds", "subspaceSeconds", ...
    "angleOrJointSeconds", "profileSeconds", ...
    "matlabMemoryDeltaBytes"];
summary = table();
for method = unique(rows.method, "stable").'
    selected = rows.method == method;
    values = zeros(1, 4*numel(metrics));
    names = strings(1, 4*numel(metrics));
    cursor = 1;
    for metric = metrics
        vector = rows.(metric)(selected);
        values(cursor:cursor+3) = [mean(vector, "omitnan"), ...
            median(vector, "omitnan"), std(vector, "omitnan"), ...
            max(vector, [], "omitnan")];
        names(cursor:cursor+3) = ["mean_"+metric, ...
            "median_"+metric, "std_"+metric, "max_"+metric];
        cursor = cursor+4;
    end
    entry = array2table(values, VariableNames=cellstr(names));
    entry = addvars(entry, method, nnz(selected), Before=1, ...
        NewVariableNames=["method", "n"]);
    summary = [summary; entry]; %#ok<AGROW>
end
end

function output = timingComparisons(summary)
pa = summary(summary.method == "P_A", :);
c = summary(summary.method == "C_enhanced", :);
public = summary(summary.method == "C_public", :);
quantity = ["P_A_vs_C_enhanced_mean_runtime_reduction_percent"; ...
    "P_A_vs_C_enhanced_median_runtime_reduction_percent"; ...
    "P_A_over_C_public_mean_runtime_ratio"; ...
    "P_A_over_C_public_median_runtime_ratio"];
value = [100*(1-pa.mean_wallSeconds/c.mean_wallSeconds); ...
    100*(1-pa.median_wallSeconds/c.median_wallSeconds); ...
    pa.mean_wallSeconds/public.mean_wallSeconds; ...
    pa.median_wallSeconds/public.median_wallSeconds];
interpretation = ["new R33 complete online timing; not the old 35.04%"; ...
    "new R33 complete online timing; robust location summary"; ...
    "transparent public-assumption baseline, not author source code"; ...
    "transparent public-assumption baseline, not author source code"];
output = table(quantity, value, interpretation);
end
