function output = preflight_round41_schemeG_final(mode)
%PREFLIGHT_ROUND41_SCHEMEG_FINAL Verify the locked framework without trials.

arguments
    mode (1, 1) string {mustBeMember(mode, ...
        ["pre-authorization", "authorized-execution"])} = "pre-authorization"
end

project = string(fileparts(fileparts(mfilename("fullpath"))));
r41.addPaths(project);
locations = r41.paths(project);
if isfolder(locations.executionFolder)
    error("r41:ExistingFinalResultDirectory", ...
        "The R41 final result directory already exists. " + ...
        "Stop and resolve it manually before authorization or trials.");
end
saved = r41.validateProtocolPackage(project);
if mode == "pre-authorization"
    if isfile(locations.authorizationFile)
        error("r41:UnexpectedAuthorizationDuringEmptyPreflight", ...
            "Pre-authorization preflight requires an empty authorization state.");
    end
    authorizationState = "absent-as-required";
else
    r41.assertAuthorized(locations.protocolFolder, saved.identity);
    authorizationState = "present-and-identity-matched";
end

files = [dir(fullfile(project, "+r41", "*.m")); ...
    dir(fullfile(project, "experiments", "*round41*.m")); ...
    dir(fullfile(project, "tests", "round41*.m"))];
static = table('Size', [0, 3], ...
    'VariableTypes', {'string', 'double', 'string'}, ...
    'VariableNames', {'file', 'line', 'message'});
for index = 1:numel(files)
    file = fullfile(files(index).folder, files(index).name);
    messages = checkcode(file, "-struct");
    for messageIndex = 1:numel(messages)
        entry = table(string(file), messages(messageIndex).line, ...
            string(messages(messageIndex).message), ...
            'VariableNames', static.Properties.VariableNames);
        static = [static; entry]; %#ok<AGROW>
    end
end
unitResults = runtests(fullfile(project, "tests", ...
    "round41ProtocolUnitTest.m"));
regressionResults = runtests(fullfile(project, "tests", ...
    "round41FrozenRegressionTest.m"));
fullRegressionResults = runtests(fullfile(project, "tests"));
unauthorizedRejection = unauthorizedProbe();
checkpointResume = checkpointProbe();
identity = struct( ...
    version="R41-final-framework-preflight-v1", mode=mode, ...
    authorizationState=authorizationState, authorized= ...
    mode == "authorized-execution", trialsExecuted=0, ...
    observationsGenerated=0, algorithmDigest=saved.identity.algorithmDigest, ...
    designHash=saved.identity.designHash, ...
    statisticsVersion=saved.identity.statisticsVersion, ...
    statisticsHash=saved.identity.statisticsHash, ...
    timestamp=string(datetime("now", "TimeZone", "Asia/Shanghai")));
if ~isfolder(locations.verificationFolder)
    mkdir(locations.verificationFolder);
end
writetable(static, fullfile(locations.verificationFolder, ...
    "code_analyzer.csv"));
save(fullfile(locations.verificationFolder, "result.mat"), ...
    "identity", "static", "unitResults", "regressionResults", ...
    "fullRegressionResults", "unauthorizedRejection", ...
    "checkpointResume", "-v7.3");
output = struct(identity=identity, static=static, ...
    unitResults=unitResults, regressionResults=regressionResults, ...
    fullRegressionResults=fullRegressionResults, ...
    unauthorizedRejection=unauthorizedRejection, ...
    checkpointResume=checkpointResume);
passed = all([unitResults.Passed]) ...
    && all([regressionResults.Passed]) ...
    && all([fullRegressionResults.Passed]) ...
    && isempty(static) && unauthorizedRejection && checkpointResume;
fprintf("ROUND41_PREFLIGHT mode=%s unit=%d regression=%d full=%d " + ...
    "analyzer=%d unauthorized=%d checkpoint=%d trials=0\n", mode, ...
    nnz([unitResults.Passed]), nnz([regressionResults.Passed]), ...
    nnz([fullRegressionResults.Passed]), height(static), ...
    unauthorizedRejection, checkpointResume);
assert(passed, "r41:PreflightFailed", ...
    "R41 final framework preflight did not pass every frozen check.");
end

function pass = unauthorizedProbe()
folder = string(tempname);
mkdir(folder);
cleanup = onCleanup(@() rmdir(folder, "s"));
identity = struct(protocolVersion="p", designHash="d", ...
    statisticsHash="s", sourceDigest="x", algorithmDigest="a", ...
    r33Digest="3", r34Digest="4", frozenDependencyDigest="f");
pass = false;
try
    r41.assertAuthorized(folder, identity);
catch exception
    pass = string(exception.identifier) == "r41:FinalTestNotAuthorized";
end
end

function pass = checkpointProbe()
folder = string(tempname);
mkdir(folder);
cleanup = onCleanup(@() rmdir(folder, "s"));
file = fullfile(folder, "checkpoint.mat");
design = table((1:4).', 'VariableNames', {'rowId'});
identity = struct(version="synthetic", designHash="d", ...
    statisticsHash="s", authorizationDigest="a");
results = cell(4, 1);
results{1} = struct(success=true, value=1);
environment = struct(role="synthetic-no-observation");
r41.saveCheckpoint(file, identity, design, results, environment);
[resumed, resumedEnvironment] = r41.loadCheckpoint( ...
    file, identity, design);
pass = ~isempty(resumed{1}) && all(cellfun(@isempty, resumed(2:4))) ...
    && isequaln(environment, resumedEnvironment);
end
