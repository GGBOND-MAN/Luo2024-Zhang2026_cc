function export_round31_diagnostics()
%EXPORT_ROUND31_DIAGNOSTICS Export per-user scores, boundaries, and costs.

project = string(fileparts(fileparts(mfilename("fullpath"))));
addpath(project);
folder = fullfile(project, "results", "full_spectrum", ...
    "round31_angle_controls_v2");
saved = load(fullfile(folder, "result.mat"), "identity", "results");
design = saved.identity.design;
diagnostics = table();
for index = 1:height(design)
    item = saved.results{index};
    cScore = max(item.controlC.estimate.spectrum, [], "all");
    row = table(item.seed, item.snrDb, cScore, ...
        item.angleA.score, item.profileA.score, ...
        item.angleB.score, item.profileB.score, ...
        item.angleA.evaluationCount, item.profileA.evaluationCount, ...
        item.angleB.evaluationCount, item.profileB.evaluationCount, ...
        item.controlC.estimate.initialThetaBoundary, ...
        item.controlC.estimate.initialRangeBoundary, ...
        item.controlC.estimate.finalThetaBoundary, ...
        item.controlC.estimate.finalRangeBoundary, ...
        item.angleA.finalEndpointHit, item.angleB.finalEndpointHit, ...
        item.profileA.endpointHit, item.profileA.nearBoundary, ...
        item.profileA.endpointOutwardTrend, ...
        item.profileB.endpointHit, item.profileB.nearBoundary, ...
        item.profileB.endpointOutwardTrend, ...
        item.profileA.retentionMargin, item.profileB.retentionMargin, ...
        numel(item.carrierA), numel(item.carrierB), ...
        item.checks.frontExactReuse, item.checks.carrierBSubsetA, ...
        item.checks.signalVectorColumnsExact, ...
        item.cost.frontHistoricalSeconds, item.cost.angleASeconds, ...
        item.cost.profileASeconds, item.cost.angleBSeconds, ...
        item.cost.profileBSeconds, item.experimentSessionSeconds, ...
        item.hash.observation, item.hash.snapshots, ...
        item.hash.frontSignalVectors, ...
        'VariableNames', {'seed', 'snrDb', 'controlCFinalScore', ...
        'angleAScore', 'profileAScore', 'angleBScore', 'profileBScore', ...
        'angleAEvaluations', 'profileAEvaluations', ...
        'angleBEvaluations', 'profileBEvaluations', ...
        'controlCInitialThetaBoundary', 'controlCInitialRangeBoundary', ...
        'controlCFinalThetaBoundary', 'controlCFinalRangeBoundary', ...
        'angleAFinalEndpointHit', 'angleBFinalEndpointHit', ...
        'profileAEndpointHit', 'profileANearBoundary', ...
        'profileAEndpointOutwardTrend', 'profileBEndpointHit', ...
        'profileBNearBoundary', 'profileBEndpointOutwardTrend', ...
        'profileARetentionMargin', 'profileBRetentionMargin', ...
        'carrierCountA', 'carrierCountB', 'frontExactReuse', ...
        'carrierBSubsetA', 'signalVectorColumnsExact', ...
        'frontHistoricalSeconds', 'angleAParallelSessionSeconds', ...
        'profileAParallelSessionSeconds', 'angleBParallelSessionSeconds', ...
        'profileBParallelSessionSeconds', 'experimentSessionSeconds', ...
        'observationHash', 'snapshotsHash', 'frontSignalVectorsHash'});
    diagnostics = [diagnostics; row]; %#ok<AGROW>
end

resourceSummary = table();
for snrDb = [-10, 0, 20]
    rows = diagnostics.snrDb == snrDb;
    entry = table(snrDb, nnz(rows), ...
        mean(diagnostics.experimentSessionSeconds(rows)), ...
        max(diagnostics.experimentSessionSeconds(rows)), ...
        mean(diagnostics.angleAParallelSessionSeconds(rows)), ...
        mean(diagnostics.profileAParallelSessionSeconds(rows)), ...
        mean(diagnostics.angleBParallelSessionSeconds(rows)), ...
        mean(diagnostics.profileBParallelSessionSeconds(rows)), ...
        'VariableNames', {'snrDb', 'n', ...
        'meanExperimentSessionSeconds', 'maxExperimentSessionSeconds', ...
        'meanAngleAParallelSessionSeconds', ...
        'meanProfileAParallelSessionSeconds', ...
        'meanAngleBParallelSessionSeconds', ...
        'meanProfileBParallelSessionSeconds'});
    resourceSummary = [resourceSummary; entry]; %#ok<AGROW>
end

writetable(design, fullfile(folder, "development_design.csv"));
writetable(diagnostics, fullfile(folder, "per_user_diagnostics.csv"));
writetable(resourceSummary, fullfile(folder, ...
    "parallel_session_resource_summary.csv"));
fprintf("ROUND31_DIAGNOSTICS_EXPORTED users=%d\n", height(diagnostics));
end
