function output = run_round38_schemeF_calibration600(options)
%RUN_ROUND38_SCHEMEF_CALIBRATION600 Run frozen Scheme F calibration.

arguments
    options.NumWorkers (1, 1) double {mustBeInteger, mustBePositive} = 8
    options.BatchSize (1, 1) double {mustBeInteger, mustBePositive} = 8
    options.PoolType (1, 1) string ...
        {mustBeMember(options.PoolType, ["Threads", "Processes"])} = "Threads"
end

project = string(fileparts(fileparts(mfilename("fullpath"))));
addpath(project);
addpath(fullfile(project, "+r38", "common"));
addpath(fullfile(project, "+r38", "schemeF"));
addpath(fullfile(project, "+r38", "calibration"));
commonProtocol = r38CommonProtocol();
calibrationProtocol = r38SchemeFCalibrationProtocol();
setup = r30.setup(project, "calibration600");
preflight = r38AssertSchemeFCalibration( ...
    project, setup, calibrationProtocol);
design = setup.design;
cfg = setup.cfg;
scan = fsjad.prepareScan(cfg);

algorithmSource = preflight.algorithmSource;
algorithmSourceDigest = preflight.algorithmDigest;
reportingSource = reportingManifest(project);
reportingSourceDigest = r32.sourceDigest(reportingSource);
frozenSource = frozenManifest(project);
frozenSourceDigest = r32.sourceDigest(frozenSource);
identity = struct(version=calibrationProtocol.version, ...
    date=calibrationProtocol.date, dataRole=calibrationProtocol.evidenceRole, ...
    studyLabel=calibrationProtocol.studyLabel, ...
    commonProtocol=commonProtocol, ...
    schemeProtocol=r38SchemeFConfig(), ...
    calibrationProtocol=calibrationProtocol, ...
    algorithmSourceDigest=algorithmSourceDigest, ...
    reportingSourceDigest=reportingSourceDigest, ...
    frozenReadOnlySourceDigest=frozenSourceDigest, ...
    developmentResultSha256=calibrationProtocol.development.resultSha256, ...
    r36CalibrationResultSha256= ...
    calibrationProtocol.calibration.r36ResultSha256, ...
    r37SingleProfileResultSha256= ...
    calibrationProtocol.calibration.r37ResultSha256, ...
    calibrationDataDigest=preflight.dataDigest, ...
    calibrationUsersAuthorized=calibrationProtocol.calibration.allUsers, ...
    calibrationUsersExecuted=0, developmentOverlapUsers= ...
    calibrationProtocol.development.requiredUsers, ...
    holdoutUsers=calibrationProtocol.calibration.holdoutUsers, ...
    finalTrialsReadOrExecuted=0, newUsersGenerated=0, ...
    baselineReestimated=false, eSingleReestimated=false, ...
    schemesExecuted="F-only");

folder = fullfile(project, "results", "full_spectrum", ...
    "round38_schemeF_raw_array_vpml_calibration600_v1");
if ~isfolder(folder)
    mkdir(folder);
end
checkpointFile = fullfile(folder, "checkpoint.mat");
results = cell(height(design), 1);
environment = struct();
if isfile(checkpointFile)
    saved = load(checkpointFile, "identity", "design", ...
        "results", "environment");
    if ~checkpointCompatible(saved.identity, identity) ...
            || ~isequaln(saved.design, design)
        error("r38:StaleSchemeFCalibrationCheckpoint", ...
            "The calibration checkpoint has a different frozen identity.");
    end
    results = saved.results;
    environment = saved.environment;
end

pool = [];
pending = find(cellfun(@isempty, results));
if ~isempty(pending)
    pool = preparePool(options.PoolType, options.NumWorkers);
    for first = 1:options.BatchSize:numel(pending)
        rows = pending(first:min(first+options.BatchSize-1, numel(pending)));
        rowDesign = design(rows, :);
        rowBaseline = preflight.r36Calibration.results(rows);
        batch = cell(numel(rows), 1);
        parfor index = 1:numel(rows)
            batch{index} = r38SchemeFTrial(cfg, scan, ...
                rowDesign(index, :), rowBaseline{index}, rows(index), ...
                r34.config(), r38SchemeFConfig());
        end
        results(rows) = batch;
        environment = environmentRecord(pool, options.BatchSize);
        save(checkpointFile, "identity", "design", "results", ...
            "environment", "-v7.3");
        fprintf("R38 SCHEME F CALIBRATION: %d/%d\n", ...
            nnz(~cellfun(@isempty, results)), height(design));
    end
end
if ~isempty(pool)
    environment = environmentRecord(pool, options.BatchSize);
    delete(pool);
end

failures = failureTable(design, results);
writeLabeled(failures, fullfile(folder, "failures.csv"), ...
    calibrationProtocol.studyLabel);
if height(failures) > 0
    save(fullfile(folder, "result.mat"), "identity", "design", ...
        "results", "failures", "environment", "algorithmSource", ...
        "reportingSource", "frozenSource", "-v7.3");
    error("r38:SchemeFCalibrationTrialFailure", ...
        "At least one frozen Scheme F calibration row failed.");
end

postflight = r38AssertSchemeFCalibration( ...
    project, setup, calibrationProtocol);
if postflight.algorithmDigest ~= algorithmSourceDigest ...
        || r32.sourceDigest(frozenManifest(project)) ~= frozenSourceDigest
    error("r38:CalibrationSourceDriftDuringRun", ...
        "A frozen reference or Scheme F source changed during execution.");
end
summary = r38SummarizeSchemeFCalibration(design, results, ...
    preflight.r37Calibration.summary.perUser, ...
    preflight.developmentMask, preflight.development.results, ...
    commonProtocol, calibrationProtocol);
writeSummaryTables(folder, summary, calibrationProtocol.studyLabel);
figureManifest = r38BuildSchemeFCalibrationFigures(summary, folder);
writetable(algorithmSource, fullfile(folder, ...
    "algorithm_source_hashes.csv"));
writetable(reportingSource, fullfile(folder, ...
    "reporting_source_hashes.csv"));
writetable(frozenSource, fullfile(folder, ...
    "frozen_readonly_source_hashes.csv"));

identity.calibrationUsersExecuted = height(design);
identity.completedUsers = height(design);
identity.all600GatePassed = summary.decision.all600GatePassed;
identity.holdout540GatePassed = summary.decision.holdout540GatePassed;
identity.developmentReproductionPassed = ...
    summary.decision.developmentReproductionPassed;
identity.calibrationReady = summary.calibrationReady;
save(checkpointFile, "identity", "design", "results", ...
    "environment", "-v7.3");
save(fullfile(folder, "result.mat"), "identity", "design", ...
    "results", "summary", "failures", "environment", ...
    "algorithmSource", "reportingSource", "frozenSource", ...
    "figureManifest", "-v7.3");
output = struct(identity=identity, summary=summary, folder=folder, ...
    figureManifest=figureManifest);
fprintf("ROUND38_SCHEME_F_CALIBRATION_COMPLETE users=%d all600=%d " + ...
    "holdout=%d reproduce=%d ready=%d final=0 new=0\n", ...
    height(design), summary.decision.all600GatePassed, ...
    summary.decision.holdout540GatePassed, ...
    summary.decision.developmentReproductionPassed, ...
    summary.calibrationReady);
end

function failures = failureTable(design, results)
failed = cellfun(@isempty, results);
for index = find(~failed).'
    failed(index) = ~results{index}.success;
end
failures = design(failed, ["seed", "trialIndex", "snrDb"]);
failures.errorIdentifier = strings(height(failures), 1);
failures.errorMessage = strings(height(failures), 1);
failedResults = results(failed);
for index = 1:numel(failedResults)
    if isempty(failedResults{index})
        failures.errorIdentifier(index) = "r38:MissingResult";
        failures.errorMessage(index) = "The required row was not produced.";
    else
        failures.errorIdentifier(index) = ...
            failedResults{index}.errorIdentifier;
        failures.errorMessage(index) = failedResults{index}.errorMessage;
    end
end
end

function writeSummaryTables(folder, summary, label)
writeLabeled(summary.perUser, fullfile(folder, ...
    "per_user_outputs.csv"), label);
writePopulation(folder, "all600", summary.all600, label);
writePopulation(folder, "holdout540", summary.holdout540, label);
writePopulation(folder, "development_overlap60", ...
    summary.developmentOverlap60, label);
writeLabeled(summary.reproduction, fullfile(folder, ...
    "development_reproduction.csv"), label);
writeLabeled(summary.gate, fullfile(folder, ...
    "engineering_gate.csv"), label);
writeLabeled(summary.decision, fullfile(folder, ...
    "calibration_decision.csv"), label);
end

function writePopulation(folder, suffix, population, label)
writeLabeled(population.methodSummary, fullfile(folder, ...
    "method_summary_"+suffix+".csv"), label);
writeLabeled(population.comparisons, fullfile(folder, ...
    "paired_comparisons_"+suffix+".csv"), label);
writeLabeled(population.tradeoff, fullfile(folder, ...
    "F_vs_E_single_tradeoff_"+suffix+".csv"), label);
writeLabeled(population.diagnostics, fullfile(folder, ...
    "vpml_diagnostics_"+suffix+".csv"), label);
end

function writeLabeled(input, file, label)
input.studyLabel = repmat(label, height(input), 1);
writetable(input, file);
end

function pool = preparePool(poolType, workers)
pool = gcp("nocreate");
requiredClass = "parallel.ThreadPool";
if poolType == "Processes"
    requiredClass = "parallel.ProcessPool";
end
if ~isempty(pool) && (pool.NumWorkers ~= workers ...
        || string(class(pool)) ~= requiredClass)
    delete(pool);
    pool = [];
end
if isempty(pool)
    pool = parpool(poolType, workers);
end
end

function environment = environmentRecord(pool, batchSize)
environment = struct(matlabVersion=version, computer=computer, ...
    workers=pool.NumWorkers, poolClass=class(pool), batchSize=batchSize, ...
    timestamp=string(datetime("now")));
end

function pass = checkpointCompatible(saved, current)
pass = saved.version == current.version ...
    && saved.algorithmSourceDigest == current.algorithmSourceDigest ...
    && saved.developmentResultSha256 ...
    == current.developmentResultSha256 ...
    && saved.r36CalibrationResultSha256 ...
    == current.r36CalibrationResultSha256 ...
    && saved.r37SingleProfileResultSha256 ...
    == current.r37SingleProfileResultSha256 ...
    && saved.calibrationDataDigest == current.calibrationDataDigest ...
    && saved.frozenReadOnlySourceDigest ...
    == current.frozenReadOnlySourceDigest ...
    && saved.calibrationUsersAuthorized ...
    == current.calibrationUsersAuthorized ...
    && saved.finalTrialsReadOrExecuted == 0 ...
    && saved.newUsersGenerated == 0 ...
    && ~saved.baselineReestimated ...
    && ~saved.eSingleReestimated ...
    && isequaln(saved.commonProtocol, current.commonProtocol) ...
    && isequaln(saved.schemeProtocol, current.schemeProtocol) ...
    && isequaln(saved.calibrationProtocol, current.calibrationProtocol);
end

function source = reportingManifest(project)
listing = [dir(fullfile(project, "+r38", "calibration", "*.m")); ...
    dir(fullfile(project, "experiments", ...
    "run_round38_schemeF_calibration600.m")); ...
    dir(fullfile(project, "tests", "round38*.m"))];
source = sourceFromListing(project, listing);
end

function source = frozenManifest(project)
listing = [dir(fullfile(project, "+r32", "**", "*.m")); ...
    dir(fullfile(project, "+r33", "**", "*.m")); ...
    dir(fullfile(project, "+r34", "**", "*.m")); ...
    dir(fullfile(project, "+r35", "**", "*.m")); ...
    dir(fullfile(project, "+r36", "**", "*.m")); ...
    dir(fullfile(project, "+r37", "**", "*.m"))];
source = sourceFromListing(project, listing);
end

function source = sourceFromListing(project, listing)
paths = strings(numel(listing), 1);
for index = 1:numel(listing)
    file = string(fullfile(listing(index).folder, listing(index).name));
    paths(index) = replace(extractAfter(file, strlength(project)+1), ...
        string(filesep), "/");
end
source = fsjad.sourceHashManifest(project, sort(unique(paths)));
end
