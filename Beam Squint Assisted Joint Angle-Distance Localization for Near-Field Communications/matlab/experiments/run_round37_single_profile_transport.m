function output = run_round37_single_profile_transport(options)
%RUN_ROUND37_SINGLE_PROFILE_TRANSPORT Validate implicit range transport.

arguments
    options.NumWorkers (1, 1) double {mustBeInteger, mustBePositive} = 8
    options.BatchSize (1, 1) double {mustBeInteger, mustBePositive} = 16
    options.PoolType (1, 1) string ...
        {mustBeMember(options.PoolType, ["Threads", "Processes"])} = "Threads"
end

project = string(fileparts(fileparts(mfilename("fullpath"))));
addpath(project);
addpath(fullfile(project, "+r36", "common"));
addpath(fullfile(project, "+r37", "singleProfile"));
protocol = r37SingleProfileProtocol();
inputFile = fullfile(project, "results", "full_spectrum", ...
    "round36_schemeE_calibration600_v1", "result.mat");
loaded = load(inputFile, "identity", "design", "results", "summary");
setup = r30.setup(project, "calibration600");
[developmentMask, frozenSource] = validateFrozenInput( ...
    project, inputFile, loaded, setup, protocol);
cfg = setup.cfg;
scan = fsjad.prepareScan(cfg);

algorithmSource = algorithmManifest(project);
algorithmDigest = r32.sourceDigest(algorithmSource);
reportingSource = reportingManifest(project);
reportingDigest = r32.sourceDigest(reportingSource);
frozenSourceDigest = r32.sourceDigest(frozenSource);
identity = struct(version=protocol.version, date=protocol.date, ...
    dataRole=protocol.evidenceRole, studyLabel=protocol.studyLabel, ...
    protocol=protocol, inputR36ResultSha256=protocol.input.r36ResultSha256, ...
    inputR36AlgorithmDigest=loaded.identity.algorithmSourceDigest, ...
    calibrationDataDigest=loaded.identity.calibrationDataDigest, ...
    algorithmSourceDigest=algorithmDigest, ...
    reportingSourceDigest=reportingDigest, ...
    frozenReadOnlySourceDigest=frozenSourceDigest, ...
    frozenBaselineRowsRead=height(loaded.design), ...
    transportRowsExecuted=0, completedRows=0, ...
    developmentOverlapRows=nnz(developmentMask), ...
    holdoutRows=nnz(~developmentMask), newUsersGenerated=0, ...
    r34FinalReadOrExecuted=false, r34FinalTrialsExecuted=0, ...
    baselineReestimated=false, schemeBOrDExecuted=false, ...
    secondCompleteProfileExecuted=false);

folder = fullfile(project, "results", "full_spectrum", ...
    "round37_schemeE_single_profile_transport_v1");
if ~isfolder(folder)
    mkdir(folder);
end
checkpointFile = fullfile(folder, "checkpoint.mat");
transportResults = cell(height(loaded.design), 1);
environment = struct();
if isfile(checkpointFile)
    saved = load(checkpointFile, "identity", "design", ...
        "transportResults", "environment");
    if ~checkpointCompatible(saved.identity, identity) ...
            || ~isequaln(saved.design, loaded.design)
        error("r37:StaleSingleProfileCheckpoint", ...
            "The R37 checkpoint has a different frozen identity.");
    end
    transportResults = saved.transportResults;
    environment = saved.environment;
end

pool = [];
pending = find(cellfun(@isempty, transportResults));
if ~isempty(pending)
    pool = preparePool(options.PoolType, options.NumWorkers);
    for first = 1:options.BatchSize:numel(pending)
        rows = pending(first:min(first+options.BatchSize-1, numel(pending)));
        rowDesign = loaded.design(rows, :);
        rowBaseline = loaded.results(rows);
        batch = cell(numel(rows), 1);
        parfor index = 1:numel(rows)
            batch{index} = transportTrial(cfg, scan, rowDesign(index, :), ...
                rowBaseline{index}, rows(index), protocol);
        end
        transportResults(rows) = batch;
        environment = environmentRecord(pool, options.BatchSize);
        design = loaded.design; %#ok<NASGU>
        save(checkpointFile, "identity", "design", ...
            "transportResults", "environment", "-v7.3");
        fprintf("R37 SINGLE PROFILE: %d/%d\n", ...
            nnz(~cellfun(@isempty, transportResults)), height(loaded.design));
    end
end
if ~isempty(pool)
    environment = environmentRecord(pool, options.BatchSize);
    delete(pool);
end

failures = failureTable(loaded.design, transportResults);
writetable(failures, fullfile(folder, "failures.csv"));
if height(failures) > 0
    design = loaded.design; %#ok<NASGU>
    baselineResults = loaded.results; %#ok<NASGU>
    save(fullfile(folder, "result.mat"), "identity", "design", ...
        "baselineResults", "transportResults", "failures", ...
        "environment", "algorithmSource", "reportingSource", ...
        "frozenSource", "-v7.3");
    error("r37:SingleProfileTrialFailure", ...
        "At least one R37 transport row failed.");
end

postFrozenSource = frozenManifest(project);
if r32.sourceDigest(postFrozenSource) ~= frozenSourceDigest ...
        || r32.sourceDigest(algorithmManifest(project)) ~= algorithmDigest
    error("r37:SourceDriftDuringRun", ...
        "A frozen or R37 algorithm source changed during execution.");
end
summary = r37SummarizeSingleProfile(loaded.design, loaded.results, ...
    transportResults, developmentMask, protocol);
writeSummaryTables(folder, summary, protocol.studyLabel);
figureManifest = r37BuildSingleProfileFigures(summary, folder);
writetable(figureManifest, fullfile(folder, "figure_manifest.csv"));
writetable(algorithmSource, fullfile(folder, ...
    "algorithm_source_hashes.csv"));
writetable(reportingSource, fullfile(folder, ...
    "reporting_source_hashes.csv"));
writetable(frozenSource, fullfile(folder, ...
    "frozen_readonly_source_hashes.csv"));

identity.transportRowsExecuted = height(loaded.design);
identity.completedRows = height(loaded.design);
identity.all600GatePassed = summary.decision.all600GatePassed;
identity.holdout540GatePassed = summary.decision.holdout540GatePassed;
identity.engineeringPassed = summary.engineeringPassed;
design = loaded.design; %#ok<NASGU>
baselineResults = loaded.results; %#ok<NASGU>
save(checkpointFile, "identity", "design", "transportResults", ...
    "environment", "-v7.3");
save(fullfile(folder, "result.mat"), "identity", "design", ...
    "baselineResults", "transportResults", "summary", "failures", ...
    "environment", "algorithmSource", "reportingSource", ...
    "frozenSource", "figureManifest", "-v7.3");
output = struct(identity=identity, summary=summary, folder=folder, ...
    figureManifest=figureManifest);
fprintf("ROUND37_SINGLE_PROFILE_COMPLETE rows=%d all600=%d " + ...
    "holdout=%d pass=%d profiles=1 final=0 new=0 B_D=0\n", ...
    height(design), summary.decision.all600GatePassed, ...
    summary.decision.holdout540GatePassed, summary.engineeringPassed);
end

function result = transportTrial(cfg, scan, row, baseline, rowIndex, protocol)
result = struct(success=false, rowIndex=rowIndex, seed=row.seed, ...
    trialIndex=row.trialIndex, snrDb=row.snrDb, errorIdentifier="", ...
    errorMessage="");
try
    replay = r37ReplayCalibrationObservation(cfg, scan, row);
    transport = r37ImplicitProfileTransport(cfg, scan, ...
        replay.observation, baseline.P_A.thetaDeg, baseline.P_A.rangeM, ...
        baseline.E_one_step.thetaDeg, baseline.frontRangeM, protocol);
    if abs(transport.thetaDeg-baseline.E_one_step.thetaDeg) ...
            > protocol.angle.thetaToleranceDeg
        error("r37:FrozenAngleIdentityFailure", ...
            "The R37 angle differs from frozen Scheme E.");
    end
    result.success = true;
    result.transport = transport;
catch exception
    result.errorIdentifier = string(exception.identifier);
    result.errorMessage = string(getReport( ...
        exception, "extended", "hyperlinks", "off"));
end
end

function [developmentMask, source] = validateFrozenInput( ...
    project, inputFile, loaded, setup, protocol)
relative = replace(extractAfter(inputFile, strlength(project)+1), ...
    string(filesep), "/");
inputHash = fsjad.sourceHashManifest(project, relative);
counts = groupcounts(loaded.design, "snrDb");
developmentMask = loaded.summary.perUser.subset ...
    == "development-overlap60";
holdoutCounts = groupcounts(loaded.design(~developmentMask, :), "snrDb");
identityPass = inputHash.sha256 == protocol.input.r36ResultSha256 ...
    && loaded.identity.algorithmSourceDigest ...
    == protocol.input.r36AlgorithmDigest ...
    && loaded.identity.calibrationDataDigest ...
    == protocol.input.calibrationDataDigest ...
    && loaded.identity.calibrationUsersExecuted == protocol.input.allUsers ...
    && loaded.identity.finalTrialsExecuted == 0 ...
    && loaded.identity.newUsersGenerated == 0 ...
    && loaded.identity.calibrationReady ...
    && height(loaded.design) == protocol.input.allUsers ...
    && numel(loaded.results) == protocol.input.allUsers ...
    && all(cellfun(@(x) x.success, loaded.results)) ...
    && isequaln(loaded.design, setup.design) ...
    && isequal(sort(counts.snrDb).', sort(protocol.input.snrDb)) ...
    && all(counts.GroupCount == protocol.input.usersPerSnr) ...
    && nnz(developmentMask) == protocol.input.developmentOverlapUsers ...
    && nnz(~developmentMask) == protocol.input.holdoutUsers ...
    && all(holdoutCounts.GroupCount == protocol.input.holdoutUsersPerSnr) ...
    && isequal(loaded.summary.perUser.seed, loaded.design.seed);
if ~identityPass
    error("r37:FrozenInputMismatch", ...
        "The R36 result or existing calibration identity is invalid.");
end
r36AssertCommonProtocol(setup.cfg, r36CommonProtocol());
r34Protocol = r34.config();
if r34Protocol.r32.profile.halfWidthM ~= protocol.profile.halfWidthM ...
        || r34Protocol.r32.profile.lambda ~= protocol.profile.lambda
    error("r37:FrozenProfileMismatch", ...
        "R37 does not match the frozen P_A profile.");
end
source = frozenManifest(project);
end

function failures = failureTable(design, results)
failed = cellfun(@isempty, results);
for index = find(~failed).'
    failed(index) = ~results{index}.success;
end
failures = design(failed, ["seed", "trialIndex", "snrDb"]);
failures.errorIdentifier = strings(height(failures), 1);
failures.errorMessage = strings(height(failures), 1);
failedResults = results(failed);
for index = 1:numel(failedResults)
    if isempty(failedResults{index})
        failures.errorIdentifier(index) = "r37:MissingResult";
        failures.errorMessage(index) = "The required row was not produced.";
    else
        failures.errorIdentifier(index) = ...
            failedResults{index}.errorIdentifier;
        failures.errorMessage(index) = failedResults{index}.errorMessage;
    end
end
end

function writeSummaryTables(folder, summary, label)
writeLabeled(summary.perUser, fullfile(folder, "per_user_outputs.csv"), label);
writePopulation(folder, "all600", summary.all600, label);
writePopulation(folder, "holdout540", summary.holdout540, label);
writePopulation(folder, "development_overlap60", ...
    summary.developmentOverlap60, label);
writeLabeled(summary.gate, fullfile(folder, "engineering_gate.csv"), label);
writeLabeled(summary.decision, fullfile(folder, ...
    "engineering_decision.csv"), label);
end

function writePopulation(folder, suffix, population, label)
writeLabeled(population.methodSummary, fullfile(folder, ...
    "method_summary_"+suffix+".csv"), label);
writeLabeled(population.angleComparisons, fullfile(folder, ...
    "paired_angle_comparisons_"+suffix+".csv"), label);
writeLabeled(population.rangeComparisons, fullfile(folder, ...
    "range_comparisons_"+suffix+".csv"), label);
writeLabeled(population.diagnostics, fullfile(folder, ...
    "transport_diagnostics_"+suffix+".csv"), label);
end

function writeLabeled(input, file, label)
input.studyLabel = repmat(label, height(input), 1);
writetable(input, file);
end

function pool = preparePool(poolType, workers)
pool = gcp("nocreate");
requiredClass = "parallel.ThreadPool";
if poolType == "Processes"
    requiredClass = "parallel.ProcessPool";
end
if ~isempty(pool) && (pool.NumWorkers ~= workers ...
        || string(class(pool)) ~= requiredClass)
    delete(pool);
    pool = [];
end
if isempty(pool)
    pool = parpool(poolType, workers);
end
end

function environment = environmentRecord(pool, batchSize)
environment = struct(matlabVersion=version, computer=computer, ...
    workers=pool.NumWorkers, poolClass=class(pool), batchSize=batchSize, ...
    timestamp=string(datetime("now")));
end

function pass = checkpointCompatible(saved, current)
pass = saved.version == current.version ...
    && saved.inputR36ResultSha256 == current.inputR36ResultSha256 ...
    && saved.inputR36AlgorithmDigest == current.inputR36AlgorithmDigest ...
    && saved.calibrationDataDigest == current.calibrationDataDigest ...
    && saved.algorithmSourceDigest == current.algorithmSourceDigest ...
    && saved.frozenReadOnlySourceDigest ...
    == current.frozenReadOnlySourceDigest ...
    && saved.newUsersGenerated == 0 ...
    && ~saved.r34FinalReadOrExecuted ...
    && saved.r34FinalTrialsExecuted == 0 ...
    && ~saved.baselineReestimated ...
    && ~saved.schemeBOrDExecuted ...
    && ~saved.secondCompleteProfileExecuted ...
    && isequaln(saved.protocol, current.protocol);
end

function source = algorithmManifest(project)
paths = ["+r37/singleProfile/r37SingleProfileProtocol.m"; ...
    "+r37/singleProfile/r37ReplayCalibrationObservation.m"; ...
    "+r37/singleProfile/r37ExactProfileLogDerivatives.m"; ...
    "+r37/singleProfile/r37ImplicitProfileTransport.m"];
source = fsjad.sourceHashManifest(project, paths);
end

function source = reportingManifest(project)
listing = [dir(fullfile(project, "+r37", "**", "*.m")); ...
    dir(fullfile(project, "experiments", ...
    "run_round37_single_profile_transport.m")); ...
    dir(fullfile(project, "tests", "round37*.m"))];
source = sourceFromListing(project, listing);
end

function source = frozenManifest(project)
listing = [dir(fullfile(project, "+r32", "**", "*.m")); ...
    dir(fullfile(project, "+r33", "**", "*.m")); ...
    dir(fullfile(project, "+r34", "**", "*.m")); ...
    dir(fullfile(project, "+r35", "**", "*.m")); ...
    dir(fullfile(project, "+r36", "**", "*.m"))];
source = sourceFromListing(project, listing);
end

function source = sourceFromListing(project, listing)
paths = strings(numel(listing), 1);
for index = 1:numel(listing)
    file = string(fullfile(listing(index).folder, listing(index).name));
    paths(index) = replace(extractAfter(file, strlength(project)+1), ...
        string(filesep), "/");
end
source = fsjad.sourceHashManifest(project, sort(unique(paths)));
end
