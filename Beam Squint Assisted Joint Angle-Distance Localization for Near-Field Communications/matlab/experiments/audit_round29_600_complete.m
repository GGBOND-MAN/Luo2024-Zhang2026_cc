function audit_round29_600_complete(options)
%AUDIT_ROUND29_600_COMPLETE Independently validate the downloaded aggregate.

arguments
    options.ResultRoot (1, 1) string = ""
end

project = string(fileparts(fileparts(mfilename("fullpath"))));
workspace = string(fileparts(fileparts(project)));
if options.ResultRoot == ""
    options.ResultRoot = fullfile(workspace, "server_packages", ...
        "round29_reference_upload_20260908_084238", "matlab", ...
        "results", "full_spectrum", "round29_calibration600_v1");
end
aggregateFolder = fullfile(options.ResultRoot, "aggregate");
acceptance = load(fullfile(aggregateFolder, "acceptance.mat"));
methods = readtable(fullfile(aggregateFolder, "method_summary.csv"), ...
    TextType="string");
paired = readtable(fullfile(aggregateFolder, "paired_summary.csv"), ...
    TextType="string");
resources = readtable(fullfile(aggregateFolder, "resources.csv"), ...
    TextType="string");
boundaries = readtable(fullfile(aggregateFolder, "boundary_and_cost.csv"), ...
    TextType="string");
seeds = readtable(fullfile(aggregateFolder, "seed_list.csv"), TextType="string");
failed = readtable(fullfile(aggregateFolder, "failed_rows.csv"), TextType="string");
source = readtable(fullfile(aggregateFolder, "source_hashes.csv"), TextType="string");

shardSource = cell(2, 1);
shardFailed = zeros(2, 1);
for shard = 1:2
    folder = fullfile(options.ResultRoot, sprintf("shard_%02d_of_02", shard));
    marker = load(fullfile(folder, "COMPLETE.mat"));
    shardFailed(shard) = nnz(marker.failed);
    shardSource{shard} = readtable(fullfile(folder, "source_hashes.csv"), ...
        TextType="string");
end
checks = struct(accepted=acceptance.accepted, seedRows=height(seeds), ...
    uniqueSeeds=numel(unique(seeds.seed)), failedRows=height(failed), ...
    methodRows=height(methods), pairedRows=height(paired), ...
    resourceRows=height(resources), boundaryRows=height(boundaries), ...
    shardFailed=shardFailed, ...
    sourceMatchesShard1=isequaln(source, shardSource{1}), ...
    sourceMatchesShard2=isequaln(source, shardSource{2}), ...
    snrCounts=[nnz(seeds.snrDb == -10), nnz(seeds.snrDb == 0), ...
    nnz(seeds.snrDb == 20)]);
checks.complete = checks.accepted && checks.seedRows == 600 ...
    && checks.uniqueSeeds == 600 && checks.failedRows == 0 ...
    && all(checks.shardFailed == 0) && checks.resourceRows == 600 ...
    && checks.sourceMatchesShard1 && checks.sourceMatchesShard2 ...
    && isequal(checks.snrCounts, [200, 200, 200]);

folder = fullfile(project, "results", "full_spectrum", ...
    "round29_600_external_audit_v1");
if ~isfolder(folder)
    mkdir(folder);
end
save(fullfile(folder, "audit.mat"), ...
    "checks", "methods", "paired", "resources", "boundaries", ...
    "seeds", "source", "options");
writetable(methods, fullfile(folder, "method_summary_copy.csv"));
writetable(paired, fullfile(folder, "paired_summary_copy.csv"));
fprintf("ROUND29_600_AUDIT complete=%d accepted=%d rows=%d failures=%d\n", ...
    checks.complete, checks.accepted, checks.seedRows, checks.failedRows);
assert(checks.complete, "r30:Round29AuditFailed", ...
    "The downloaded Round29 result set failed an integrity or coverage check.");
end
