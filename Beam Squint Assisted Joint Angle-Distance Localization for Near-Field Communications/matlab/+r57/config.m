    entersPrimaryJudgement=false, ...
    expectedRows=20*3*6*2);

protocol.design = struct(positionCount=30, ...
    snrDb=[-10, -5, 0, 5, 10, 15, 20], ...
    angleLimitsDeg=[-60, 60], rangeLimitsM=[15, 50], ...
    positionSeed=72000000, trialSeedRoot=72100000, expectedRows=210);
