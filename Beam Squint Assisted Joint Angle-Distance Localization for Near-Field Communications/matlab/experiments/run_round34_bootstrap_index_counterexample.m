function run_round34_bootstrap_index_counterexample()
%RUN_ROUND34_BOOTSTRAP_INDEX_COUNTEREXAMPLE Persist the inherited index bug.

project = string(fileparts(fileparts(mfilename("fullpath"))));
addpath(project);
folder = fullfile(project, "results", "full_spectrum", ...
    "round34_final_engineering_v1", "bootstrap_index_counterexample");
if ~isfolder(folder)
    mkdir(folder);
end
n = 3;
bootstrapCount = 4;
rangeDelta = [1, 10; 2, 20; 4, 40];
indices = [1, 1, 2, 3; 2, 3, 3, 1; 3, 2, 1, 2];
snrIndex = 2;
oldSampled = rangeDelta(indices, snrIndex);
oldOutput = squeeze(mean(oldSampled, 1));
fixedOutput = r34.clusterBootstrapMeans( ...
    rangeDelta(:, snrIndex), indices);
explicitOutput = zeros(bootstrapCount, 1);
for bootstrap = 1:bootstrapCount
    explicitOutput(bootstrap) = mean( ...
        rangeDelta(indices(:, bootstrap), snrIndex));
end
comparison = table((1:bootstrapCount).', explicitOutput, ...
    fixedOutput, repmat(oldOutput, bootstrapCount, 1), ...
    'VariableNames', {'bootstrapColumn', 'explicitLoopMean', ...
    'fixedReshapeMean', 'oldCollapsedMeanRepeated'});
audit = struct(version="R34-bootstrap-index-counterexample-v1", ...
    matlabVersion=version, n=n, bootstrapCount=bootstrapCount, ...
    oldSampledSize=size(oldSampled), oldOutputSize=size(oldOutput), ...
    fixedOutputSize=size(fixedOutput), ...
    oldEqualsExplicit=isequal(oldOutput, explicitOutput), ...
    fixedEqualsExplicit=isequal(fixedOutput, explicitOutput), ...
    inheritedFile="+r32/summarizeFinal.m", ...
    inheritedLine="rangeDelta(indices,snrIndex)", ...
    finalDataPreviouslyExecuted=false);
assert(~audit.oldEqualsExplicit && audit.fixedEqualsExplicit, ...
    "r34:BootstrapCounterexampleDidNotReproduce");
writetable(comparison, fullfile(folder, "counterexample.csv"));
save(fullfile(folder, "result.mat"), "audit", "rangeDelta", ...
    "indices", "oldSampled", "oldOutput", "fixedOutput", ...
    "explicitOutput");
fprintf("R34_BOOTSTRAP_COUNTEREXAMPLE oldSize=%dx%d fixedSize=%dx%d " + ...
    "oldEqual=%d fixedEqual=%d\n", size(oldOutput, 1), ...
    size(oldOutput, 2), size(fixedOutput, 1), ...
    size(fixedOutput, 2), audit.oldEqualsExplicit, ...
    audit.fixedEqualsExplicit);
end
