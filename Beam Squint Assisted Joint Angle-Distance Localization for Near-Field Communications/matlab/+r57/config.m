    robustAmplitude="P_FACR_A", robustDispersion="P_FACR_D", ...
    falsification="P_FACR_T", arrayOnly="P_FACR_Yonly", ...
    base="P_FALF", angleBase="P_FA", baseline="P_A", ...
    reference="C_enhanced", ...
    finalAngle="exact-frozen-P_FA-angle", ...
    paFree=true, musicFree=true, evdFree=true);
