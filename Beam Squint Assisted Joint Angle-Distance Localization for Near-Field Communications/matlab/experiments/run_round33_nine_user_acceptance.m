function run_round33_nine_user_acceptance()
%RUN_ROUND33_NINE_USER_ACCEPTANCE Validate A, B, and AB on nine old users.

project = string(fileparts(fileparts(mfilename("fullpath"))));
addpath(project);
raw = r31.loadRound30Raw(project);
controlFile = fullfile(project, "results", "full_spectrum", ...
    "round31_angle_controls_v2", "result.mat");
control = load(controlFile, "identity", "results");
protocol = r33.config();
cfg = raw.pilot.expected.cfg;
scan = fsjad.prepareScan(cfg);
rowIndex = selectedRows(raw.pilot.design, protocol.development);
variants = protocol.variants;
methods = protocol.timing.methods;
rows = table();
failure = table('Size', [0, 6], ...
    'VariableTypes', {'double', 'double', 'string', 'string', ...
    'string', 'string'}, 'VariableNames', {'seed', 'snrDb', ...
    'variant', 'method', 'errorIdentifier', 'errorMessage'});

for localUser = 1:numel(rowIndex)
    index = rowIndex(localUser);
    designRow = raw.pilot.design(index, :);
    replay = fsjad.replayRound27Data(cfg, scan, designRow);
    reference = referenceData(raw, control, index);
    for variant = variants
        [useFastResponse, useGram] = variantOptions(variant);
        for method = methods
            try
                fast = r33.estimate(cfg, replay.observation, ...
                    replay.snapshots, scan, method, protocol, ...
                    UseFastResponse=useFastResponse, UseGram=useGram);
                entry = comparisonRow(designRow, variant, method, fast, ...
                    reference, protocol.validation);
                rows = [rows; entry]; %#ok<AGROW>
            catch exception
                failure = [failure; table(designRow.seed, designRow.snrDb, ...
                    variant, method, string(exception.identifier), ...
                    string(getReport(exception, "extended", ...
                    "hyperlinks", "off")), 'VariableNames', {'seed', ...
                    'snrDb', 'variant', 'method', 'errorIdentifier', ...
                    'errorMessage'})]; %#ok<AGROW>
            end
        end
    end
end

variantSummary = summarizeVariants(rows, variants);
variantPass = table();
for variant = variants
    selected = rows.variant == variant;
    pass = nnz(selected) == numel(rowIndex)*numel(methods) ...
        && all(rows.pass(selected)) ...
        && (isempty(failure) || ~any(failure.variant == variant));
    variantPass = [variantPass; table(variant, pass, nnz(selected), ...
        nnz(rows.fallbackCount(selected)), 'VariableNames', ...
        {'variant', 'pass', 'completedMethodRuns', ...
        'totalFallbackCount'})]; %#ok<AGROW>
end

folder = fullfile(project, "results", "full_spectrum", ...
    "round33_equivalent_acceleration_v1", "nine_user_acceptance");
if ~isfolder(folder)
    mkdir(folder);
end
writetable(rows, fullfile(folder, "per_method_comparisons.csv"));
writetable(variantSummary, fullfile(folder, "variant_maxima.csv"));
writetable(variantPass, fullfile(folder, "variant_pass.csv"));
writetable(failure, fullfile(folder, "failures.csv"));
source = r33.manifest(project);
writetable(source, fullfile(folder, "source_hashes.csv"));
identity = struct(version="R33-nine-existing-user-acceptance-v1", ...
    protocol=protocol, design=raw.pilot.design(rowIndex, :), ...
    pilotHash=raw.pilotHash, baselineHash=raw.baselineHash, ...
    controlIdentity=control.identity);
save(fullfile(folder, "result.mat"), "identity", "rows", ...
    "variantSummary", "variantPass", "failure", "source", "-v7.3");
if ~all(variantPass.pass)
    error("r33:NineUserAcceptanceFailed", ...
        "At least one frozen equivalent implementation did not pass.");
end
fprintf("ROUND33_NINE_USER_ACCEPTANCE_COMPLETE runs=%d fallbacks=%d\n", ...
    height(rows), sum(rows.fallbackCount));
end

function rowIndex = selectedRows(design, development)
rowIndex = zeros(numel(development.snrDb)*development.usersPerSnr, 1);
cursor = 1;
for snrDb = development.snrDb
    found = find(design.snrDb == snrDb, development.usersPerSnr, "first");
    rowIndex(cursor:cursor+numel(found)-1) = found;
    cursor = cursor+numel(found);
end
end

function reference = referenceData(raw, control, index)
pilot = raw.pilot.results{index}.candidateResults{raw.l06PilotIndex};
baseline = raw.baselines.results{index, raw.l06BaselineIndex};
controlResult = control.results{index};
reference.front = pilot.front;
reference.control = controlResult;
reference.enhanced = baseline.enhancedBaseline;
reference.public = baseline.publicBaseline;
end

function [useFastResponse, useGram] = variantOptions(variant)
useFastResponse = variant ~= "B_gram_subspace";
useGram = variant ~= "A_response_invariants";
end

function entry = comparisonRow( ...
    design, variant, method, fast, reference, tolerance)
[expectedTheta, expectedRange, referenceVectors] = ...
    expectedOutput(method, reference);
projection = sum(conj(referenceVectors).*fast.state.signalVectors, 1);
projectionDifference = max(abs(1-abs(projection).^2));
referenceState = fast.state;
referenceState.signalVectors = referenceVectors;
scoreRange = fast.front.selected.rangeM;
if method == "C_enhanced" || method == "C_public"
    scoreRange = expectedRange;
end
referenceScore = jad.localMusicLogScore( ...
    fast.musicCfg, referenceState, expectedTheta, scoreRange);
fastScore = jad.localMusicLogScore( ...
    fast.musicCfg, fast.state, expectedTheta, scoreRange);
musicScoreDifference = abs(fastScore-referenceScore);
[frontThetaDifference, frontRangeDifference, bankThetaDifference, ...
    bankRangeDifference, bankScoreDifference, selectedBankThetaDifference, ...
    selectedBankRangeDifference, selectedBankScoreDifference, ...
    sameSelectedIndex, sameBankSize, sameBankSources, ...
    sameSelectedBankSources] = frontComparison( ...
    fast.front, reference.front);
absoluteThetaDifference = abs(fast.thetaDeg-expectedTheta);
absoluteRangeDifference = abs(fast.rangeM-expectedRange);
pass = absoluteThetaDifference <= tolerance.thetaToleranceDeg ...
    && absoluteRangeDifference <= tolerance.rangeToleranceM ...
    && abs(frontThetaDifference) ...
        <= tolerance.selectedCandidateTolerance(1) ...
    && abs(frontRangeDifference) ...
        <= tolerance.selectedCandidateTolerance(2) ...
    && bankThetaDifference <= tolerance.selectedCandidateTolerance(1) ...
    && bankRangeDifference <= tolerance.selectedCandidateTolerance(2) ...
    && bankScoreDifference <= tolerance.candidateScoreTolerance ...
    && selectedBankThetaDifference ...
        <= tolerance.selectedCandidateTolerance(1) ...
    && selectedBankRangeDifference ...
        <= tolerance.selectedCandidateTolerance(2) ...
    && selectedBankScoreDifference <= tolerance.candidateScoreTolerance ...
    && sameSelectedIndex && sameBankSize && sameBankSources ...
    && sameSelectedBankSources ...
    && projectionDifference <= tolerance.projectionTolerance ...
    && musicScoreDifference <= tolerance.profileScoreTolerance;
entry = table(design.seed, design.snrDb, variant, method, ...
    absoluteThetaDifference, absoluteRangeDifference, ...
    frontThetaDifference, frontRangeDifference, bankThetaDifference, ...
    bankRangeDifference, bankScoreDifference, selectedBankThetaDifference, ...
    selectedBankRangeDifference, selectedBankScoreDifference, ...
    sameSelectedIndex, sameBankSize, sameBankSources, ...
    sameSelectedBankSources, projectionDifference, ...
    musicScoreDifference, fast.cost.sparseResponseCalls, ...
    fast.cost.frontFullResponseCalls, fast.cost.profileResponseCalls, ...
    fast.cost.fallbackCount, fast.cost.gramSuccessCount, ...
    fast.cost.directCount, fast.cost.maximumRelativeResidual, ...
    fast.cost.minimumRelativeEigengap, fast.cost.totalOnlineSeconds, pass, ...
    'VariableNames', {'seed', 'snrDb', 'variant', 'method', ...
    'absoluteThetaDifferenceDeg', 'absoluteRangeDifferenceM', ...
    'frontThetaDifferenceDeg', 'frontRangeDifferenceM', ...
    'frontBankThetaDifferenceDeg', 'frontBankRangeDifferenceM', ...
    'frontBankScoreDifference', 'selectedBankThetaDifferenceDeg', ...
    'selectedBankRangeDifferenceM', 'selectedBankScoreDifference', ...
    'sameFrontSelectedIndex', 'sameFrontBankSize', ...
    'sameFrontBankSources', 'sameSelectedBankSources', ...
    'signalProjectionDifference', ...
    'musicScoreDifference', 'sparseResponseCalls', ...
    'frontFullResponseCalls', 'profileResponseCalls', ...
    'fallbackCount', 'gramSuccessCount', 'directCount', ...
    'maximumRelativeResidual', 'minimumRelativeEigengap', ...
    'totalOnlineSeconds', 'pass'});
end

function [thetaDeg, rangeM, vectors] = expectedOutput(method, reference)
switch method
    case "C_enhanced"
        thetaDeg = reference.control.thetaDeg(1);
        rangeM = reference.control.rangeM(1);
        vectors = reference.enhanced.estimate.signalVectors;
    case "H_A"
        thetaDeg = reference.control.thetaDeg(2);
        rangeM = reference.control.rangeM(2);
        vectors = reference.enhanced.estimate.signalVectors;
    case "P_A"
        thetaDeg = reference.control.thetaDeg(3);
        rangeM = reference.control.rangeM(3);
        vectors = reference.enhanced.estimate.signalVectors;
    case "C_public"
        thetaDeg = reference.public.estimate.thetaDeg;
        rangeM = reference.public.estimate.rangeM;
        vectors = reference.public.estimate.signalVectors;
    otherwise
        error("r33:UnknownReferenceMethod", "Unknown method %s.", method);
end
end

function [thetaDifference, rangeDifference, bankThetaDifference, ...
    bankRangeDifference, bankScoreDifference, selectedThetaDifference, ...
    selectedRangeDifference, selectedScoreDifference, ...
    sameSelectedIndex, sameBankSize, sameBankSources, ...
    sameSelectedBankSources] = frontComparison(fast, reference)
thetaDifference = fast.selected.thetaDeg-reference.selected.thetaDeg;
rangeDifference = fast.selected.rangeM-reference.selected.rangeM;
sameSelectedIndex = fast.selectedIndex == reference.selectedIndex;
sameBankSize = height(fast.candidateBank) == height(reference.candidateBank);
bankThetaDifference = inf;
bankRangeDifference = inf;
bankScoreDifference = inf;
sameBankSources = false;
if sameBankSize
    bankThetaDifference = maximumDifference(fast.candidateBank.thetaDeg, ...
        reference.candidateBank.thetaDeg);
    bankRangeDifference = maximumDifference(fast.candidateBank.rangeM, ...
        reference.candidateBank.rangeM);
    bankScoreDifference = maximumDifference( ...
        fast.candidateBank.subsetLogScore, ...
        reference.candidateBank.subsetLogScore);
    sameBankSources = isequal(fast.candidateBank.source, ...
        reference.candidateBank.source);
end
sameSelectedBankSize = height(fast.selectedBank) ...
    == height(reference.selectedBank);
selectedThetaDifference = inf;
selectedRangeDifference = inf;
selectedScoreDifference = inf;
sameSelectedBankSources = false;
if sameSelectedBankSize
    selectedThetaDifference = maximumDifference( ...
        fast.selectedBank.thetaDeg, reference.selectedBank.thetaDeg);
    selectedRangeDifference = maximumDifference( ...
        fast.selectedBank.rangeM, reference.selectedBank.rangeM);
    selectedScoreDifference = maximumDifference( ...
        fast.selectedBank.subsetLogScore, ...
        reference.selectedBank.subsetLogScore);
    sameSelectedBankSources = isequal(fast.selectedBank.source, ...
        reference.selectedBank.source);
end
end

function value = maximumDifference(left, right)
if isempty(left) && isempty(right)
    value = 0;
else
    value = max(abs(left-right), [], "all");
end
end

function summary = summarizeVariants(rows, variants)
summary = table();
fields = ["absoluteThetaDifferenceDeg", "absoluteRangeDifferenceM", ...
    "frontThetaDifferenceDeg", "frontRangeDifferenceM", ...
    "frontBankThetaDifferenceDeg", "frontBankRangeDifferenceM", ...
    "frontBankScoreDifference", "selectedBankThetaDifferenceDeg", ...
    "selectedBankRangeDifferenceM", "selectedBankScoreDifference", ...
    "signalProjectionDifference", "musicScoreDifference", ...
    "fallbackCount"];
for variant = variants
    selected = rows.variant == variant;
    values = cell(1, numel(fields));
    for index = 1:numel(fields)
        values{index} = max(rows.(fields(index))(selected), [], "all");
    end
    summary = [summary; cell2table([{variant}, values], ...
        'VariableNames', ["variant", "max_"+fields])]; %#ok<AGROW>
end
end
