function authorize_round41_schemeG_final(approvalPhrase)
%AUTHORIZE_ROUND41_SCHEMEG_FINAL Create one exact future authorization.
% This function is not called by preparation, preflight, or tests.

arguments
    approvalPhrase (1, 1) string
end

project = string(fileparts(fileparts(mfilename("fullpath"))));
r41.addPaths(project);
locations = r41.paths(project);
if isfolder(locations.executionFolder)
    error("r41:ExistingFinalResultDirectory", ...
        "The R41 final result directory already exists. " + ...
        "Resolve it manually before authorization.");
end
if isfile(locations.authorizationFile)
    error("r41:AuthorizationAlreadyExists", ...
        "The R41 authorization is immutable and cannot be overwritten.");
end
saved = r41.validateProtocolPackage(project);
if approvalPhrase ~= saved.protocol.execution.authorizationPhrase
    error("r41:ExplicitApprovalPhraseRequired", ...
        "The exact explicit R41 approval phrase is required.");
end
authorization = struct(approved=true, ...
    protocolVersion=saved.identity.protocolVersion, ...
    designHash=saved.identity.designHash, ...
    statisticsVersion=saved.identity.statisticsVersion, ...
    statisticsHash=saved.identity.statisticsHash, ...
    sourceDigest=saved.identity.sourceDigest, ...
    algorithmDigest=saved.identity.algorithmDigest, ...
    r33Digest=saved.identity.r33Digest, ...
    r34Digest=saved.identity.r34Digest, ...
    frozenDependencyDigest=saved.identity.frozenDependencyDigest, ...
    approvedAt=string(datetime("now", "TimeZone", "Asia/Shanghai")), ...
    statement= ...
    "user-explicitly-authorized-one-frozen-R41-1400-trial-final", ...
    authorized=true, trialsExecuted=0);
save(locations.authorizationFile, "authorization");
fprintf("ROUND41_FINAL_AUTHORIZED design=%s trials=0\n", ...
    authorization.designHash);
end
