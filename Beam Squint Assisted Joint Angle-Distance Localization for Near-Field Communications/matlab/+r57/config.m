    warmups=1, methods=["P_FACR", "C_enhanced"]);

% G9 is an efficiency gate against the closed-form coherent CRLB. It replaced
% a per-SNR ratio-spread gate on 2026-09-20 after the 21-row smoke showed the
% spread measures the heavy tail of the P_A denominator rather than Theorem 2.
% No R57 development row had been executed at that time. See research/141 8.1.
