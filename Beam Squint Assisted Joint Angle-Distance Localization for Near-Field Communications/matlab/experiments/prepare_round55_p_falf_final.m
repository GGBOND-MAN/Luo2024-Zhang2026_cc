function output = prepare_round55_p_falf_final()
%PREPARE_ROUND55_P_FALF_FINAL Create the locked package without trials.

project = string(fileparts(fileparts(mfilename("fullpath"))));
r41.addPaths(project);
locations = r55.paths(project);
if isfolder(locations.protocolFolder) || isfolder(locations.executionFolder)
    error("r55:ExistingFinalState", ...
        "R55 protocol or execution state already exists.");
end
protocol = r55.config();
design = r55.design(protocol);
if height(design) ~= protocol.design.expectedRows ...
        || numel(unique(design.positionId)) ~= protocol.design.positionCount ...
        || numel(unique(design.seed)) ~= protocol.design.expectedRows
    error("r55:FrozenDesignMismatch", "The R55 design is invalid.");
end
r53Source = r53.manifest(project);
r54Source = r54.manifest(project);
pfaSource = r45.manifest(project);
if r32.sourceDigest(r53Source) ~= protocol.algorithm.r53SourceDigest ...
        || r32.sourceDigest(r54Source) ~= protocol.algorithm.r54SourceDigest ...
        || r32.sourceDigest(pfaSource) ~= protocol.algorithm.pfaSourceDigest
    error("r55:FrozenDependencyDrift", ...
        "A calibrated frozen dependency no longer matches its digest.");
end
source = r55.sourceManifest(project);
designHash = r32.designHash(design);
statisticsHash = r41.structHash(protocol.statistics);
estimate = conservativeEstimate(protocol);
if isfile(locations.benchmarkFile)
    benchmark = load(locations.benchmarkFile, "estimate");
    estimate = benchmark.estimate;
end
identity = struct(version="R55-PFALF-final-protocol-package-v1", ...
    protocolVersion=protocol.version, status=protocol.execution.status, ...
    authorized=false, trialsExecuted=0, ...
    r53SourceDigest=r32.sourceDigest(r53Source), ...
    r54SourceDigest=r32.sourceDigest(r54Source), ...
    pfaSourceDigest=r32.sourceDigest(pfaSource), ...
    designHash=designHash, statisticsHash=statisticsHash, ...
    sourceDigest=r32.sourceDigest(source), observationsGenerated=0, ...
    estimatedHours=max(estimate.recommendedUpperHours, ...
        estimate.conservativeRawHours), ...
    exceedsFourHours=estimate.exceedsFourHours, ...
    preparedAt=string(datetime("now", "TimeZone", "Asia/Shanghai")));
mkdir(locations.protocolFolder);
writetable(design, fullfile(locations.protocolFolder, "design.csv"));
writetable(source, fullfile(locations.protocolFolder, "source_manifest.csv"));
writetable(estimate, fullfile(locations.protocolFolder, "runtime_estimate.csv"));
save(locations.protocolFile, "identity", "protocol", "design", ...
    "source", "r53Source", "r54Source", "pfaSource", "estimate", "-v7");
writelines([ ...
    "LOCKED: no R55 authorization or final observation exists."; ...
    "Estimated runtime exceeds the user's four-hour auto-run limit."; ...
    "Run manually only after reviewing runtime_estimate.csv."; ...
    "Exact authorization phrase:"; protocol.execution.authorizationPhrase], ...
    fullfile(locations.protocolFolder, "LOCKED_README.txt"));
output = struct(folder=locations.protocolFolder, identity=identity, ...
    protocol=protocol, estimate=estimate);
fprintf("ROUND55_PROTOCOL_PREPARED_LOCKED rows=%d trials=0 over4h=%d\n", ...
    height(design), identity.exceedsFourHours);
disp(estimate);
end

function output = conservativeEstimate(protocol)
output = table(protocol.complexity.recommendedWorkers, 0, 0, nan, nan, ...
    nan, protocol.complexity.rawLinearProjectionHours, 10/60, ...
    1.15*protocol.complexity.rawLinearProjectionHours+10/60, ...
    protocol.complexity.rawLinearProjectionHours, true, ...
    'VariableNames', {'workers', 'benchmarkRows', 'repetitions', ...
    'meanWallSeconds', 'medianWallSeconds', 'effectiveSecondsPerRow', ...
    'projectedComputeHours1400', 'postprocessHours', ...
    'recommendedUpperHours', 'conservativeRawHours', ...
    'exceedsFourHours'});
end
