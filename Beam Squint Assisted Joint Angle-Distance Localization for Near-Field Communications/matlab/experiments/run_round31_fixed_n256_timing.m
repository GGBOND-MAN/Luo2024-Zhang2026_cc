function run_round31_fixed_n256_timing(options)
%RUN_ROUND31_FIXED_N256_TIMING Time exact C/A/B configurations at N=256.

arguments
    options.PositionCount (1, 1) double {mustBeInteger, mustBePositive} = 3
    options.Repetitions (1, 1) double {mustBeInteger, mustBePositive} = 3
end

project = string(fileparts(fileparts(mfilename("fullpath"))));
addpath(project);
raw = r31.loadRound30Raw(project, IncludeBaselineResults=false);
protocol = r31.config();
cfg = raw.pilot.expected.cfg;
if cfg.numAntennas ~= 256
    error("r31:TimingRequiresN256", ...
        "The corrected timing comparison is fixed at N=256.");
end
algorithm = raw.pilot.expected.enhancedAlgorithm;
if algorithm.subarraySize ~= 160 || algorithm.fusionCarrierCount ~= 2047 ...
        || ~isequal(algorithm.gridSizes, [41, 31, 21])
    error("r31:TimingConfigurationMismatch", ...
        "The enhanced timing configuration must be N256/L160/K2047/41-31-21.");
end

positions = raw.pilot.design(raw.pilot.design.snrDb == 0, :);
positions = positions(1:min(options.PositionCount, height(positions)), :);
scan = fsjad.prepareScan(cfg);
output = table();
warmupCount = 1;
for position = 1:height(positions)
    rowIndex = find(raw.pilot.design.seed == positions.seed(position), 1);
    oldItem = raw.pilot.results{rowIndex}.candidateResults{raw.l06PilotIndex};
    replay = fsjad.replayRound27Data(cfg, scan, positions(position, :));
    front = oldItem.front.selected;
    for warmup = 1:warmupCount
        measureOne(cfg, scan, replay, front, algorithm, ...
            raw.l06Candidate, protocol);
    end
    for repetition = 1:options.Repetitions
        measured = measureOne(cfg, scan, replay, front, algorithm, ...
            raw.l06Candidate, protocol);
        rows = timingRows(measured, positions(position, :), ...
            repetition, oldItem.front.runtimeSeconds, cfg, algorithm, ...
            raw.l06Candidate);
        output = [output; rows]; %#ok<AGROW>
    end
end

environment = struct(matlabVersion=version, computer=computer, ...
    execution="sequential-single-MATLAB-process", ...
    warmupCount=warmupCount, repetitions=options.Repetitions, ...
    positionCount=height(positions), timestamp=string(datetime("now")));
folder = fullfile(project, "results", "full_spectrum", ...
    "round31_fixed_n256_timing_v2");
if ~isfolder(folder)
    mkdir(folder);
end
writetable(output, fullfile(folder, "timing_rows.csv"));
writetable(raw.source, fullfile(folder, "source_hashes.csv"));
identity = struct(version="R31-fixed-N256-L160-timing-v2", ...
    protocol=protocol, positions=positions, algorithm=algorithm, ...
    pilotHash=raw.pilotHash, source=raw.source);
save(fullfile(folder, "result.mat"), ...
    "identity", "output", "environment", "-v7.3");
fprintf("ROUND31_FIXED_N256_TIMING_COMPLETE rows=%d\n", height(output));
end

function measured = measureOne(cfg, scan, replay, front, ...
    algorithm, l06Candidate, protocol)
carrierA = r30.selectLocalCarriers(cfg.numSubcarriers, ...
    algorithm.fusionCarrierCount, replay.peakCarrierIndex);
carrierB = r30.selectLocalCarriers(cfg.numSubcarriers, ...
    l06Candidate.musicCarrierCount, replay.peakCarrierIndex);
musicCfg = cfg;
musicCfg.subarraySize = algorithm.subarraySize;
musicCfg.numSubarrays = cfg.numAntennas-algorithm.subarraySize+1;

timer = tic;
stateA = jad.freezeLocalMusicSubspace(musicCfg, ...
    replay.snapshots(:, carrierA+1), carrierA, front.thetaDeg, front.rangeM);
measured.stateASeconds = toc(timer);
timer = tic;
measured.C = r31.stagedJointMusic(musicCfg, stateA, ...
    front.thetaDeg, front.rangeM, algorithm.localHalfWidthDeg, ...
    algorithm.localHalfWidthM, algorithm.gridSizes);
measured.CSeconds = toc(timer);
timer = tic;
measured.A = r31.stagedAngleMusic(musicCfg, stateA, ...
    front.thetaDeg, front.rangeM, algorithm.localHalfWidthDeg, ...
    algorithm.gridSizes);
measured.ASeconds = toc(timer);
timer = tic;
measured.profileA = r31.profileAtAngle(cfg, replay.observation, scan, ...
    measured.A.thetaDeg, front.rangeM, protocol);
measured.profileASeconds = toc(timer);

timer = tic;
stateB = jad.freezeLocalMusicSubspace(musicCfg, ...
    replay.snapshots(:, carrierB+1), carrierB, front.thetaDeg, front.rangeM);
measured.stateBSeconds = toc(timer);
timer = tic;
measured.B = r31.stagedAngleMusic(musicCfg, stateB, ...
    front.thetaDeg, front.rangeM, algorithm.localHalfWidthDeg, ...
    algorithm.gridSizes);
measured.BSeconds = toc(timer);
timer = tic;
measured.profileB = r31.profileAtAngle(cfg, replay.observation, scan, ...
    measured.B.thetaDeg, front.rangeM, protocol);
measured.profileBSeconds = toc(timer);

[stateASubset, ~] = r31.subsetState(stateA, carrierB);
innerProduct = sum(conj(stateASubset.signalVectors).*stateB.signalVectors, 1);
measured.maximumProjectionDifference = max(abs(1-abs(innerProduct).^2));
measured.carrierBSubsetA = all(ismember(carrierB, carrierA));
end

function rows = timingRows(measured, position, repetition, ...
    frontHistoricalSeconds, cfg, algorithm, l06Candidate)
method = ["C_enhanced"; "H_A"; "P_A"; "H_B"; "P_B"];
subarraySize = repmat(algorithm.subarraySize, 5, 1);
numSubarrays = repmat(cfg.numAntennas-algorithm.subarraySize+1, 5, 1);
carrierCount = [algorithm.fusionCarrierCount; algorithm.fusionCarrierCount; ...
    algorithm.fusionCarrierCount; l06Candidate.musicCarrierCount; ...
    l06Candidate.musicCarrierCount];
thetaHalfWidthDeg = repmat(algorithm.localHalfWidthDeg, 5, 1);
rangeHalfWidthM = [algorithm.localHalfWidthM; 0; 2; 0; 2];
gridDescription = repmat("41/31/21", 5, 1);
constrainToInitialWindow = true(5, 1);
fixedRangeDuringAngle = [false; true; true; true; true];
stateSeconds = [measured.stateASeconds; measured.stateASeconds; ...
    measured.stateASeconds; measured.stateBSeconds; measured.stateBSeconds];
searchSeconds = [measured.CSeconds; measured.ASeconds; measured.ASeconds; ...
    measured.BSeconds; measured.BSeconds];
profileSeconds = [0; 0; measured.profileASeconds; 0; measured.profileBSeconds];
backendSeconds = stateSeconds+searchSeconds+profileSeconds;
thetaDeg = [measured.C.thetaDeg; measured.A.thetaDeg; measured.A.thetaDeg; ...
    measured.B.thetaDeg; measured.B.thetaDeg];
rangeM = [measured.C.rangeM; nan; measured.profileA.value; ...
    nan; measured.profileB.value];
searchEvaluations = [measured.C.evaluationCount; measured.A.evaluationCount; ...
    measured.A.evaluationCount; measured.B.evaluationCount; ...
    measured.B.evaluationCount];
profileEvaluations = [0; 0; measured.profileA.evaluationCount; ...
    0; measured.profileB.evaluationCount];

rows = table(repmat(cfg.numAntennas, 5, 1), subarraySize, numSubarrays, ...
    carrierCount, repmat(position.seed, 5, 1), ...
    repmat(position.snrDb, 5, 1), repmat(repetition, 5, 1), method, ...
    thetaHalfWidthDeg, rangeHalfWidthM, gridDescription, ...
    constrainToInitialWindow, fixedRangeDuringAngle, ...
    repmat(frontHistoricalSeconds, 5, 1), stateSeconds, searchSeconds, ...
    profileSeconds, backendSeconds, ...
    backendSeconds+frontHistoricalSeconds, searchEvaluations, ...
    profileEvaluations, thetaDeg, rangeM, ...
    repmat(measured.carrierBSubsetA, 5, 1), ...
    repmat(measured.maximumProjectionDifference, 5, 1), ...
    'VariableNames', {'numAntennas', 'subarraySize', 'numSubarrays', ...
    'carrierCount', 'seed', 'snrDb', 'repetition', 'method', ...
    'thetaHalfWidthDeg', 'rangeHalfWidthM', 'gridDescription', ...
    'constrainToInitialWindow', 'fixedRangeDuringAngle', ...
    'frontHistoricalSeconds', 'stateSeconds', 'searchSeconds', ...
    'profileSeconds', 'backendSeconds', ...
    'endToEndUsingHistoricalFrontSeconds', 'searchEvaluations', ...
    'profileEvaluations', 'thetaDeg', 'rangeM', 'carrierBSubsetA', ...
    'maximumProjectionDifference'});
end
