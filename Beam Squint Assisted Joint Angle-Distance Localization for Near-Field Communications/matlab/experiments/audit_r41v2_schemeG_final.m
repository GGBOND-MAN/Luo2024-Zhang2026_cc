function output = audit_r41v2_schemeG_final()
%AUDIT_R41V2_SCHEMEG_FINAL Independently audit the completed frozen final.

project = string(fileparts(fileparts(mfilename("fullpath"))));
r41.addPaths(project);
saved = r41statsv2.validateProtocolPackage(project);
locations = r41statsv2.paths(project);
authorization = r41.assertAuthorized( ...
    locations.protocolFolder, saved.identity);
authorizationDigest = r41.structHash(authorization);
aggregateFile = fullfile(locations.executionFolder, ...
    "aggregate", "result.mat");
timingFile = fullfile(locations.executionFolder, ...
    "matched_timing", "result.mat");
if ~isfile(aggregateFile) || ~isfile(timingFile)
    error("r41v2:AuditRequiresAggregateAndTiming", ...
        "The independent audit requires completed aggregate and matched timing.");
end
auditFolder = fullfile(locations.executionFolder, "final_audit");
if isfolder(auditFolder)
    error("r41v2:FinalAuditAlreadyExists", ...
        "The independent final audit cannot be overwritten.");
end
mkdir(auditFolder);

[payloads, shardChecks, shardDetails] = loadShards( ...
    locations, saved, authorizationDigest);
results = r41.mergeShardPayloads(saved.design, payloads, saved.identity);
aggregate = load(aggregateFile, "identity", "analysis", "source");
timing = load(timingFile, "identity", "design", ...
    "rows", "summary", "comparison");
[designChecks, designDetails] = designAudit(saved.design, payloads);
[trialChecks, trialDetails, fallbackSummary] = trialAudit(results);
[aggregateChecks, aggregateDetails, recomputed] = aggregateAudit( ...
    saved, results, aggregate, authorizationDigest);
[timingChecks, timingDetails] = timingAudit( ...
    saved, timing, authorizationDigest);

cfg = jad.defaultConfig();
r41.validateFrozenSystem(cfg, saved.protocol);
scan = fsjad.prepareScan(cfg);
inputHashes = r34.prepareInputHashes(cfg, scan, saved.design);
inputHashTable = hashesToTable(saved.design, inputHashes);
spotRows = ismember(saved.design.positionId, [1, 100, 101, 200]);
spotHashes = r34.prepareInputHashes(cfg, scan, saved.design(spotRows, :));
inputReplayPass = compareHashes(inputHashes(spotRows), spotHashes);
inputChecks = [height(inputHashTable) == 1400; ...
    numel(unique(inputHashTable.observationHash)) == 1400; ...
    numel(unique(inputHashTable.snapshotsHash)) == 1400; ...
    inputReplayPass];
inputDetails = ["1400 deterministic replay hashes"; ...
    "all observation hashes unique"; "all snapshot hashes unique"; ...
    "28-row boundary-cluster replay hashes identical"];

check = [shardChecks.check; designChecks.check; trialChecks.check; ...
    aggregateChecks.check; timingChecks.check; ...
    ["input hash row count"; "observation hash uniqueness"; ...
    "snapshot hash uniqueness"; "input hash deterministic replay"]];
pass = [shardChecks.pass; designChecks.pass; trialChecks.pass; ...
    aggregateChecks.pass; timingChecks.pass; inputChecks];
detail = [shardDetails; designDetails; trialDetails; ...
    aggregateDetails; timingDetails; inputDetails];
audit = table(check, pass, detail);
writetable(audit, fullfile(auditFolder, "final_audit_checks.csv"));
writetable(inputHashTable, ...
    fullfile(auditFolder, "observation_input_hashes.csv"));
writetable(fallbackSummary, ...
    fullfile(auditFolder, "schemeG_fallback_summary.csv"));

identity = struct(version="R41-v2-independent-final-audit-v1", ...
    authorized=true, trialsExecuted=height(saved.design), ...
    positionsAudited=numel(unique(saved.design.positionId)), ...
    failedTrials=nnz(~cellfun(@(item) item.success, results)), ...
    auditPassed=all(pass), algorithmDigest=saved.identity.algorithmDigest, ...
    designHash=saved.identity.designHash, ...
    statisticsVersion=saved.identity.statisticsVersion, ...
    statisticsHash=saved.identity.statisticsHash, ...
    sourceDigest=saved.identity.sourceDigest, ...
    r33Digest=saved.identity.r33Digest, r34Digest=saved.identity.r34Digest, ...
    frozenDependencyDigest=saved.identity.frozenDependencyDigest, ...
    authorizationDigest=authorizationDigest, ...
    bootstrapIndexHash=recomputed.statisticsAudit.global.indexHash, ...
    inputHashTableDigest=r31.arrayHash( ...
    double(char(join(inputHashTable.observationHash ...
    +inputHashTable.snapshotsHash, "")))), ...
    timestamp=string(datetime("now", "TimeZone", "Asia/Shanghai")));
save(fullfile(auditFolder, "result.mat"), "identity", "audit", ...
    "inputHashTable", "fallbackSummary", "recomputed", "-v7.3");
output = struct(identity=identity, audit=audit, ...
    inputHashTable=inputHashTable, fallbackSummary=fallbackSummary, ...
    folder=auditFolder);
fprintf("R41_V2_FINAL_AUDIT checks=%d passed=%d trials=%d\n", ...
    height(audit), nnz(audit.pass), identity.trialsExecuted);
assert(all(pass), "r41v2:IndependentFinalAuditFailed", ...
    "At least one independent final audit check failed; retain all evidence.");
end

function [payloads, checks, details] = loadShards( ...
    locations, saved, authorizationDigest)
payloads = cell(2, 1);
check = strings(0, 1);
pass = false(0, 1);
details = strings(0, 1);
for shardId = 1:2
    folder = fullfile(locations.executionFolder, ...
        sprintf("shard_%02d_of_02", shardId));
    completeFile = fullfile(folder, "COMPLETE.mat");
    resultFile = fullfile(folder, "result.mat");
    completeExists = isfile(completeFile);
    resultExists = isfile(resultFile);
    check(end+1, 1) = "shard "+shardId+" completion artifacts"; %#ok<AGROW>
    pass(end+1, 1) = completeExists && resultExists; %#ok<AGROW>
    details(end+1, 1) = "COMPLETE.mat and result.mat required"; %#ok<AGROW>
    if ~completeExists || ~resultExists
        continue;
    end
    payloads{shardId} = load(resultFile, "identity", "design", ...
        "results", "environment", "failures");
    identity = payloads{shardId}.identity;
    identityPass = identity.authorized ...
        && identity.trialsExecuted == 700 ...
        && identity.shardId == shardId && identity.shardCount == 2 ...
        && identity.designHash == saved.identity.designHash ...
        && identity.statisticsHash == saved.identity.statisticsHash ...
        && identity.algorithmDigest == saved.identity.algorithmDigest ...
        && identity.sourceDigest == saved.identity.sourceDigest ...
        && identity.r33Digest == saved.identity.r33Digest ...
        && identity.r34Digest == saved.identity.r34Digest ...
        && identity.frozenDependencyDigest ...
        == saved.identity.frozenDependencyDigest ...
        && identity.authorizationDigest == authorizationDigest;
    check(end+1, 1) = "shard "+shardId+" frozen identity"; %#ok<AGROW>
    pass(end+1, 1) = identityPass; %#ok<AGROW>
    details(end+1, 1) = "authorized exact 700-row identity"; %#ok<AGROW>
end
checks = table(check, pass);
end

function [checks, details] = designAudit(design, payloads)
keys = design(:, ["positionId", "snrDb"]);
positions = unique(design.positionId);
snrValues = unique(design.snrDb);
completeClusters = true;
for positionId = positions.'
    rows = design.positionId == positionId;
    completeClusters = completeClusters ...
        && nnz(rows) == 7 ...
        && isequal(sort(design.snrDb(rows)).', sort(snrValues).') ...
        && isscalar(unique(design.truthThetaDeg(rows))) ...
        && isscalar(unique(design.truthRangeM(rows)));
end
perSnr = groupcounts(design, "snrDb");
firstPositions = unique(payloads{1}.design.positionId);
secondPositions = unique(payloads{2}.design.positionId);
check = ["exactly 1400 design rows"; "exactly 200 positions"; ...
    "exactly 200 rows per SNR"; "zero duplicate position-SNR keys"; ...
    "all position clusters complete"; "shard positions do not overlap"; ...
    "shard assignment remains 1-100 and 101-200"];
pass = [height(design) == 1400; numel(positions) == 200; ...
    height(perSnr) == 7 && all(perSnr.GroupCount == 200); ...
    height(unique(keys, "rows")) == 1400; completeClusters; ...
    isempty(intersect(firstPositions, secondPositions)); ...
    isequal(firstPositions, (1:100).') ...
    && isequal(secondPositions, (101:200).')];
details = ["frozen paired rows"; "frozen position clusters"; ...
    "seven SNR groups"; "positionId plus snrDb unique"; ...
    "truth fixed within each seven-row cluster"; ...
    "no cluster split"; "exact frozen position ranges"];
checks = table(check, pass);
end

function [checks, details, fallbackSummary] = trialAudit(results)
success = cellfun(@(item) item.success, results);
methodIdentity = cellfun(@(item) isequal(string(item.methodNames), ...
    ["G_schur", "C_enhanced", "P_A"]), results);
profileIdentity = cellfun(@(item) isequal(item.profilePassCount, ...
    [1, 0, 1]), results);
evdFinitePositive = cellfun(@(item) all(isfinite(item.evdCount)) ...
    && all(item.evdCount > 0), results);
fallbackReason = cellfun(@(item) ...
    string(item.gDiagnostics.angle.fallbackReason), results);
allowedFallback = [""; "invalid-information"; ...
    "array-range-outside-physical-limits"; ...
    "concentrated-cost-not-decreased"; "final-grid-endpoint"];
fallbackIdentity = all(ismember(fallbackReason, allowedFallback));
estimateSource = string(fileread(which("r34.estimate")));
directOnlySource = contains(estimateSource, "UseGram=false") ...
    && contains(estimateSource, "r34.assertAOnlyCost") ...
    && ~contains(estimateSource, "options.UseGram");
check = ["zero failed formal trials"; "method order exact"; ...
    "exact profile pass vector"; "positive direct EVD counts"; ...
    "no Gram or subspace fallback path"; ...
    "Scheme G safeguard fallback set frozen"];
pass = [all(success); all(methodIdentity); all(profileIdentity); ...
    all(evdFinitePositive); directOnlySource; fallbackIdentity];
details = ["all 1400 results success"; "G_schur,C_enhanced,P_A"; ...
    "G=1 C=0 P_A=1"; "all methods report direct EVD work"; ...
    "successful r34 entry enforces assertAOnlyCost"; ...
    "no unknown post-freeze fallback reason"];
checks = table(check, pass);
[reason, ~, group] = unique(fallbackReason);
count = accumarray(group, 1);
fallbackSummary = table(reason, count);
end

function [checks, details, recomputed] = aggregateAudit( ...
    saved, results, aggregate, authorizationDigest)
identity = aggregate.identity;
identityPass = identity.authorized && identity.trialsExecuted == 1400 ...
    && identity.algorithmDigest == saved.identity.algorithmDigest ...
    && identity.designHash == saved.identity.designHash ...
    && identity.statisticsVersion == saved.identity.statisticsVersion ...
    && identity.statisticsHash == saved.identity.statisticsHash ...
    && identity.sourceDigest == saved.identity.sourceDigest ...
    && identity.r33Digest == saved.identity.r33Digest ...
    && identity.r34Digest == saved.identity.r34Digest ...
    && identity.frozenDependencyDigest ...
    == saved.identity.frozenDependencyDigest ...
    && identity.authorizationDigest == authorizationDigest;
recomputed = r41statsv2.summarizeFinal( ...
    saved.design, results, saved.protocol);
metricPass = isequaln(recomputed.perUser, aggregate.analysis.perUser) ...
    && isequaln(recomputed.summary, aggregate.analysis.summary) ...
    && isequaln(recomputed.paired, aggregate.analysis.paired) ...
    && isequaln(recomputed.coPrimaryGlobal, ...
    aggregate.analysis.coPrimaryGlobal) ...
    && isequaln(recomputed.pointwiseConsistency, ...
    aggregate.analysis.pointwiseConsistency) ...
    && isequaln(recomputed.perSnrConfirmatoryFamilies, ...
    aggregate.analysis.perSnrConfirmatoryFamilies);
secondReplay = r41statsv2.summarizeFinal( ...
    saved.design, results, saved.protocol);
bootstrapPass = isequaln(recomputed.coPrimaryGlobal, ...
    secondReplay.coPrimaryGlobal) ...
    && isequaln(recomputed.perSnrConfirmatoryFamilies, ...
    secondReplay.perSnrConfirmatoryFamilies) ...
    && recomputed.statisticsAudit.global.indexHash ...
    == secondReplay.statisticsAudit.global.indexHash;
sourcePass = r32.sourceDigest(aggregate.source) ...
    == saved.identity.sourceDigest;
check = ["aggregate provenance identity"; ...
    "raw-to-aggregate metric recomputation"; ...
    "bootstrap deterministic replay"; "aggregate source manifest"];
pass = [identityPass; metricPass; bootstrapPass; sourcePass];
details = ["authorized=true trialsExecuted=1400 and exact digests"; ...
    "raw shard results reproduce saved tables"; ...
    "global and per-SNR results plus index hash repeat exactly"; ...
    "saved aggregate source digest matches protocol"];
checks = table(check, pass);
end

function [checks, details] = timingAudit(saved, timing, authorizationDigest)
identity = timing.identity;
identityPass = identity.authorized ...
    && identity.performanceTrialsExecuted == 0 ...
    && identity.replayedExistingFinalRows == 20 ...
    && identity.newUsersGenerated == 0 ...
    && identity.designHash == saved.identity.designHash ...
    && identity.algorithmDigest == saved.identity.algorithmDigest ...
    && identity.statisticsHash == saved.identity.statisticsHash ...
    && identity.sourceDigest == saved.identity.sourceDigest ...
    && identity.authorizationDigest == authorizationDigest ...
    && ~identity.serverThroughputUsed;
rowsPass = height(timing.rows) == 180 ...
    && numel(unique(timing.design.positionId)) == 20 ...
    && all(groupcounts(timing.rows, "method").GroupCount == 60);
summaryPass = height(timing.summary) == 3 ...
    && all(ismember(["G_schur", "P_A", "C_enhanced"], ...
    timing.summary.method)) && height(timing.comparison) == 1;
check = ["matched timing provenance identity"; ...
    "matched timing row balance"; "matched timing methods and ratios"];
pass = [identityPass; rowsPass; summaryPass];
details = ["20 frozen rows, no new performance trials, no throughput timing"; ...
    "20 positions x 3 repetitions x 3 methods"; ...
    "G_schur, P_A, C_enhanced with G/C and G/P_A ratios"];
checks = table(check, pass);
end

function output = hashesToTable(design, hashes)
seed = design.seed;
positionId = design.positionId;
snrDb = design.snrDb;
observationHash = cellfun(@(item) item.observation, hashes);
snapshotsHash = cellfun(@(item) item.snapshots, hashes);
output = table(positionId, seed, snrDb, observationHash, snapshotsHash);
end

function pass = compareHashes(first, second)
pass = numel(first) == numel(second);
for index = 1:numel(first)
    pass = pass && first{index}.seed == second{index}.seed ...
        && first{index}.observation == second{index}.observation ...
        && first{index}.snapshots == second{index}.snapshots;
end
end
