function output = run_round40_schemeG(options)
%RUN_ROUND40_SCHEMEG Execute staged Scheme G development and calibration.

arguments
    options.NumWorkers (1, 1) double {mustBeInteger, mustBePositive} = 8
    options.BatchSize (1, 1) double {mustBeInteger, mustBePositive} = 4
    options.PoolType (1, 1) string ...
        {mustBeMember(options.PoolType, ["Threads", "Processes"])} = "Threads"
end

project = string(fileparts(fileparts(mfilename("fullpath"))));
addRequiredPaths(project);
protocol = r40SchemeGProtocol();
validateFrozenSystem(jad.defaultConfig(), protocol);
rootFolder = fullfile(project, "results", "full_spectrum", ...
    "round40_schemeG_full_aperture_profiled_v1");
if ~isfolder(rootFolder)
    mkdir(rootFolder);
end

algorithmSource = algorithmManifest(project);
algorithmDigest = r32.sourceDigest(algorithmSource);
reportingSource = reportingManifest(project);
frozenSource = frozenManifest(project);
sourceHashes = labelSources(algorithmSource, reportingSource, frozenSource);
writetable(sourceHashes, fullfile(rootFolder, "source_hashes.csv"));

[developmentInput, eSingle] = loadDevelopmentInputs(project, protocol);
developmentIdentity = baseIdentity(protocol, "development60", ...
    algorithmDigest, r32.sourceDigest(frozenSource));
[developmentResults, developmentEnvironment] = runStage( ...
    rootFolder, developmentInput.design, ...
    developmentInput.results, eSingle, developmentIdentity, ...
    protocol, options);
developmentFailures = failureTable( ...
    developmentInput.design, developmentResults);
writetable(developmentFailures, fullfile(rootFolder, "failures.csv"));
if height(developmentFailures) > 0
    saveStageFailure(rootFolder, developmentIdentity, ...
        developmentInput.design, developmentResults, ...
        developmentFailures, developmentEnvironment, sourceHashes);
    error("r40:DevelopmentTrialFailure", ...
        "At least one fixed Scheme G development row failed.");
end
assertNoSourceDrift(project, algorithmDigest, frozenSource);
developmentSummary = r40SummarizeSchemeG( ...
    developmentInput.design, developmentResults, ...
    protocol, "development60");
writeStageTables(rootFolder, developmentSummary, ...
    protocol.studyLabelDevelopment);
developmentFigureManifest = r40BuildSchemeGFigures( ...
    developmentSummary, rootFolder, protocol.studyLabelDevelopment);
developmentIdentity.completedRows = height(developmentInput.design);
developmentIdentity.hardGatePassed = developmentSummary.hardGatePassed;
developmentIdentity.calibrationAuthorized = ...
    developmentSummary.hardGatePassed;
developmentIdentity.calibrationRowsExecuted = 0;
developmentIdentity.finalTrialsReadOrExecuted = 0;
developmentIdentity.newUsersGenerated = 0;
identity = developmentIdentity; %#ok<NASGU>
design = developmentInput.design; %#ok<NASGU>
results = developmentResults; %#ok<NASGU>
summary = developmentSummary; %#ok<NASGU>
failures = developmentFailures; %#ok<NASGU>
environment = developmentEnvironment; %#ok<NASGU>
figureManifest = developmentFigureManifest; %#ok<NASGU>
save(fullfile(rootFolder, "result.mat"), "identity", "design", ...
    "results", "summary", "failures", "environment", ...
    "sourceHashes", "figureManifest", "-v7.3");

output = struct(protocol=protocol, folder=rootFolder, ...
    development=struct(identity=developmentIdentity, ...
    summary=developmentSummary, figureManifest=developmentFigureManifest), ...
    calibration=struct(), stoppedAfter="development60");
fprintf("ROUND40_SCHEME_G_DEVELOPMENT_COMPLETE users=%d pass=%d " + ...
    "final=0 new=0 profiles=1\n", height(design), ...
    developmentSummary.hardGatePassed);
if ~developmentSummary.hardGatePassed
    return;
end

assertNoSourceDrift(project, algorithmDigest, frozenSource);
[calibrationInput, calibrationE] = loadCalibrationInputs(project, protocol);
calibrationFolder = fullfile(rootFolder, "calibration600");
if ~isfolder(calibrationFolder)
    mkdir(calibrationFolder);
end
calibrationIdentity = baseIdentity(protocol, "calibration600", ...
    algorithmDigest, r32.sourceDigest(frozenSource));
calibrationIdentity.developmentAlgorithmDigest = algorithmDigest;
calibrationIdentity.developmentResultSha256 = fileHash( ...
    fullfile(rootFolder, "result.mat"));
calibrationIdentity.developmentGatePassed = true;
[calibrationResults, calibrationEnvironment] = runStage( ...
    calibrationFolder, calibrationInput.design, ...
    calibrationInput.results, calibrationE, calibrationIdentity, ...
    protocol, options);
calibrationFailures = failureTable( ...
    calibrationInput.design, calibrationResults);
writetable(calibrationFailures, ...
    fullfile(calibrationFolder, "failures.csv"));
if height(calibrationFailures) > 0
    saveStageFailure(calibrationFolder, calibrationIdentity, ...
        calibrationInput.design, calibrationResults, ...
        calibrationFailures, calibrationEnvironment, sourceHashes);
    error("r40:CalibrationTrialFailure", ...
        "At least one fixed Scheme G calibration row failed.");
end
assertNoSourceDrift(project, algorithmDigest, frozenSource);
calibrationSummary = r40SummarizeSchemeG( ...
    calibrationInput.design, calibrationResults, ...
    protocol, "calibration600");
writeStageTables(calibrationFolder, calibrationSummary, ...
    protocol.studyLabelCalibration);
calibrationFigureManifest = r40BuildSchemeGFigures( ...
    calibrationSummary, calibrationFolder, ...
    protocol.studyLabelCalibration);
calibrationIdentity.completedRows = height(calibrationInput.design);
calibrationIdentity.hardGatePassed = calibrationSummary.hardGatePassed;
calibrationIdentity.calibrationCandidatePassed = ...
    calibrationSummary.hardGatePassed;
calibrationIdentity.finalTrialsReadOrExecuted = 0;
calibrationIdentity.newUsersGenerated = 0;
identity = calibrationIdentity; %#ok<NASGU>
design = calibrationInput.design; %#ok<NASGU>
results = calibrationResults; %#ok<NASGU>
summary = calibrationSummary; %#ok<NASGU>
failures = calibrationFailures; %#ok<NASGU>
environment = calibrationEnvironment; %#ok<NASGU>
figureManifest = calibrationFigureManifest; %#ok<NASGU>
save(fullfile(calibrationFolder, "result.mat"), "identity", ...
    "design", "results", "summary", "failures", "environment", ...
    "sourceHashes", "figureManifest", "-v7.3");
output.calibration = struct(identity=calibrationIdentity, ...
    summary=calibrationSummary, ...
    figureManifest=calibrationFigureManifest);
output.stoppedAfter = "calibration600";
fprintf("ROUND40_SCHEME_G_CALIBRATION_COMPLETE users=%d pass=%d " + ...
    "final=0 new=0 profiles=1\n", height(design), ...
    calibrationSummary.hardGatePassed);
end

function addRequiredPaths(project)
addpath(project);
addpath(fullfile(project, "+r35", "common"));
addpath(fullfile(project, "+r36", "common"));
addpath(fullfile(project, "+r37", "singleProfile"));
addpath(fullfile(project, "+r38", "common"));
addpath(fullfile(project, "+r38", "schemeF"));
addpath(fullfile(project, "+r40", "schemeG"));
end

function validateFrozenSystem(cfg, protocol)
r35AssertCommonProtocol(cfg, r35CommonProtocol());
frozen = r34.config();
pass = cfg.numAntennas == protocol.system.N ...
    && cfg.numSubcarriers == protocol.system.M ...
    && frozen.r32.music.carrierCount == protocol.system.K ...
    && frozen.r32.music.subarraySize == protocol.system.L ...
    && frozen.r32.music.numSubarrays == protocol.system.P ...
    && ~frozen.implementation.useGram ...
    && isequal(frozen.r32.music.gridSizes, protocol.system.angleGridSizes) ...
    && frozen.r32.profile.halfWidthM == protocol.system.profileHalfWidthM ...
    && frozen.r32.profile.lambda == protocol.system.lambda;
if ~pass
    error("r40:FrozenSystemMismatch", ...
        "Scheme G does not match the frozen P_A system.");
end
end

function [input, references] = loadDevelopmentInputs(project, protocol)
inputFile = fullfile(project, "results", "full_spectrum", ...
    "round38_schemeF_raw_array_vpml_development_v1", "result.mat");
eFile = fullfile(project, "results", "full_spectrum", ...
    "round37_schemeE_single_profile_transport_v1", "result.mat");
assertHash(project, inputFile, protocol.input.developmentResultSha256);
assertHash(project, eFile, protocol.input.eSingleResultSha256);
input = load(inputFile, "identity", "design", "results");
e = load(eFile, "identity", "summary");
counts = groupcounts(input.design, "snrDb");
valid = input.identity.completedUsers == protocol.input.developmentUsers ...
    && input.identity.calibrationUsersReadOrExecuted == 0 ...
    && input.identity.finalTrialsReadOrExecuted == 0 ...
    && input.identity.newUsersGenerated == 0 ...
    && height(input.design) == protocol.input.developmentUsers ...
    && all(counts.GroupCount == protocol.input.developmentUsersPerSnr) ...
    && all(cellfun(@(x) x.success, input.results));
if ~valid
    error("r40:DevelopmentInputIdentityMismatch", ...
        "The frozen Scheme F development input is invalid.");
end
references = buildEReferences(e.summary.perUser, input.design, ...
    "development-overlap60");
end

function [input, references] = loadCalibrationInputs(project, protocol)
inputFile = fullfile(project, "results", "full_spectrum", ...
    "round38_schemeF_raw_array_vpml_calibration600_v1", "result.mat");
assertHash(project, inputFile, protocol.input.calibrationResultSha256);
input = load(inputFile, "identity", "design", "results", "summary");
counts = groupcounts(input.design, "snrDb");
valid = input.identity.completedUsers == protocol.input.calibrationUsers ...
    && input.identity.calibrationDataDigest ...
    == protocol.input.calibrationDataDigest ...
    && input.identity.finalTrialsReadOrExecuted == 0 ...
    && input.identity.newUsersGenerated == 0 ...
    && height(input.design) == protocol.input.calibrationUsers ...
    && all(counts.GroupCount == protocol.input.calibrationUsersPerSnr) ...
    && all(cellfun(@(x) x.success, input.results));
if ~valid
    error("r40:CalibrationInputIdentityMismatch", ...
        "The frozen Scheme F calibration input is invalid.");
end
references = buildEReferences(input.summary.perUser, input.design, "");
end

function references = buildEReferences(perUser, design, requiredSubset)
[found, locations] = ismember(design.seed, perUser.seed);
if ~all(found)
    error("r40:ESinglePairingMismatch", ...
        "E single-profile references cannot be paired by seed.");
end
if requiredSubset ~= "" ...
        && any(perUser.subset(locations) ~= requiredSubset)
    error("r40:DevelopmentSubsetLeak", ...
        "Stage 1 references must be the fixed development overlap only.");
end
references = cell(height(design), 1);
for index = 1:height(design)
    row = perUser(locations(index), :);
    references{index} = struct(thetaDeg=row.theta_E_single, ...
        rangeM=row.range_E_single, runtimeSeconds=row.runtime_E_single, ...
        responseEvaluationCount=row.responseCount_E_single, ...
        musicEvaluationCount=row.musicCount_E_single, ...
        evdCount=row.evdCount_E_single, ...
        completeProfilePassCount=row.profilePasses_E_single, ...
        profileEvaluationCount=row.profileEvaluations_E_single);
end
end

function identity = baseIdentity(protocol, stage, algorithmDigest, frozenDigest)
identity = struct(version=protocol.version, date=protocol.date, stage=stage, ...
    evidenceRole=protocol.evidenceRole, protocol=protocol, ...
    algorithmSourceDigest=algorithmDigest, ...
    frozenReadOnlySourceDigest=frozenDigest, completedRows=0, ...
    developmentRowsExecuted=0, calibrationRowsExecuted=0, ...
    finalTrialsReadOrExecuted=0, newUsersGenerated=0, ...
    schemesABDExecuted=false, parameterTuningPerformed=false, ...
    secondCompleteProfileExecuted=false);
end

function [results, environment] = runStage(folder, design, ...
    baseline, eReferences, identity, protocol, options)
cfg = jad.defaultConfig();
scan = fsjad.prepareScan(cfg);
checkpointFile = fullfile(folder, "checkpoint.mat");
results = cell(height(design), 1);
environment = struct();
if isfile(checkpointFile)
    saved = load(checkpointFile, "identity", "design", ...
        "results", "environment");
    if ~checkpointCompatible(saved.identity, identity) ...
            || ~isequaln(saved.design, design)
        error("r40:StaleCheckpoint", ...
            "The Scheme G checkpoint has a different frozen identity.");
    end
    results = saved.results;
    environment = saved.environment;
end
pool = [];
pending = find(cellfun(@isempty, results));
if ~isempty(pending)
    pool = preparePool(options.PoolType, options.NumWorkers);
    for first = 1:options.BatchSize:numel(pending)
        rows = pending(first:min(first+options.BatchSize-1, numel(pending)));
        rowDesign = design(rows, :);
        rowBaseline = baseline(rows);
        rowE = eReferences(rows);
        batch = cell(numel(rows), 1);
        parfor index = 1:numel(rows)
            batch{index} = r40SchemeGTrial(cfg, scan, ...
                rowDesign(index, :), rowBaseline{index}, rowE{index}, ...
                rows(index), r34.config(), protocol);
        end
        results(rows) = batch;
        environment = environmentRecord(pool, options.BatchSize);
        save(checkpointFile, "identity", "design", "results", ...
            "environment", "-v7.3");
        fprintf("R40 %s: %d/%d\n", identity.stage, ...
            nnz(~cellfun(@isempty, results)), height(design));
    end
end
if ~isempty(pool)
    environment = environmentRecord(pool, options.BatchSize);
    delete(pool);
end
end

