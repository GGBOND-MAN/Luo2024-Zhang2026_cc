    sigmaTauSeconds=[0, 1e-13, 1e-12, 1e-11, 1e-10, 1e-9], ...
    modes=["array", "common"], ...
    positionCount=20, snrDb=[-10, 0, 20], ...
    positionSeed=74000000, trialSeedRoot=74100000, tauSeed=74200000, ...
    methods=["P_A", "P_FALF", "P_FACR"], ...
    sharedNoiseAcrossLevels=true, ...
