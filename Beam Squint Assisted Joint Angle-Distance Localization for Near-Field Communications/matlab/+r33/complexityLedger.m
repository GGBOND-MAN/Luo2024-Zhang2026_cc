disclosure = ["K_Z and G_Z were not uniquely disclosed; neither is imputed"; ...
    "K=2047, L=160, P=97, G_C=3083"; ...
    "K=2047, L=160, P=97, G_A=93"; ...
    "transparent assumed baseline: K_p=5, L_p=128, P_p=129, G_p=3083"];
output = table(method, publishedOrReference, acceptedAOrder, ...
    attemptedGramOrder, musicScoring, disclosure);
end

function rows = actualRows(cfg, protocol, counts)
methods = ["C_enhanced", "P_A", "C_public"];
rows = table();
for index = 1:height(counts)
    for method = methods
        [K, L, P, G, Er, matrixMacs, evdUnits, recoveryMacs, solver] = ...
            dimensions(method, protocol, counts(index, :));
        Es = counts.Es(index);
        Ef = counts.Ef(index);
        sparseTerms = Es*cfg.numAntennas*protocol.r32.front.carrierCount;
        fullTerms = (Ef+Er)*cfg.numAntennas*cfg.numSubcarriers;
        alignmentTerms = K*P*L;
        searchTerms = K*G*L;
        rows = [rows; table(counts.seed(index), counts.snrDb(index), ...
            method, K, L, P, G, Es, Ef, Er, sparseTerms, fullTerms, ...
            alignmentTerms, matrixMacs, evdUnits, recoveryMacs, ...
            searchTerms, sparseTerms+fullTerms, sparseTerms+fullTerms, ...
            alignmentTerms, searchTerms, solver, ...
            'VariableNames', {'seed', 'snrDb', 'method', 'K', 'L', ...
            'P', 'G', 'Es', 'Ef', 'Er', 'sparseResponseTerms', ...
            'fullResponseTerms', 'phaseAlignmentMacs', ...
            'subspaceMatrixFormationMacs', 'evdCubicUnits', ...
            'subspaceRecoveryMacs', 'musicInnerProductMacs', ...
            'responseSqrtTerms', 'responseExponentialTerms', ...
            'alignmentExponentialTerms', 'musicSteeringExponentialTerms', ...
            'subspaceSolver'})]; %#ok<AGROW>
    end
end
end

function [K, L, P, G, Er, matrixMacs, evdUnits, recoveryMacs, solver] = ...
    dimensions(method, protocol, row)
if method == "C_public"
    K = protocol.r32.publicC.carrierCount;
    L = protocol.r32.publicC.subarraySize;
    P = 256-L+1;
    G = row.G_public;
    Er = 0;
    matrixMacs = row.publicMatrixFormationMacs;
    evdUnits = row.publicEvdCubicUnits;
    recoveryMacs = row.publicRecoveryMacs;
    solver = solverName(row, "publicSolver", ...
        "direct-L-by-L-EVD-because-P-not-less-than-L");
else
    K = protocol.r32.music.carrierCount;
    L = protocol.r32.music.subarraySize;
    P = protocol.r32.music.numSubarrays;
    if method == "C_enhanced"
        G = row.G_C;
        Er = 0;
    else
        G = row.G_A;
        Er = row.Er;
    end
    matrixMacs = row.enhancedMatrixFormationMacs;
    evdUnits = row.enhancedEvdCubicUnits;
    recoveryMacs = row.enhancedRecoveryMacs;
    solver = solverName(row, "enhancedSolver", ...
        "smaller-P-by-P-Gram-EVD-with-frozen-fallback");
end
end

function solver = solverName(row, field, defaultValue)
solver = defaultValue;
if ismember(field, string(row.Properties.VariableNames))
    solver = string(row.(field));
end
end

function summary = summarizeActual(rows)
metrics = ["Es", "Ef", "Er", "sparseResponseTerms", ...
    "fullResponseTerms", "phaseAlignmentMacs", ...
    "subspaceMatrixFormationMacs", "evdCubicUnits", ...
    "subspaceRecoveryMacs", "musicInnerProductMacs", ...
    "responseSqrtTerms", "responseExponentialTerms", ...
    "alignmentExponentialTerms", "musicSteeringExponentialTerms"];
summary = table();
for method = unique(rows.method, "stable").'
    selected = rows.method == method;
    values = zeros(1, 4*numel(metrics));
    names = strings(1, 4*numel(metrics));
    cursor = 1;
    for metric = metrics
        vector = rows.(metric)(selected);
        values(cursor:cursor+3) = [min(vector), median(vector), ...
            mean(vector), max(vector)];
        names(cursor:cursor+3) = ["min_"+metric, "median_"+metric, ...
            "mean_"+metric, "max_"+metric];
        cursor = cursor+4;
    end
    entry = array2table(values, VariableNames=cellstr(names));
    entry = addvars(entry, method, nnz(selected), Before=1, ...
        NewVariableNames=["method", "n"]);
    summary = [summary; entry]; %#ok<AGROW>
end
end

function output = subspaceComparison(protocol)
K = protocol.r32.music.carrierCount;
L = protocol.r32.music.subarraySize;
P = protocol.r32.music.numSubarrays;
quantity = ["matrix_formation_MAC_units"; "EVD_cubic_units"; ...
    "recovery_MAC_units"];
direct = [K*P*L^2; K*L^3; 0];
gram = [K*L*P^2; K*P^3; 3*K*L*P];
reductionPercent = 100*(1-gram./direct);
reductionPercent(direct == 0) = nan;
output = table(quantity, direct, gram, reductionPercent, ...
    'VariableNames', {'quantity', 'directReference', ...
    'gramImplementation', 'nominalReductionPercent'});
end
