function aggregate_round31_l06_solver_repair()
%AGGREGATE_ROUND31_L06_SOLVER_REPAIR Compare old and repaired L06 outputs.

project = string(fileparts(fileparts(mfilename("fullpath"))));
addpath(project);
raw = r31.loadRound30Raw(project, IncludeBaselineResults=false);
folder = fullfile(project, "results", "full_spectrum", ...
    "round31_l06_scalar_repair_v2");
saved = load(fullfile(folder, "result.mat"), "identity", "results");
marker = load(fullfile(folder, "COMPLETE.mat"), "identity", "failed");
if ~isequaln(saved.identity, marker.identity) || any(marker.failed)
    error("r31:IncompleteL06Repair", ...
        "The L06 repair result is incomplete or contains retained failures.");
end

design = raw.pilot.design;
oldTheta = cellfun(@(item) item.oldThetaDeg, saved.results);
newTheta = cellfun(@(item) item.newThetaDeg, saved.results);
oldRange = cellfun(@(item) item.oldRangeM, saved.results);
newRange = cellfun(@(item) item.newRangeM, saved.results);
perUser = table(design.seed, design.snrDb, design.truthThetaDeg, ...
    design.truthRangeM, oldTheta, newTheta, oldRange, newRange, ...
    newTheta-oldTheta, newRange-oldRange, ...
    cellfun(@(item) item.angleSolver.retentionMargin, saved.results), ...
    cellfun(@(item) item.profileSolver.retentionMargin, saved.results), ...
    'VariableNames', {'seed', 'snrDb', 'truthThetaDeg', 'truthRangeM', ...
    'oldThetaDeg', 'newThetaDeg', 'oldRangeM', 'newRangeM', ...
    'thetaChangeDeg', 'rangeChangeM', 'angleRetentionMargin', ...
    'profileRetentionMargin'});
summary = table();
for snrDb = [-10, 0, 20]
    rows = design.snrDb == snrDb;
    for method = ["old", "repaired"]
        if method == "old"
            theta = oldTheta(rows);
            range = oldRange(rows);
        else
            theta = newTheta(rows);
            range = newRange(rows);
        end
        angleError = theta-design.truthThetaDeg(rows);
        rangeError = range-design.truthRangeM(rows);
        positionError = hypot( ...
            range.*sind(theta)-design.truthRangeM(rows) ...
            .*sind(design.truthThetaDeg(rows)), ...
            range.*cosd(theta)-design.truthRangeM(rows) ...
            .*cosd(design.truthThetaDeg(rows)));
        entry = table(snrDb, method, nnz(rows), ...
            sqrt(mean(angleError.^2)), sqrt(mean(rangeError.^2)), ...
            sqrt(mean(positionError.^2)), quantile(abs(rangeError), 0.95), ...
            mean(abs(rangeError) > 1), ...
            'VariableNames', {'snrDb', 'method', 'n', 'angleRmseDeg', ...
            'rangeRmseM', 'positionRmseM', 'p95RangeM', 'missOver1m'});
        summary = [summary; entry]; %#ok<AGROW>
    end
end
writetable(perUser, fullfile(folder, "per_user_old_vs_repaired.csv"));
writetable(summary, fullfile(folder, "summary_old_vs_repaired.csv"));
identity = struct(pilotHash=raw.pilotHash, ...
    baselineHash=raw.baselineHash, source=raw.source);
save(fullfile(folder, "aggregate.mat"), ...
    "saved", "perUser", "summary", "identity", "-v7.3");
fprintf("ROUND31_L06_REPAIR_AGGREGATE_COMPLETE maxThetaChange=%g maxRangeChange=%g\n", ...
    max(abs(perUser.thetaChangeDeg)), max(abs(perUser.rangeChangeM)));
end
