function output = repair_round56_q_anchored_split_consensus_summary()
%REPAIR_ROUND56_Q_ANCHORED_SPLIT_CONSENSUS_SUMMARY Repair summary-only bug.

project = string(fileparts(fileparts(mfilename("fullpath"))));
r41.addPaths(project);
protocol = r56.config();
folder = fullfile(project, "results", "full_spectrum", ...
    "round56_q_anchored_split_consensus_development_v1");
resultFile = fullfile(folder, "result.mat");
if isfile(resultFile)
    error("r56:OutputExists", "The immutable repaired R56 result exists.");
end

checkpointFile = fullfile(folder, "checkpoint.mat");
if ~isfile(checkpointFile)
    error("r56:MissingCheckpoint", "The completed R56 checkpoint is missing.");
end
saved = load(checkpointFile, "identity", "results");
design = r56.design(protocol);
if numel(saved.results) ~= height(design) ...
        || any(cellfun(@isempty, saved.results)) ...
        || any(cellfun(@(item) ~item.success, saved.results))
    error("r56:IncompleteCheckpoint", ...
        "The summary repair requires 210 successful frozen trial rows.");
end
if r32.designHash(design) ~= saved.identity.designHash
    error("r56:RepairDesignMismatch", ...
        "The repaired summary design does not match the trial checkpoint.");
end

trialSource = readtable(fullfile(folder, "source_hashes.csv"), ...
    TextType="string");
if r32.sourceDigest(trialSource) ~= saved.identity.sourceDigest
    error("r56:RepairTrialSourceMismatch", ...
        "The recorded trial source does not match the checkpoint identity.");
end
summarySource = r56.manifest(project);
allowedDifference = ["+r56/summarize.m"; ...
    "experiments/repair_round56_q_anchored_split_consensus_summary.m"];
trialKernel = sortrows(trialSource( ...
    ~ismember(trialSource.path, allowedDifference), :), "path");
summaryKernel = sortrows(summarySource( ...
    ~ismember(summarySource.path, allowedDifference), :), "path");
if ~isequal(trialKernel, summaryKernel)
    error("r56:RepairKernelDrift", ...
        "A trial-computation source changed after checkpoint completion.");
end

frozenR53Digest = r32.sourceDigest(r53.manifest(project));
frozenPfaDigest = r32.sourceDigest(r45.manifest(project));
if frozenR53Digest ~= saved.identity.frozenR53Digest ...
        || frozenPfaDigest ~= saved.identity.frozenPfaDigest
    error("r56:RepairFrozenDependencyDrift", ...
        "A frozen R53 or P_FA dependency changed after the trial run.");
end

summary = r56.summarize(design, saved.results, protocol);
sourceDigest = r32.sourceDigest(summarySource);
designInfo = dir(fullfile(folder, "design.csv"));
completionInfo = dir(fullfile(folder, "failures.csv"));
observedTrialWallSeconds = ...
    max(0, (completionInfo.datenum-designInfo.datenum)*86400); %#ok<DATNM>
runtime = table(height(design), observedTrialWallSeconds, ...
    observedTrialWallSeconds/height(design), ...
    mean(summary.perUser.backendSeconds), ...
    'VariableNames', {'rows', 'observedTrialWallSeconds', ...
    'observedWallSecondsPerRow', 'meanCompleteBackendSeconds'});
audit = table(["trial-source-digest-preserved"; ...
    "trial-kernel-unchanged"; "frozen-R53-unchanged"; ...
    "frozen-P_FA-unchanged"; "summary-only-repair"], ...
    [true; true; true; true; true], ...
    [saved.identity.sourceDigest; "all-paths-except-summarize-and-repair"; ...
    frozenR53Digest; frozenPfaDigest; sourceDigest], ...
    'VariableNames', {'check', 'pass', 'detail'});

writetable(summarySource, fullfile(folder, "summary_source_hashes.csv"));
writetable(audit, fullfile(folder, "summary_repair_audit.csv"));
writetable(summary.perUser, fullfile(folder, "per_row.csv"));
writetable(summary.methodSummary, fullfile(folder, "method_summary.csv"));
writetable(summary.comparisons, fullfile(folder, "performance_tables.csv"));
writetable(summary.bootstrap, fullfile(folder, "bootstrap.csv"));
writetable(summary.mechanism, fullfile(folder, "mechanism.csv"));
writetable(summary.mechanismBySnr, ...
    fullfile(folder, "mechanism_by_snr.csv"));
writetable(summary.gate, fullfile(folder, "gate.csv"));
writetable(runtime, fullfile(folder, "runtime.csv"));

finalIdentity = struct(version=protocol.version, completedRows=height(design), ...
    failedRows=0, trialSourceDigest=saved.identity.sourceDigest, ...
    summarySourceDigest=sourceDigest, frozenR53Digest=frozenR53Digest, ...
    frozenPfaDigest=frozenPfaDigest, designHash=saved.identity.designHash, ...
    summaryOnlyRepair=true, trialKernelUnchanged=true, ...
    finalRowsRead=false, R53R54R55RowsRead=false, ...
    parameterTuningPerformed=false, ...
    developmentPass=summary.developmentPass, ...
    completedAt=string(datetime("now", "TimeZone", "Asia/Shanghai")));
results = saved.results;
save(resultFile, "protocol", "finalIdentity", "design", "results", ...
    "summary", "runtime", "audit", "trialSource", ...
    "summarySource", "-v7");
output = struct(folder=folder, identity=finalIdentity, ...
    summary=summary, runtime=runtime, audit=audit);
fprintf("ROUND56_PFALFSC_SUMMARY_REPAIRED pass=%d rows=%d failures=0\n", ...
    summary.developmentPass, height(design));
disp(summary.gate);
disp(summary.comparisons(summary.comparisons.candidate == "P_FALF_SC", :));
disp(summary.mechanism);
end
