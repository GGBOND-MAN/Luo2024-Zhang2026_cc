function output = analyze_round44_failure(options)
%ANALYZE_ROUND44_FAILURE Read-only mechanism audit with a truth-angle oracle.

arguments
    options.NumWorkers (1, 1) double {mustBeInteger, mustBePositive} = 4
    options.PoolType (1, 1) string ...
        {mustBeMember(options.PoolType, ["Threads", "Processes"])} = "Threads"
end

project = string(fileparts(fileparts(mfilename("fullpath"))));
addpath(project);
addpath(fullfile(project, "+r38", "schemeF"));
folder = fullfile(project, "results", "full_spectrum", ...
    "round44_clock_invariant_sequential_development_v1", "positions_10");
saved = load(fullfile(folder, "result.mat"), ...
    "design", "results", "protocol", "identity");
if saved.identity.finalTrialsReadOrExecuted ~= 0
    error("r44:FailureAuditIdentity", ...
        "The failure audit cannot consume final-test rows.");
end
pool = gcp("nocreate");
requiredClass = "parallel.ThreadPool";
if options.PoolType == "Processes"
    requiredClass = "parallel.ProcessPool";
end
if ~isempty(pool) && string(class(pool)) ~= requiredClass
    delete(pool);
    pool = [];
end
if isempty(pool)
    parpool(options.PoolType, options.NumWorkers);
end
cfg = jad.defaultConfig();
scan = fsjad.prepareScan(cfg);
numRows = height(saved.design);
oracle = cell(numRows, 1);
parfor index = 1:numRows
    row = saved.design(index, :);
    replay = fsjad.replayRound27Data(cfg, scan, row);
    carriers = saved.results{index}.h.contextCarrierIndex;
    context = r42.prepareContext(cfg, scan, replay.observation, ...
        replay.snapshots(:, carriers+1), carriers);
    centerRangeM = saved.results{index}.h.front.selected.rangeM;
    oracle{index} = r44.profileVpRange(cfg, context, ...
        row.truthThetaDeg, centerRangeM, saved.protocol);
end

snrDb = saved.design.snrDb;
truthRangeM = saved.design.truthRangeM;
estimatedAngleDeg = cellfun(@(x) x.h.H_seqVP.thetaDeg, saved.results);
estimatedRangeM = cellfun(@(x) x.h.H_seqVP.rangeM, saved.results);
frontRangeM = cellfun(@(x) x.h.front.selected.rangeM, saved.results);
oracleRangeM = cellfun(@(x) x.value, oracle);
endpointHit = cellfun(@(x) x.h.vpProfile.endpointHit, saved.results);
nearBoundary = cellfun(@(x) x.h.vpProfile.nearBoundary, saved.results);
selectedScore = cellfun(@(x) x.h.vpProfile.score, saved.results);
frontScore = zeros(numRows, 1);
truthScore = zeros(numRows, 1);
for index = 1:numRows
    replay = fsjad.replayRound27Data(cfg, scan, saved.design(index, :));
    carriers = saved.results{index}.h.contextCarrierIndex;
    context = r42.prepareContext(cfg, scan, replay.observation, ...
        replay.snapshots(:, carriers+1), carriers);
    frontScore(index) = r38RawArrayVpmlScore(cfg, context, ...
        estimatedAngleDeg(index), frontRangeM(index));
    truthScore(index) = r38RawArrayVpmlScore(cfg, context, ...
        estimatedAngleDeg(index), truthRangeM(index));
end
rangeErrorM = estimatedRangeM-truthRangeM;
oracleRangeErrorM = oracleRangeM-truthRangeM;
perUser = table(saved.design.positionId, saved.design.seed, snrDb, ...
    saved.design.truthThetaDeg, truthRangeM, estimatedAngleDeg, ...
    frontRangeM, estimatedRangeM, rangeErrorM, oracleRangeM, ...
    oracleRangeErrorM, endpointHit, nearBoundary, selectedScore, ...
    frontScore, truthScore, selectedScore-frontScore, ...
    selectedScore-truthScore, ...
    'VariableNames', {'positionId', 'seed', 'snrDb', 'truthThetaDeg', ...
    'truthRangeM', 'estimatedAngleDeg', 'frontRangeM', ...
    'estimatedRangeM', 'rangeErrorM', 'oracleRangeM', ...
    'oracleRangeErrorM', 'endpointHit', 'nearBoundary', ...
    'selectedScore', 'frontScore', 'truthScore', ...
    'selectedMinusFrontScore', 'selectedMinusTruthScore'});
summary = table();
for snr = saved.protocol.development.snrDb
    selected = perUser.snrDb == snr;
    entry = table(snr, sum(perUser.endpointHit(selected)), ...
        sum(perUser.nearBoundary(selected)), ...
        sqrt(mean(perUser.rangeErrorM(selected).^2)), ...
        sqrt(mean(perUser.oracleRangeErrorM(selected).^2)), ...
        mean(abs(perUser.estimatedRangeM(selected) ...
        -perUser.frontRangeM(selected))), ...
        max(abs(perUser.rangeErrorM(selected))), ...
        median(perUser.selectedMinusTruthScore(selected)), ...
        'VariableNames', {'snrDb', 'endpointHits', 'nearBoundaryHits', ...
        'estimatedAngleRangeRmseM', 'truthAngleRangeRmseM', ...
        'meanAbsDisplacementFromFrontM', 'maxAbsRangeErrorM', ...
        'medianSelectedMinusTruthScore'});
    summary = [summary; entry]; %#ok<AGROW>
end
writetable(perUser, fullfile(folder, "failure_diagnostics.csv"));
writetable(summary, fullfile(folder, "failure_mechanism_summary.csv"));
identity = struct(version="R44-read-only-failure-audit-v1", ...
    date="2026-09-17", estimationRowsAdded=0, ...
    oracleUsedForMethodSelection=false, finalDataRead=false);
save(fullfile(folder, "failure_analysis.mat"), ...
    "identity", "perUser", "summary", "oracle");
output = struct(identity=identity, perUser=perUser, summary=summary);
disp(summary);
end
