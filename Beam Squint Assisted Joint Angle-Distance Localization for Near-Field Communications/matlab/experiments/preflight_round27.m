function preflight_round27
%PREFLIGHT_ROUND27 Gate long jobs on tests, an outlier replay, and smoke resume.
project=string(fileparts(fileparts(mfilename('fullpath'))));
originalPath=path;
addpath(project);
cleanup=onCleanup(@() path(originalPath));
folder=fullfile(project,"results","full_spectrum","round27_preflight");
if ~isfolder(folder)
    mkdir(folder);
end
tests=[fullfile(project,"tests","round27ConvergenceTest.m"), ...
    fullfile(project,"tests","round27WorkflowTest.m"), ...
    fullfile(project,"tests","round27PublishedFormulaAuditTest.m"), ...
    fullfile(project,"tests","localMusicSpectrumTest.m"), ...
    fullfile(project,"tests","testFullSpectrumTheory.m")];
testResults=runtests(cellstr(tests));
save(fullfile(folder,"test_results.mat"),"testResults");
assertSuccess(testResults);
setup=fsjad.round27Setup(project,1000,"formal");
cfg=setup.cfg;
scan=fsjad.prepareScan(cfg);
row=setup.design(setup.design.seed==36400431,:);
q=fsjad.exactSpectralResponse(cfg,deg2rad(row.truthThetaDeg),row.truthRangeM,scan);
stream=RandStream("mt19937ar",Seed=row.seed);
variance=mean(abs(q).^2)/10^(row.snrDb/10);
beta=exp(1i*2*pi*rand(stream));
z=beta*q+sqrt(variance/2)*(randn(stream,cfg.numSubcarriers,1) ...
    +1i*randn(stream,cfg.numSubcarriers,1));
old=fsjad.angleMultistartProfileEstimate(cfg,z,scan,setup.zhang.frontOffsetsDeg);
short=fsjad.convergedFrontEstimate(cfg,z,scan,old, ...
    MaxIterations=setup.protocol.maxIterations, ...
    StepTolerance=setup.protocol.stepTolerance);
long=fsjad.convergedFrontEstimate(cfg,z,scan,old, ...
    MaxIterations=setup.protocol.stabilityMaxIterations, ...
    StepTolerance=setup.protocol.stepTolerance);
scoreDifference=abs(short.score-long.score);
thetaDifferenceDeg=abs(short.thetaDeg-long.thetaDeg);
rangeDifferenceM=abs(short.rangeM-long.rangeM);
numericallyStable=short.converged && long.converged ...
    && short.score>=old.score-setup.protocol.stabilityScoreTolerance ...
    && long.score>=old.score-setup.protocol.stabilityScoreTolerance ...
    && scoreDifference<=setup.protocol.stabilityScoreTolerance ...
    && thetaDifferenceDeg<=setup.protocol.stabilityThetaToleranceDeg ...
    && rangeDifferenceM<=setup.protocol.stabilityRangeToleranceM ...
    && short.stationarity<=setup.protocol.stepTolerance ...
    && long.stationarity<=setup.protocol.stepTolerance;
outlier=table(row.seed,old.rangeM-row.truthRangeM, ...
    short.rangeM-row.truthRangeM,long.rangeM-row.truthRangeM, ...
    old.converged,short.converged,long.converged, ...
    short.stationarity,long.stationarity,short.score-old.score, ...
    scoreDifference,thetaDifferenceDeg,rangeDifferenceM,numericallyStable, ...
    'VariableNames',{'seed','oldRangeErrorM','shortRangeErrorM', ...
    'longRangeErrorM','oldConverged','shortConverged','longConverged', ...
    'shortStationarity','longStationarity','shortScoreGain', ...
    'scoreDifference','thetaDifferenceDeg','rangeDifferenceM', ...
    'numericallyStable'});
writetable(outlier,fullfile(folder,"outlier_replay.csv"));
save(fullfile(folder,"outlier_replay.mat"),"row","old","short","long");
assert(numericallyStable,"fsjad:Round27OutlierNumericallyUnstable", ...
    "The 200/400 iteration replay is numerically inconsistent. Inspect round27_preflight.");
smokeRoot=string(tempname(folder));
run_round27_convergence_shard(1,1,CountPerSnr=1,NumWorkers=2,BatchSize=1, ...
    Protocol="smoke",OutputRoot=smokeRoot);
run_round27_convergence_shard(1,1,CountPerSnr=1,NumWorkers=2,BatchSize=1, ...
    Protocol="smoke",OutputRoot=smokeRoot);
aggregate_round27_convergence(smokeRoot);
assert(isfile(fullfile(smokeRoot,"aggregate","paired_summary.csv")) ...
    && isfile(fullfile(smokeRoot,"aggregate","method_summary.csv")), ...
    "fsjad:Round27SmokeAggregateMissing");
source=setup.source;
matlabVersion=version;
save(fullfile(folder,"preflight_passed.mat"), ...
    "source","matlabVersion","outlier");
disp(outlier);
fprintf('ROUND27_PREFLIGHT_PASSED %s\n',folder);
end
