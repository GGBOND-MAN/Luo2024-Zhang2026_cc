function output = run_round44_timing_stress(options)
%RUN_ROUND44_TIMING_STRESS Compare end-to-end delay sensitivity to P_A.

arguments
    options.NumWorkers (1, 1) double {mustBeInteger, mustBePositive} = 4
    options.PoolType (1, 1) string ...
        {mustBeMember(options.PoolType, ["Threads", "Processes"])} = "Threads"
end

project = string(fileparts(fileparts(mfilename("fullpath"))));
addpath(project);
addpath(fullfile(project, "+r38", "schemeF"));
folder = fullfile(project, "results", "full_spectrum", ...
    "round44_clock_invariant_sequential_development_v1", "positions_10");
saved = load(fullfile(folder, "result.mat"), ...
    "design", "results", "protocol", "identity");
if ~saved.identity.pilotPass || saved.identity.finalTrialsReadOrExecuted ~= 0
    error("r44:TimingStressIdentity", ...
        "The timing stress requires the passed R44 development pilot.");
end
selected = find(saved.design.snrDb == saved.protocol.timingStress.snrDb);
delays = saved.protocol.timingStress.residualDelaySeconds;
methods = ["P_A", "H_seqVP"];
numConditions = numel(selected)*numel(delays);
records = cell(numConditions, 1);
pool = gcp("nocreate");
requiredClass = "parallel.ThreadPool";
if options.PoolType == "Processes"
    requiredClass = "parallel.ProcessPool";
end
if ~isempty(pool) && string(class(pool)) ~= requiredClass
    delete(pool);
    pool = [];
end
if isempty(pool)
    parpool(options.PoolType, options.NumWorkers);
end
cfg = jad.defaultConfig();
scan = fsjad.prepareScan(cfg);
parfor conditionIndex = 1:numConditions
    positionIndex = ceil(conditionIndex/numel(delays));
    delayIndex = mod(conditionIndex-1, numel(delays))+1;
    designIndex = selected(positionIndex);
    row = saved.design(designIndex, :);
    replay = fsjad.replayRound27Data(cfg, scan, row);
    [zDelayed, yDelayed] = r32.applyResidualDelay(cfg, ...
        replay.observation, replay.snapshots, delays(delayIndex));
    pa = r34.estimate(cfg, zDelayed, yDelayed, scan, "P_A", r34.config());
    h = r44.estimate(cfg, zDelayed, yDelayed, scan, saved.protocol);
    zero = saved.results{designIndex};
    zeroTheta = [zero.pa.thetaDeg, zero.h.H_seqVP.thetaDeg];
    zeroRange = [zero.pa.rangeM, zero.h.H_seqVP.rangeM];
    delayedTheta = [pa.thetaDeg, h.H_seqVP.thetaDeg];
    delayedRange = [pa.rangeM, h.H_seqVP.rangeM];
    records{conditionIndex} = table( ...
        repmat(row.positionId, 2, 1), repmat(row.seed, 2, 1), ...
        repmat(delays(delayIndex), 2, 1), ...
        repmat(delays(delayIndex)*1e9, 2, 1), methods(:), ...
        repmat(row.truthThetaDeg, 2, 1), ...
        repmat(row.truthRangeM, 2, 1), zeroTheta(:), zeroRange(:), ...
        delayedTheta(:), delayedRange(:), ...
        delayedTheta(:)-zeroTheta(:), delayedRange(:)-zeroRange(:), ...
        delayedTheta(:)-row.truthThetaDeg, delayedRange(:)-row.truthRangeM, ...
        'VariableNames', {'positionId', 'seed', 'delaySeconds', ...
        'delayNs', 'method', 'truthThetaDeg', 'truthRangeM', ...
        'zeroThetaDeg', 'zeroRangeM', 'delayedThetaDeg', ...
        'delayedRangeM', 'angleShiftDeg', 'rangeShiftM', ...
        'angleErrorDeg', 'rangeErrorM'});
end
rows = vertcat(records{:});
summary = table();
for method = methods
    zeroRows = saved.summary.perUser(saved.summary.perUser.method == method ...
        & saved.summary.perUser.snrDb == saved.protocol.timingStress.snrDb, :);
    zeroAngleMse = mean(zeroRows.angleErrorDeg.^2);
    zeroRangeMse = mean(zeroRows.rangeErrorM.^2);
    for delayIndex = 1:numel(delays)
        selectedRows = rows.method == method ...
            & rows.delaySeconds == delays(delayIndex);
        current = rows(selectedRows, :);
        entry = table(method, delays(delayIndex), delays(delayIndex)*1e9, ...
            max(abs(current.angleShiftDeg)), ...
            max(abs(current.rangeShiftM)), mean(current.rangeShiftM), ...
            mean(current.angleErrorDeg.^2)/zeroAngleMse, ...
            mean(current.rangeErrorM.^2)/zeroRangeMse, ...
            'VariableNames', {'method', 'delaySeconds', 'delayNs', ...
            'maxAbsAngleShiftDeg', 'maxAbsRangeShiftM', ...
            'meanRangeShiftM', 'angleMseRatioToZero', ...
            'rangeMseRatioToZero'});
        summary = [summary; entry]; %#ok<AGROW>
    end
end
hRows = summary.method == "H_seqVP";
angleInvariantPass = all(summary.maxAbsAngleShiftDeg(hRows) ...
    <= saved.protocol.timingStress.maxAngleShiftDeg);
rangeInvariantPass = all(summary.maxAbsRangeShiftM(hRows) ...
    <= saved.protocol.timingStress.maxRangeShiftM);
gate = table(angleInvariantPass, rangeInvariantPass, ...
    angleInvariantPass && rangeInvariantPass, ...
    'VariableNames', {'angleInvariantPass', ...
    'rangeInvariantPass', 'timingStressPass'});
writetable(rows, fullfile(folder, "timing_stress_rows.csv"));
writetable(summary, fullfile(folder, "timing_stress_summary.csv"));
writetable(gate, fullfile(folder, "timing_stress_gate.csv"));
identity = struct(version="R44-end-to-end-timing-stress-v1", ...
    date="2026-09-17", evidenceRole="prespecified-secondary-stress", ...
    delaysSeconds=delays, estimatorSelectionChanged=false, ...
    finalDataRead=false, timingStressPass=gate.timingStressPass);
save(fullfile(folder, "timing_stress_result.mat"), ...
    "identity", "rows", "summary", "gate");
output = struct(identity=identity, rows=rows, summary=summary, gate=gate);
disp(summary);
disp(gate);
end
