function output = run_round51_p_farc_development(options)
%RUN_ROUND51_P_FARC_DEVELOPMENT Execute the frozen R51 development study.

arguments
    options.NumWorkers (1, 1) double {mustBeInteger, mustBePositive} = 8
    options.PoolType (1, 1) string ...
        {mustBeMember(options.PoolType, ["Threads", "Processes"])} = "Threads"
end

project = string(fileparts(fileparts(mfilename("fullpath"))));
r41.addPaths(project);
protocol = r51.config();
normalDesign = r51.design(protocol);
stressDesign = r51.stressDesign(protocol);
source = r51.manifest(project);
sourceDigest = r32.sourceDigest(source);
folder = fullfile(project, "results", "full_spectrum", ...
    "round51_p_farc_reliability_recovery_development_v1");
if isfolder(folder)
    error("r51:OutputExists", ...
        "The immutable R51 development output already exists.");
end
mkdir(folder);
writetable(normalDesign, fullfile(folder, "normal_design.csv"));
writetable(stressDesign, fullfile(folder, "stress_design.csv"));
writetable(source, fullfile(folder, "source_manifest.csv"));

cfg = jad.defaultConfig();
scan = fsjad.prepareScan(cfg);
pool = preparePool(options.PoolType, options.NumWorkers);
normalResults = cell(height(normalDesign), 1);
parfor index = 1:height(normalDesign)
    normalResults{index} = r51.trial( ...
        cfg, scan, normalDesign(index, :), index, protocol);
end
save(fullfile(folder, "normal_phase.mat"), ...
    "protocol", "normalDesign", "normalResults", "sourceDigest", "-v7");
normalFailures = failureTable(normalDesign, normalResults);
writetable(normalFailures, fullfile(folder, "normal_failures.csv"));
if ~isempty(normalFailures)
    error("r51:NormalTrialFailure", "At least one normal R51 row failed.");
end

stressResults = cell(height(stressDesign), 1);
parfor index = 1:height(stressDesign)
    stressResults{index} = r51.trial( ...
        cfg, scan, stressDesign(index, :), index, protocol);
end
save(fullfile(folder, "stress_phase.mat"), ...
    "protocol", "stressDesign", "stressResults", "sourceDigest", "-v7");
stressFailures = failureTable(stressDesign, stressResults);
writetable(stressFailures, fullfile(folder, "stress_failures.csv"));
if ~isempty(stressFailures)
    error("r51:StressTrialFailure", "At least one stress R51 row failed.");
end

if r32.sourceDigest(r51.manifest(project)) ~= sourceDigest
    error("r51:SourceDrift", "Executable source changed during R51.");
end
summary = r51.summarize( ...
    normalDesign, normalResults, stressDesign, stressResults, protocol);
timing = r51.matchedTiming(normalDesign, cfg, scan, protocol);
runtimeGate = table("mean-complete-runtime/P_C_enhanced", ...
    timing.comparison.meanRuntimeRatio, "<=", 1.0, ...
    timing.comparison.pass, ...
    "predeclared-development-engineering-gate", ...
    'VariableNames', summary.gate.Properties.VariableNames);
summary.gate = [summary.gate; runtimeGate];
summary.developmentPass = all(summary.gate.pass);

legacyDesign = r48.design(protocol.r50.r48);
legacyRow = legacyDesign(legacyDesign.positionId ...
    == protocol.execution.historicalReplayPositionId ...
    & legacyDesign.snrDb ...
    == protocol.execution.historicalReplaySnrDb, :);
historicalReplay = r51.trial(cfg, scan, legacyRow, 1, protocol);
if ~historicalReplay.success
    error("r51:HistoricalReplayFailure", ...
        "The frozen position124 mechanism replay failed.");
end
historicalTable = replayTable(legacyRow, historicalReplay);

writetable(summary.normalPerUser, fullfile(folder, "per_row_results.csv"));
writetable(summary.stressPerUser, fullfile(folder, "stress_results.csv"));
writetable(summary.methodSummary, fullfile(folder, "method_summary.csv"));
writetable(summary.comparisons, fullfile(folder, "comparisons.csv"));
writetable(summary.bootstrap, fullfile(folder, "bootstrap.csv"));
writetable(summary.normalDiagnostics, ...
    fullfile(folder, "trigger_diagnostics.csv"));
writetable(summary.stressSummary, fullfile(folder, "stress_summary.csv"));
writetable(summary.gate, fullfile(folder, "gate.csv"));
writetable(candidateCoverageTable( ...
    normalDesign, normalResults, "normal"), ...
    fullfile(folder, "candidate_coverage.csv"));
writetable([crossValidationTable(normalDesign, normalResults, "normal"); ...
    crossValidationTable(stressDesign, stressResults, "stress")], ...
    fullfile(folder, "cross_validation.csv"));
writetable([runtimeTable(normalDesign, normalResults, "normal"); ...
    runtimeTable(stressDesign, stressResults, "stress")], ...
    fullfile(folder, "runtime_breakdown.csv"));
writetable(timing.rows, fullfile(folder, "matched_timing_rows.csv"));
writetable(timing.summary, fullfile(folder, "matched_timing_summary.csv"));
writetable(timing.comparison, fullfile(folder, "runtime_comparison.csv"));
writetable(historicalTable, fullfile(folder, "historical_replay.csv"));

identity = struct(version=protocol.version, completedNormalRows=60, ...
    completedStressRows=54, failedRows=0, sourceDigest=sourceDigest, ...
    normalDesignHash=r32.designHash(normalDesign), ...
    stressDesignHash=r32.designHash(stressDesign), ...
    finalRowsRead=false, calibrationRowsUsedForSelection=false, ...
    historicalReplayExcludedFromGate=true, ...
    developmentPass=summary.developmentPass, ...
    workers=pool.NumWorkers, poolClass=class(pool), ...
    completedAt=string(datetime("now", "TimeZone", "Asia/Shanghai")));
save(fullfile(folder, "result.mat"), "protocol", "identity", ...
    "normalDesign", "normalResults", "stressDesign", "stressResults", ...
    "summary", "timing", "historicalReplay", "historicalTable", ...
    "source", "-v7");
output = struct(folder=folder, identity=identity, ...
    summary=summary, timing=timing, historical=historicalTable);
fprintf("ROUND51_PFARC_DEVELOPMENT_COMPLETE pass=%d normal=60 stress=54\n", ...
    summary.developmentPass);
disp(summary.gate);
disp(summary.normalDiagnostics);
disp(summary.stressSummary);
disp(timing.comparison);
disp(historicalTable);
end

function pool = preparePool(poolType, workers)
pool = gcp("nocreate");
requiredClass = "parallel.ThreadPool";
if poolType == "Processes"
    requiredClass = "parallel.ProcessPool";
end
if ~isempty(pool) && (pool.NumWorkers ~= workers ...
        || string(class(pool)) ~= requiredClass)
    delete(pool);
    pool = [];
end
if isempty(pool)
    pool = parpool(poolType, workers);
end
end

function failures = failureTable(design, results)
failed = cellfun(@(item) isempty(item) || ~item.success, results);
failures = design(failed, :);
failures.errorIdentifier = strings(nnz(failed), 1);
failures.errorMessage = strings(nnz(failed), 1);
indices = find(failed);
for index = 1:numel(indices)
    item = results{indices(index)};
    if ~isempty(item)
        failures.errorIdentifier(index) = item.errorIdentifier;
        failures.errorMessage(index) = item.errorMessage;
    end
end
end

function output = candidateCoverageTable(design, results, dataset)
output = design(:, intersect(["positionId", "seed", "snrDb", ...
    "stressType", "truthThetaDeg", "truthRangeM"], ...
    string(design.Properties.VariableNames), "stable"));
output.dataset = repmat(dataset, height(output), 1);
output = movevars(output, "dataset", Before=1);
output.top8TruthBasinCovered = cellfun( ...
    @(item) item.candidateCoverage.top8TruthBasinCovered, results);
output.minimumTop8AngleErrorDeg = cellfun( ...
    @(item) item.candidateCoverage.minimumTop8AngleErrorDeg, results);
output.minimumTop8RangeErrorM = cellfun( ...
    @(item) item.candidateCoverage.minimumTop8RangeErrorM, results);
end

function output = crossValidationTable(design, results, dataset)
output = table();
for rowIndex = 1:height(design)
    candidates = results{rowIndex}.backend.recovery.candidates;
    for candidateIndex = 1:numel(candidates)
        candidate = candidates(candidateIndex);
        output = [output; table(dataset, rowIndex, ...
            design.positionId(rowIndex), design.snrDb(rowIndex), ...
            candidate.family, candidate.thetaDeg, ...
            candidate.oddRangeM, candidate.evenRangeM, ...
            candidate.oddCrossGain, candidate.evenCrossGain, ...
            candidate.crossPassOdd, candidate.crossPassEven, ...
            candidate.basinConsistent, candidate.accepted, ...
            'VariableNames', {'dataset', 'rowIndex', 'positionId', ...
            'snrDb', 'family', 'thetaDeg', 'oddRangeM', 'evenRangeM', ...
            'oddCrossGain', 'evenCrossGain', 'crossPassOdd', ...
            'crossPassEven', 'basinConsistent', 'accepted'})]; %#ok<AGROW>
    end
end
end

function output = runtimeTable(design, results, dataset)
output = table(repmat(dataset, height(design), 1), ...
    (1:height(design)).', design.positionId, design.snrDb, ...
    cellfun(@(item) item.backend.certificate.trigger, results), ...
    cellfun(@(item) item.backend.recovery.accepted, results), ...
    cellfun(@(item) item.backend.contextSeconds, results), ...
    cellfun(@(item) item.backend.baseSeconds, results), ...
    cellfun(@(item) item.backend.certificateSeconds, results), ...
    cellfun(@(item) item.backend.conditionalRecoverySeconds, results), ...
    cellfun(@(item) item.backend.primaryCompleteSeconds, results), ...
    'VariableNames', {'dataset', 'rowIndex', 'positionId', 'snrDb', ...
    'trigger', 'recoveryAccepted', 'contextSeconds', 'baseSeconds', ...
    'certificateSeconds', 'conditionalRecoverySeconds', ...
    'primaryCompleteSeconds'});
end

function output = replayTable(row, result)
output = table(row.positionId, row.snrDb, row.truthThetaDeg, ...
    row.truthRangeM, result.backend.certificate.C1, ...
    result.backend.certificate.C2, result.backend.certificate.C3, ...
    result.backend.certificate.C4, result.backend.certificate.trigger, ...
    result.backend.recovery.accepted, ...
    string(result.backend.recovery.selectedFamily), ...
    result.P_FA.thetaDeg, result.P_FA.rangeM, ...
    result.P_FARC.thetaDeg, result.P_FARC.rangeM, ...
    result.candidateCoverage.top8TruthBasinCovered, ...
    'VariableNames', {'positionId', 'snrDb', 'truthThetaDeg', ...
    'truthRangeM', 'C1', 'C2', 'C3', 'C4', 'trigger', ...
    'recoveryAccepted', 'selectedFamily', 'thetaPFA', 'rangePFA', ...
    'thetaPFARC', 'rangePFARC', 'top8TruthBasinCovered'});
end
