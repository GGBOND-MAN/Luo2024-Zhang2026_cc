function output = preflight_round55_p_falf_final()
%PREFLIGHT_ROUND55_P_FALF_FINAL Validate the locked package without trials.

project = string(fileparts(fileparts(mfilename("fullpath"))));
r41.addPaths(project);
locations = r55.paths(project);
saved = r55.validateProtocolPackage(project);
counts = groupcounts(saved.design, "snrDb");
designPass = height(saved.design) == 1400 ...
    && numel(unique(saved.design.positionId)) == 200 ...
    && numel(unique(saved.design.seed)) == 1400 ...
    && all(counts.GroupCount == 200);
authorizationExists = isfile(locations.authorizationFile);
executionExists = isfolder(locations.executionFolder);
manualRunRequired = saved.identity.exceedsFourHours;
readyForManualAuthorization = designPass && ~authorizationExists ...
    && ~executionExists && manualRunRequired;
status = table(designPass, authorizationExists, executionExists, ...
    manualRunRequired, readyForManualAuthorization, ...
    saved.identity.sourceDigest, saved.identity.designHash, ...
    saved.identity.statisticsHash, ...
    'VariableNames', {'designPass', 'authorizationExists', ...
    'executionExists', 'manualRunRequired', ...
    'readyForManualAuthorization', 'sourceDigest', ...
    'designHash', 'statisticsHash'});
output = struct(status=status, estimate=saved.estimate, ...
    identity=saved.identity);
disp(status);
disp(saved.estimate);
fprintf("ROUND55_PREFLIGHT_COMPLETE observations=0 trials=0 manual=%d\n", ...
    manualRunRequired);
end
