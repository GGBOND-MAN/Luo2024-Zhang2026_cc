function output = prepare_round41_schemeG_final()
%PREPARE_ROUND41_SCHEMEG_FINAL Create one locked protocol without trials.

project = string(fileparts(fileparts(mfilename("fullpath"))));
r41.addPaths(project);
locations = r41.paths(project);
if isfolder(locations.protocolFolder)
    error("r41:ProtocolAlreadyExists", ...
        "The immutable R41 protocol folder already exists; do not overwrite it.");
end
if isfolder(locations.executionFolder)
    error("r41:ExistingFinalResultDirectory", ...
        "The R41 final result directory already exists. " + ...
        "Resolve it manually before preparing or authorizing R41.");
end

protocol = r41.config();
r41.validateFrozenSystem(jad.defaultConfig(), protocol);
design = r41.finalDesign(protocol);
historicalAudit = r41.historicalExclusionAudit(project, design);
schemeGSource = r41.schemeGManifest(project);
dependencies = r41.dependencyManifests(project);
source = r41.sourceManifest(project);
algorithmDigest = r32.sourceDigest(schemeGSource);
if algorithmDigest ~= protocol.algorithm.schemeGDigest
    error("r41:SchemeGAlgorithmDigestMismatch", ...
        "The current Scheme G code is not the frozen calibration candidate.");
end
designHash = r41.designHash(design);
statisticsHash = r41.structHash(protocol.statistics);
identity = struct( ...
    version="R41-independent-final-protocol-package-v1", ...
    protocolVersion=protocol.version, evidenceRole=protocol.evidenceRole, ...
    status=protocol.execution.status, authorized=false, trialsExecuted=0, ...
    algorithmDigest=algorithmDigest, designHash=designHash, ...
    statisticsVersion=protocol.statistics.version, ...
    statisticsHash=statisticsHash, ...
    r33Digest=r32.sourceDigest(dependencies.r33), ...
    r34Digest=r32.sourceDigest(dependencies.r34), ...
    frozenDependencyDigest=r32.sourceDigest(dependencies.all), ...
    sourceDigest=r32.sourceDigest(source), ...
    positionSeedRoot=protocol.design.positionSeedRoot, ...
    positionSeedMinimum=min(design.positionSeed), ...
    positionSeedMaximum=max(design.positionSeed), ...
    trialSeedRoot=protocol.design.trialSeedRoot, ...
    trialSeedMinimum=min(design.seed), ...
    trialSeedMaximum=max(design.seed), ...
    preparedAt=string(datetime("now", "TimeZone", "Asia/Shanghai")), ...
    observationsGenerated=0, finalResultsDirectoryCreated=false);

resultsRoot = fileparts(locations.protocolFolder);
staging = string(tempname(resultsRoot));
mkdir(staging);
cleanup = onCleanup(@() cleanupStaging(staging));
r41.writeDesignCsv(design, fullfile(staging, "design.csv"));
writetable(historicalAudit, ...
    fullfile(staging, "historical_design_exclusion.csv"));
writetable(schemeGSource, fullfile(staging, "schemeG_source_hashes.csv"));
writetable(dependencies.r33, fullfile(staging, "r33_source_hashes.csv"));
writetable(dependencies.r34, fullfile(staging, "r34_source_hashes.csv"));
writetable(dependencies.all, ...
    fullfile(staging, "frozen_dependency_source_hashes.csv"));
writetable(source, fullfile(staging, "complete_source_hashes.csv"));
save(fullfile(staging, "protocol.mat"), "identity", "protocol", ...
    "design", "source", "schemeGSource", "dependencies", ...
    "historicalAudit", "-v7.3");
writelines([ ...
    "LOCKED: no R41 authorization has been created."; ...
    "LOCKED: no observation or final trial has been generated."; ...
    "Do not edit protocol.mat or design.csv and do not redraw positions."; ...
    "Future explicit authorization phrase:"; ...
    protocol.execution.authorizationPhrase], ...
    fullfile(staging, "LOCKED_README.txt"));
movefile(staging, locations.protocolFolder);
clear cleanup
output = struct(identity=identity, protocol=protocol, design=design, ...
    historicalAudit=historicalAudit, folder=locations.protocolFolder);
fprintf("ROUND41_PROTOCOL_PREPARED_LOCKED rows=%d positions=%d trials=0\n", ...
    height(design), numel(unique(design.positionId)));
end

function cleanupStaging(staging)
if isfolder(staging)
    rmdir(staging, "s");
end
end
