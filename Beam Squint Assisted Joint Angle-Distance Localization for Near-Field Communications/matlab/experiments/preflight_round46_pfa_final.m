function output = preflight_round46_pfa_final()
%PREFLIGHT_ROUND46_PFA_FINAL Validate the locked package without trials.

project = string(fileparts(fileparts(mfilename("fullpath"))));
r41.addPaths(project);
locations = r46.paths(project);
saved = r46.validateProtocolPackage(project);
counts = groupcounts(saved.design, "snrDb");
designPass = height(saved.design) == 1400 ...
    && numel(unique(saved.design.positionId)) == 200 ...
    && numel(unique(saved.design.seed)) == 1400 ...
    && all(counts.GroupCount == 200);
authorizationExists = isfile(locations.authorizationFile);
executionExists = isfolder(locations.executionFolder);
readyForAuthorization = designPass && ~authorizationExists && ~executionExists;
estimate = table(8, 8, 86.6109, 3.3682, 3.5, 4.0, ...
    'VariableNames', {'threadWorkers', 'batchSize', ...
    'calibration600Minutes', 'linearProjectionHours', ...
    'recommendedLowerHours', 'recommendedUpperHours'});
status = table(designPass, authorizationExists, executionExists, ...
    readyForAuthorization, saved.identity.sourceDigest, ...
    saved.identity.designHash, saved.identity.statisticsHash, ...
    'VariableNames', {'designPass', 'authorizationExists', ...
    'executionExists', 'readyForAuthorization', 'sourceDigest', ...
    'designHash', 'statisticsHash'});
output = struct(status=status, estimate=estimate, identity=saved.identity);
disp(status);
disp(estimate);
fprintf("ROUND46_PREFLIGHT_COMPLETE observations=0 trials=0 ready=%d\n", ...
    readyForAuthorization);
end
