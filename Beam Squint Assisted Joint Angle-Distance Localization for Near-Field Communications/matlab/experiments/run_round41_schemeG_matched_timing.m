function output = run_round41_schemeG_matched_timing(options)
%RUN_ROUND41_SCHEMEG_MATCHED_TIMING Collect post-final same-machine timing.

arguments
    options.Repetitions (1, 1) double {mustBeInteger, mustBePositive} = 3
    options.Warmups (1, 1) double {mustBeInteger, mustBeNonnegative} = 1
end

project = string(fileparts(fileparts(mfilename("fullpath"))));
r41.addPaths(project);
saved = r41.validateProtocolPackage(project);
locations = r41.paths(project);
authorization = r41.assertAuthorized( ...
    locations.protocolFolder, saved.identity);
aggregateFile = fullfile(locations.executionFolder, ...
    "aggregate", "result.mat");
if ~isfile(aggregateFile)
    error("r41:TimingRequiresCompletedFinalAggregate", ...
        "Matched timing is allowed only after the frozen 1400-row aggregate.");
end
aggregate = load(aggregateFile, "identity");
if ~aggregate.identity.authorized ...
        || aggregate.identity.trialsExecuted ~= 1400 ...
        || aggregate.identity.designHash ~= saved.identity.designHash
    error("r41:TimingAggregateIdentityMismatch", ...
        "The completed final aggregate does not match this timing protocol.");
end
folder = fullfile(locations.executionFolder, "matched_timing");
if isfolder(folder)
    error("r41:TimingAlreadyExists", ...
        "The matched timing result is immutable and cannot be overwritten.");
end
mkdir(folder);

protocol = saved.protocol;
selected = ismember(saved.design.positionId, ...
    protocol.complexity.timingPositionIds) ...
    & saved.design.snrDb == protocol.complexity.timingSnrDb;
design = saved.design(selected, :);
design = sortrows(design, "positionId");
if height(design) ~= numel(protocol.complexity.timingPositionIds)
    error("r41:TimingDesignMismatch", ...
        "The frozen timing subset is incomplete.");
end
cfg = jad.defaultConfig();
r41.validateFrozenSystem(cfg, protocol);
scan = fsjad.prepareScan(cfg);
methods = ["G_schur", "P_A", "C_enhanced"];
rows = table();
for positionIndex = 1:height(design)
    replay = fsjad.replayRound27Data(cfg, scan, design(positionIndex, :));
    for warmup = 1:options.Warmups
        for method = methods
            executeMethod(cfg, scan, replay, method, protocol);
        end
    end
    for repetition = 1:options.Repetitions
        shift = mod(positionIndex+repetition-2, numel(methods));
        order = circshift(methods, -shift);
        for orderIndex = 1:numel(order)
            method = order(orderIndex);
            timer = tic;
            record = executeMethod(cfg, scan, replay, method, protocol);
            wallSeconds = toc(timer);
            entry = table(design.positionId(positionIndex), ...
                design.seed(positionIndex), repetition, orderIndex, ...
                method, wallSeconds, record.reportedSeconds, ...
                record.responseEquivalentCount, ...
                record.musicEvaluationCount, record.evdCount, ...
                record.fullArrayEvaluationCount, record.profilePassCount, ...
                'VariableNames', {'positionId', 'seed', 'repetition', ...
                'orderIndex', 'method', 'wallSeconds', 'reportedSeconds', ...
                'responseEquivalentCount', 'musicEvaluationCount', ...
                'evdCount', 'fullArrayEvaluationCount', 'profilePassCount'});
            rows = [rows; entry]; %#ok<AGROW>
        end
    end
end
summary = table();
for method = methods
    selectedRows = rows(rows.method == method, :);
    entry = table(method, height(selectedRows), ...
        mean(selectedRows.wallSeconds), median(selectedRows.wallSeconds), ...
        mean(selectedRows.reportedSeconds), ...
        mean(selectedRows.responseEquivalentCount), ...
        mean(selectedRows.musicEvaluationCount), ...
        mean(selectedRows.evdCount), ...
        mean(selectedRows.fullArrayEvaluationCount), ...
        mean(selectedRows.profilePassCount), ...
        'VariableNames', {'method', 'n', 'meanWallSeconds', ...
        'medianWallSeconds', 'meanReportedSeconds', ...
        'meanResponseEquivalentCount', 'meanMusicEvaluationCount', ...
        'meanEvdCount', 'meanFullArrayEvaluationCount', ...
        'meanProfilePassCount'});
    summary = [summary; entry]; %#ok<AGROW>
end
g = summary(summary.method == "G_schur", :);
c = summary(summary.method == "C_enhanced", :);
pa = summary(summary.method == "P_A", :);
comparison = table(g.meanWallSeconds/c.meanWallSeconds, ...
    g.meanWallSeconds/pa.meanWallSeconds, ...
    g.meanWallSeconds <= c.meanWallSeconds, ...
    'VariableNames', {'runtimeRatioGToC', 'runtimeRatioGToPA', ...
    'engineeringRuntimePass'});
identity = struct(version="R41-same-machine-matched-timing-v1", ...
    authorized=true, performanceTrialsExecuted=0, ...
    replayedExistingFinalRows=height(design), newUsersGenerated=0, ...
    designHash=saved.identity.designHash, ...
    algorithmDigest=saved.identity.algorithmDigest, ...
    sourceDigest=saved.identity.sourceDigest, ...
    authorizationDigest=r41.structHash(authorization), ...
    serverThroughputUsed=false, ...
    timestamp=string(datetime("now", "TimeZone", "Asia/Shanghai")));
writetable(rows, fullfile(folder, "raw_timing_rows.csv"));
writetable(summary, fullfile(folder, "timing_summary.csv"));
writetable(comparison, fullfile(folder, "runtime_comparison.csv"));
save(fullfile(folder, "result.mat"), "identity", "design", ...
    "rows", "summary", "comparison", "-v7.3");
output = struct(identity=identity, rows=rows, summary=summary, ...
    comparison=comparison, folder=folder);
end

function record = executeMethod(cfg, scan, replay, method, protocol)
if method == "G_schur"
    pa = r34.estimate(cfg, replay.observation, replay.snapshots, ...
        scan, "P_A", protocol.r34);
    g = r41.gFromPA(cfg, scan, replay, pa, protocol);
    incremental = g.contextSeconds+g.angle.standaloneAngleSeconds ...
        +g.transport.runtimeSeconds;
    record = baselineRecord(pa);
    record.reportedSeconds = record.reportedSeconds+incremental;
    record.responseEquivalentCount = record.responseEquivalentCount ...
        +g.angle.fullArrayEvaluationCount ...
        +g.transport.addedResponseEvaluationCount;
    record.fullArrayEvaluationCount = g.angle.fullArrayEvaluationCount;
    record.profilePassCount = 1;
else
    estimate = r34.estimate(cfg, replay.observation, replay.snapshots, ...
        scan, method, protocol.r34);
    record = baselineRecord(estimate);
    record.profilePassCount = double(method == "P_A");
end
end

function output = baselineRecord(input)
output = struct(reportedSeconds=input.cost.totalOnlineSeconds, ...
    responseEquivalentCount=input.cost.sparseResponseCalls ...
    +input.cost.frontFullResponseCalls+input.cost.profileResponseCalls, ...
    musicEvaluationCount=input.estimate.evaluationCount, ...
    evdCount=input.cost.directCount, fullArrayEvaluationCount=0, ...
    profilePassCount=0);
end
