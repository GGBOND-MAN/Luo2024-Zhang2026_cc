function preflight_round34()
%PREFLIGHT_ROUND34 Persist real tests, static analysis, and lock checks.

project = string(fileparts(fileparts(mfilename("fullpath"))));
addpath(project);
files = [dir(fullfile(project, "+r34", "*.m")); ...
    dir(fullfile(project, "experiments", "*round34*.m")); ...
    dir(fullfile(project, "tests", "round34*.m"))];
static = table('Size', [0, 3], ...
    'VariableTypes', {'string', 'double', 'string'}, ...
    'VariableNames', {'file', 'line', 'message'});
for index = 1:numel(files)
    name = fullfile(files(index).folder, files(index).name);
    messages = checkcode(name, "-struct");
    for messageIndex = 1:numel(messages)
        static = [static; table(string(name), ...
            messages(messageIndex).line, ...
            string(messages(messageIndex).message), ...
            'VariableNames', static.Properties.VariableNames)]; %#ok<AGROW>
    end
end
targetedResults = runtests(fullfile(project, "tests", ...
    "round34FinalEngineeringTest.m"));
fullResults = runtests(fullfile(project, "tests"));
gate = gateAudit(project);
source = r34.manifest(project);
folder = fullfile(project, "results", "full_spectrum", ...
    "round34_final_engineering_v1", "verification");
if ~isfolder(folder)
    mkdir(folder);
end
writetable(static, fullfile(folder, "static_analysis.csv"));
writetable(gate, fullfile(folder, "execution_gate_audit.csv"));
writetable(source, fullfile(folder, "source_hashes.csv"));
identity = struct(version="R34-final-engineering-verification-v1", ...
    finalTrialsExecuted=0, newDevelopmentUsers=0, ...
    acceptedEstimator="R33-A-q-only-invariants-direct-EVD-v1", ...
    timestamp=string(datetime("now")));
save(fullfile(folder, "result.mat"), "identity", "static", ...
    "targetedResults", "fullResults", "gate", "source", "-v7.3");
fprintf("R34 TESTS targetedPassed=%d targetedFailed=%d " + ...
    "fullPassed=%d fullFailed=%d fullIncomplete=%d static=%d gates=%d\n", ...
    nnz([targetedResults.Passed]), nnz([targetedResults.Failed]), ...
    nnz([fullResults.Passed]), nnz([fullResults.Failed]), ...
    nnz([fullResults.Incomplete]), height(static), nnz(gate.pass));
assert(all([targetedResults.Passed]) && all([fullResults.Passed]) ...
    && isempty(static) && all(gate.pass), "r34:PreflightFailed");
end

function gate = gateAudit(project)
protocolFolder = fullfile(project, "results", "full_spectrum", ...
    "round34_final_test_protocol_v1");
protocolFile = fullfile(protocolFolder, "protocol.mat");
smokeFile = fullfile(project, "results", "full_spectrum", ...
    "round34_final_engineering_v1", "development_smoke", "result.mat");
counterexampleFile = fullfile(project, "results", "full_spectrum", ...
    "round34_final_engineering_v1", ...
    "bootstrap_index_counterexample", "result.mat");
acceptedFile = fullfile(project, "results", "full_spectrum", ...
    "round33_equivalent_acceleration_v1", ...
    "accepted_a_only_implementation", "identity.mat");
protocolPass = false;
smokePass = false;
acceptedPass = false;
if isfile(protocolFile)
    saved = load(protocolFile, "identity", "design");
    protocolPass = saved.identity.designHash ...
        == r34.config().finalTest.designHash ...
        && r32.designHash(saved.design) == saved.identity.designHash ...
        && saved.identity.status ...
        == "LOCKED-WAITING-FOR-EXPLICIT-USER-AUTHORIZATION" ...
        && ~saved.identity.authorized && saved.identity.trialsExecuted == 0;
end
if isfile(smokeFile)
    smoke = load(smokeFile, "identity");
    smokePass = smoke.identity.threadsPathExecuted ...
        && smoke.identity.checkpointPass ...
        && smoke.identity.miniShardMergePass ...
        && smoke.identity.finalTrialRows == 0;
end
if isfile(acceptedFile)
    accepted = load(acceptedFile, "identity");
    acceptedPass = accepted.identity.version ...
        == "R33-A-equivalent-implementation-accepted-v1";
end
authorizationFiles = [ ...
    fullfile(protocolFolder, "FINAL_TEST_AUTHORIZATION.mat"), ...
    fullfile(project, "results", "full_spectrum", ...
    "round32_final_test_protocol_v1", "FINAL_TEST_AUTHORIZATION.mat"), ...
    fullfile(project, "results", "full_spectrum", ...
    "round33_final_test_candidate_protocol_v1", ...
    "FINAL_TEST_AUTHORIZATION.mat")];
check = ["accepted_R33_A_only_identity"; ...
    "bootstrap_counterexample_saved"; ...
    "three_old_input_threads_smoke_passed"; ...
    "R34_protocol_locked_exact_design"; ...
    "no_final_authorization_any_version"; ...
    "no_R34_final_trial_result_directory"];
pass = [acceptedPass; isfile(counterexampleFile); smokePass; ...
    protocolPass; ~any(isfile(authorizationFiles)); ...
    ~isfolder(fullfile(project, "results", "full_spectrum", ...
    "round34_final_test_v1"))];
gate = table(check, pass);
end
