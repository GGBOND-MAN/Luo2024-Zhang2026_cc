function output = generate_r41v2_final_reports()
%GENERATE_R41V2_FINAL_REPORTS Write the frozen result, audit, and paper summaries.

project = string(fileparts(fileparts(mfilename("fullpath"))));
workspace = string(fileparts(fileparts(project)));
research = fullfile(workspace, "research");
r41.addPaths(project);
saved = r41statsv2.validateProtocolPackage(project);
locations = r41statsv2.paths(project);
aggregate = load(fullfile(locations.executionFolder, ...
    "aggregate", "result.mat"), "identity", "analysis");
timing = load(fullfile(locations.executionFolder, ...
    "matched_timing", "result.mat"), "identity", "summary", "comparison");
audit = load(fullfile(locations.executionFolder, ...
    "final_audit", "result.mat"), "identity", "audit", ...
    "fallbackSummary");
if ~aggregate.identity.authorized ...
        || aggregate.identity.trialsExecuted ~= 1400 ...
        || ~audit.identity.auditPassed ...
        || audit.identity.trialsExecuted ~= 1400
    error("r41v2:ReportsRequirePassingFinalAudit", ...
        "Final reports require an authorized 1400-row aggregate and passing audit.");
end

resultFile = fullfile(research, ...
    "98_schemeG_R41_independent_final_results.md");
auditFile = fullfile(research, ...
    "99_schemeG_R41_independent_final_audit.md");
paperFile = fullfile(research, "100_schemeG_final_paper_results.md");
for file = [resultFile, auditFile, paperFile]
    if isfile(file)
        error("r41v2:FinalReportAlreadyExists", ...
            "A frozen final report already exists: %s", file);
    end
end

writelines(resultReport(saved, aggregate, timing), resultFile);
writelines(auditReport(saved, audit), auditFile);
writelines(paperReport(saved, aggregate, timing), paperFile);
output = struct(resultFile=resultFile, auditFile=auditFile, ...
    paperFile=paperFile, interpretation=aggregate.analysis.interpretation);
fprintf("R41_V2_FINAL_REPORTS_WRITTEN level=%s\n", ...
    aggregate.analysis.interpretation.level);
end

function lines = resultReport(saved, aggregate, timing)
analysis = aggregate.analysis;
lines = ["# Scheme G R41 Independent Final Results"; ""; ...
    "Date: "+string(datetime("now", "Format", "yyyy-MM-dd", ...
    "TimeZone", "Asia/Shanghai")); ...
    "Status: authorized independent final, 1400/1400 rows"; ""; ...
    "## Frozen identity"; ""; ...
    "- Scheme G digest: `"+saved.identity.algorithmDigest+"`."; ...
    "- Design hash: `"+saved.identity.designHash+"`."; ...
    "- Statistics: `"+saved.identity.statisticsVersion+"`."; ...
    "- Statistics hash: `"+saved.identity.statisticsHash+"`."; ""; ...
    "## Frozen interpretation"; ""; ...
    "- Level: **"+analysis.interpretation.level+"**."; ...
    "- "+analysis.interpretation.allowedClaim; ""; ...
    "## Co-primary global endpoints"; ""; ...
    markdownTable(analysis.coPrimaryGlobal); ""; ...
    "## Pointwise consistency"; ""; ...
    markdownTable(analysis.pointwiseConsistency(:, 1:8)); ""; ...
    "## Per-SNR simultaneous characterization"; ""; ...
    markdownTable(analysis.perSnrConfirmatoryFamilies(:, 1:5)); ""; ...
    "## Descriptive performance"; ""; markdownTable(analysis.summary); ""; ...
    "## Paired win/tie/loss"; ""; markdownTable(analysis.paired); ""; ...
    "## Matched timing"; ""; markdownTable(timing.summary); ""; ...
    markdownTable(timing.comparison)];
end

function lines = auditReport(saved, audit)
lines = ["# Scheme G R41 Independent Final Audit"; ""; ...
    "Date: "+string(datetime("now", "Format", "yyyy-MM-dd", ...
    "TimeZone", "Asia/Shanghai")); ...
    "Status: **"+string(audit.identity.auditPassed)+"**"; ""; ...
    "## Identity"; ""; ...
    "- Authorized: `"+string(audit.identity.authorized)+"`."; ...
    "- Trials executed: `"+string(audit.identity.trialsExecuted)+"`."; ...
    "- Algorithm digest: `"+saved.identity.algorithmDigest+"`."; ...
    "- Design hash: `"+saved.identity.designHash+"`."; ...
    "- Statistics hash: `"+saved.identity.statisticsHash+"`."; ...
    "- Authorization digest: `"+audit.identity.authorizationDigest+"`."; ...
    "- Bootstrap index hash: `"+audit.identity.bootstrapIndexHash+"`."; ""; ...
    "## Audit checks"; ""; markdownTable(audit.audit); ""; ...
    "## Scheme G safeguard fallback summary"; ""; ...
    markdownTable(audit.fallbackSummary)];
end

function lines = paperReport(saved, aggregate, timing)
analysis = aggregate.analysis;
g = timing.summary(timing.summary.method == "G_schur", :);
c = timing.summary(timing.summary.method == "C_enhanced", :);
pa = timing.summary(timing.summary.method == "P_A", :);
lines = ["# Scheme G Final Paper Results"; ""; ...
    "This document reports the frozen R41 v2 independent final only. " + ...
    "C_enhanced is a strengthened Zhang-style executable baseline, not " + ...
    "author-supplied Zhang2026 code."; ""; ...
    "## Confirmatory statement"; ""; ...
    "> "+analysis.interpretation.allowedClaim; ""; ...
    "Interpretation level: **"+analysis.interpretation.level+"**."; ""; ...
    "## Global statistics"; ""; ...
    markdownTable(analysis.coPrimaryGlobal); ""; ...
    "## Per-SNR characterization"; ""; ...
    markdownTable(analysis.perSnrConfirmatoryFamilies(:, 1:5)); ""; ...
    "## Complexity"; ""; ...
    "Matched mean wall times were G=`"+string(g.meanWallSeconds)+ ...
    "` s, P_A=`"+string(pa.meanWallSeconds)+"` s, and C_enhanced=`"+ ...
    string(c.meanWallSeconds)+"` s. Server throughput was not used."; ""; ...
    markdownTable(timing.comparison); ""; ...
    "## Reproducibility identity"; ""; ...
    "- Scheme G: `"+saved.identity.algorithmDigest+"`."; ...
    "- Design: `"+saved.identity.designHash+"`."; ...
    "- Statistics: `"+saved.identity.statisticsHash+"`."];
end

function lines = markdownTable(input)
names = string(input.Properties.VariableNames);
lines = "| "+join(names, " | ")+" |";
lines(end+1, 1) = "| "+join(repmat("---", size(names)), " | ")+" |";
for row = 1:height(input)
    values = strings(1, width(input));
    for column = 1:width(input)
        value = input{row, column};
        if iscell(value)
            value = value{1};
        end
        if isnumeric(value) || islogical(value)
            if isscalar(value)
                values(column) = string(value);
            else
                values(column) = "["+join(string(value), ",")+"]";
            end
        else
            values(column) = replace(string(value), "|", "\|");
        end
    end
    lines(end+1, 1) = "| "+join(values, " | ")+" |"; %#ok<AGROW>
end
end
