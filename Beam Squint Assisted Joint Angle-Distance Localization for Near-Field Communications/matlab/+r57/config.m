    fusionWeightAllowed=false, thresholdAllowed=false, ...
    selectorAllowed=false, snrRuleAllowed=false, truthAllowed=false);

% Search constants. coarseSpacingM and tolXM are fixed by the sampling
% theorem and the target bound, never retuned from any outcome.
protocol.profile = protocol.base.profile;
protocol.profile.coarseSpacingM = 299792458/(4*3e9);
protocol.profile.tolXM = 1e-7;
protocol.profile.mainlobeM = 299792458/3e9;
