function output = prepare_round46_pfa_final()
%PREPARE_ROUND46_PFA_FINAL Create the locked R46 package without trials.

project = string(fileparts(fileparts(mfilename("fullpath"))));
r41.addPaths(project);
locations = r46.paths(project);
if isfolder(locations.protocolFolder)
    error("r46:ProtocolAlreadyExists", ...
        "The immutable R46 protocol folder already exists.");
end
if isfolder(locations.executionFolder)
    error("r46:ExistingFinalResultDirectory", ...
        "An R46 final execution folder already exists.");
end

protocol = r46.config();
design = r46.design(protocol);
if height(design) ~= protocol.design.expectedRows ...
        || numel(unique(design.positionId)) ~= protocol.design.positionCount ...
        || numel(unique(design.seed)) ~= protocol.design.expectedRows
    error("r46:FrozenDesignMismatch", ...
        "The generated R46 design is not the frozen 1400-row design.");
end
calibrationSource = r45.manifest(project);
calibrationSourceDigest = r32.sourceDigest(calibrationSource);
if calibrationSourceDigest ~= protocol.algorithm.calibrationSourceDigest
    error("r46:CalibrationSourceDrift", ...
        "The P_FA source no longer matches the successful R45 calibration.");
end
source = r46.sourceManifest(project);
designHash = r46.designHash(design);
statisticsHash = r41.structHash(protocol.statistics);
identity = struct( ...
    version="R46-PFA-final-protocol-package-v1", ...
    protocolVersion=protocol.version, evidenceRole=protocol.evidenceRole, ...
    status=protocol.execution.status, authorized=false, trialsExecuted=0, ...
    calibrationSourceDigest=calibrationSourceDigest, ...
    designHash=designHash, statisticsHash=statisticsHash, ...
    sourceDigest=r32.sourceDigest(source), ...
    positionSeed=protocol.design.positionSeed, ...
    trialSeedRoot=protocol.design.trialSeedRoot, ...
    trialSeedMinimum=min(design.seed), ...
    trialSeedMaximum=max(design.seed), ...
    observationsGenerated=0, finalResultsDirectoryCreated=false, ...
    preparedAt=string(datetime("now", "TimeZone", "Asia/Shanghai")));

resultsRoot = fileparts(locations.protocolFolder);
staging = string(tempname(resultsRoot));
mkdir(staging);
cleanup = onCleanup(@() cleanupStaging(staging, resultsRoot));
writetable(design, fullfile(staging, "design.csv"));
writetable(calibrationSource, ...
    fullfile(staging, "calibration_source_manifest.csv"));
writetable(source, fullfile(staging, "complete_source_manifest.csv"));
save(fullfile(staging, "protocol.mat"), "identity", "protocol", ...
    "design", "source", "calibrationSource", "-v7.3");
writelines([ ...
    "LOCKED: no R46 authorization has been created."; ...
    "LOCKED: no final observation or trial has been generated."; ...
    "Estimated single-PC runtime at 8 thread workers: 3.5-4.0 hours."; ...
    "Do not edit protocol, design, statistics, or source files."; ...
    "Exact future authorization phrase:"; ...
    protocol.execution.authorizationPhrase], ...
    fullfile(staging, "LOCKED_README.txt"));
movefile(staging, locations.protocolFolder);
clear cleanup
output = struct(identity=identity, protocol=protocol, design=design, ...
    folder=locations.protocolFolder);
fprintf("ROUND46_PROTOCOL_PREPARED_LOCKED rows=%d positions=%d trials=0\n", ...
    height(design), numel(unique(design.positionId)));
end

function cleanupStaging(staging, resultsRoot)
resolvedStaging = string(java.io.File(staging).getCanonicalPath());
resolvedRoot = string(java.io.File(resultsRoot).getCanonicalPath());
if isfolder(resolvedStaging) && startsWith(resolvedStaging, resolvedRoot+filesep)
    rmdir(resolvedStaging, "s");
end
end
