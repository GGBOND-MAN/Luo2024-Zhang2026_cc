function preflight_round33()
%PREFLIGHT_ROUND33 Persist static analysis and complete regression results.

project = string(fileparts(fileparts(mfilename("fullpath"))));
addpath(project);
files = [dir(fullfile(project, "+r33", "*.m")); ...
    dir(fullfile(project, "experiments", "*round33*.m")); ...
    dir(fullfile(project, "tests", "round33*.m"))];
static = table('Size', [0, 3], ...
    'VariableTypes', {'string', 'double', 'string'}, ...
    'VariableNames', {'file', 'line', 'message'});
for index = 1:numel(files)
    name = fullfile(files(index).folder, files(index).name);
    messages = checkcode(name, "-struct");
    for messageIndex = 1:numel(messages)
        static = [static; table(string(name), ...
            messages(messageIndex).line, string(messages(messageIndex).message), ...
            'VariableNames', static.Properties.VariableNames)]; %#ok<AGROW>
    end
end
targetedFiles = [fullfile(project, "tests", ...
    "round33EquivalentAccelerationTest.m"), ...
    fullfile(project, "tests", "round33ComplexityLedgerTest.m")];
targetedResults = runtests(targetedFiles);
fullResults = runtests(fullfile(project, "tests"));
gate = gateAudit(project);
source = r33.manifest(project);
folder = fullfile(project, "results", "full_spectrum", ...
    "round33_equivalent_acceleration_v1", "verification");
if ~isfolder(folder)
    mkdir(folder);
end
writetable(static, fullfile(folder, "static_analysis.csv"));
writetable(gate, fullfile(folder, "execution_gate_audit.csv"));
writetable(source, fullfile(folder, "source_hashes.csv"));
identity = struct(version="R33-finite-verification-v1", ...
    finalTrialsExecuted=0, newDevelopmentUsers=0, ...
    timestamp=string(datetime("now")));
save(fullfile(folder, "result.mat"), "identity", "static", ...
    "targetedResults", "fullResults", "gate", "source", "-v7.3");
fprintf("R33 TESTS targetedPassed=%d targetedFailed=%d " + ...
    "fullPassed=%d fullFailed=%d fullIncomplete=%d static=%d\n", ...
    nnz([targetedResults.Passed]), nnz([targetedResults.Failed]), ...
    nnz([fullResults.Passed]), nnz([fullResults.Failed]), ...
    nnz([fullResults.Incomplete]), height(static));
assert(all([targetedResults.Passed]) && all([fullResults.Passed]) ...
    && isempty(static) && all(gate.pass), "r33:PreflightFailed");
end

function gate = gateAudit(project)
acceptanceFile = fullfile(project, "results", "full_spectrum", ...
    "round33_equivalent_acceleration_v1", ...
    "nine_user_acceptance_v2", "result.mat");
acceptance = load(acceptanceFile, "variantPass");
a = acceptance.variantPass.variant == "A_response_invariants";
b = acceptance.variantPass.variant == "B_gram_subspace";
ab = acceptance.variantPass.variant == "AB_combined";
authorizationFiles = [fullfile(project, "results", "full_spectrum", ...
    "round32_final_test_protocol_v1", "FINAL_TEST_AUTHORIZATION.mat"), ...
    fullfile(project, "results", "full_spectrum", ...
    "round33_final_test_candidate_protocol_v1", ...
    "FINAL_TEST_AUTHORIZATION.mat")];
check = ["A_variant_accepted"; "B_variant_rejected"; ...
    "AB_variant_rejected"; "no_final_authorization"; ...
    "no_sixty_user_result"; "no_round33_final_result"];
pass = [nnz(a) == 1 && acceptance.variantPass.pass(a); ...
    nnz(b) == 1 && ~acceptance.variantPass.pass(b); ...
    nnz(ab) == 1 && ~acceptance.variantPass.pass(ab); ...
    ~any(isfile(authorizationFiles)); ...
    ~isfile(fullfile(project, "results", "full_spectrum", ...
    "round33_equivalent_acceleration_v1", "sixty_user_equivalence", ...
    "result.mat")); ...
    ~isfolder(fullfile(project, "results", "full_spectrum", ...
    "round33_final_results"))];
gate = table(check, pass);
end
