function prepare_round33_final_test_candidate()
%PREPARE_ROUND33_FINAL_TEST_CANDIDATE Bind fast code to the R32 design.
% This creates no authorization file and executes no final trial.

project = string(fileparts(fileparts(mfilename("fullpath"))));
addpath(project);
requireCompletedFiniteAudit(project);
r32File = fullfile(project, "results", "full_spectrum", ...
    "round32_final_test_protocol_v1", "protocol.mat");
if ~isfile(r32File)
    error("r33:R32FinalProtocolMissing", ...
        "The already-frozen R32 final protocol is required.");
end
inherited = load(r32File, "identity", "design");
protocol = r33.config();
if inherited.identity.status ~= "LOCKED-WAITING-FOR-USER-CONFIRMATION"
    error("r33:R32FinalProtocolUnexpectedStatus", ...
        "The inherited R32 design is not in the expected locked state.");
end
if inherited.identity.designHash ~= r32.designHash(inherited.design)
    error("r33:R32FinalDesignHashMismatch", ...
        "The inherited R32 final design hash does not match.");
end
source = r33.manifest(project);
sourceDigest = r32.sourceDigest(source);
identity = struct(version="R33-fast-final-test-candidate-protocol-v1", ...
    implementation="R33-A-q-only-invariants-direct-EVD-v1", ...
    inheritedDesignVersion=inherited.identity.version, ...
    designHash=inherited.identity.designHash, sourceDigest=sourceDigest, ...
    preparedAt=string(datetime("now")), ...
    status="LOCKED-WAITING-FOR-USER-CONFIRMATION", ...
    authorized=false, trialsExecuted=0, ...
    dataUse="must-not-be-used-for-implementation-selection");
folder = fullfile(project, "results", "full_spectrum", ...
    "round33_final_test_candidate_protocol_v1");
if ~isfolder(folder)
    mkdir(folder);
end
writetable(inherited.design, fullfile(folder, ...
    "inherited_frozen_design_1400.csv"));
writetable(source, fullfile(folder, "source_hashes.csv"));
design = inherited.design;
save(fullfile(folder, "protocol.mat"), "identity", "protocol", ...
    "design", "source", "-v7.3");
writelines([ ...
    "LOCKED: no R33 authorization file was created."; ...
    "LOCKED: no final trial was executed in Round33."; ...
    "The 1400-row design is inherited unchanged from Round32."; ...
    "A future runner must bind authorization to this source digest."], ...
    fullfile(folder, "LOCKED_PENDING_USER_APPROVAL.txt"));
authorizationFile = fullfile(folder, "FINAL_TEST_AUTHORIZATION.mat");
if isfile(authorizationFile)
    error("r33:UnexpectedAuthorizationFile", ...
        "Preparation must not create or retain an authorization file.");
end
fprintf("ROUND33_FINAL_CANDIDATE_PREPARED_LOCKED rows=%d trials=0\n", ...
    height(design));
end

function requireCompletedFiniteAudit(project)
identityFile = fullfile(project, "results", "full_spectrum", ...
    "round33_equivalent_acceleration_v1", ...
    "accepted_a_only_implementation", "identity.mat");
timingFile = fullfile(project, "results", "full_spectrum", ...
    "round33_equivalent_acceleration_v1", ...
    "complete_online_timing_a_only", ...
    "result.mat");
if ~isfile(identityFile) || ~isfile(timingFile)
    error("r33:FiniteAuditIncomplete", ...
        "Accepted A-only identity and fair timing must exist first.");
end
accepted = load(identityFile, "identity");
if accepted.identity.version ...
        ~= "R33-A-equivalent-implementation-accepted-v1"
    error("r33:FiniteAuditIdentityMismatch", ...
        "The accepted implementation identity is not the A-only version.");
end
end
