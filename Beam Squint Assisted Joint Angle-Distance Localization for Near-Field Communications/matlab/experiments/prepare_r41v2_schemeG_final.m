function output = prepare_r41v2_schemeG_final()
%PREPARE_R41V2_SCHEMEG_FINAL Create the isolated locked v2 protocol.

project = string(fileparts(fileparts(mfilename("fullpath"))));
r41.addPaths(project);
v1Locations = r41.paths(project);
locations = r41statsv2.paths(project);
if isfolder(locations.protocolFolder)
    error("r41v2:ProtocolAlreadyExists", ...
        "The immutable R41 v2 protocol folder already exists.");
end
if isfolder(locations.executionFolder)
    error("r41v2:ExistingFinalResultDirectory", ...
        "The R41 v2 final result directory already exists. " + ...
        "Resolve it manually before preparation or authorization.");
end
if isfile(v1Locations.authorizationFile) ...
        || isfolder(v1Locations.executionFolder)
    error("r41v2:V1NoLongerEmpty", ...
        "The v2 hierarchy review requires the archived v1 to remain unexecuted.");
end
v1 = r41.validateProtocolPackage(project);
protocol = r41statsv2.config();
design = v1.design;
if r41.designHash(design) ...
        ~= "a50ad0b244b5f5dba36f3b6322093f30908c99e34f86e17898557d6b17dfe374"
    error("r41v2:DesignHashMismatch", ...
        "R41 v2 must reuse the exact frozen v1 design.");
end
source = r41statsv2.sourceManifest(project);
v1Artifacts = r41statsv2.v1ArtifactManifest(project);
statisticsHash = r41.structHash(protocol.statistics);
hierarchyAudit = hierarchyIdentity(v1, protocol, design);
identity = struct( ...
    version="R41-independent-final-protocol-package-v2", ...
    protocolVersion=protocol.version, ...
    evidenceRole=protocol.evidenceRole, status=protocol.execution.status, ...
    authorized=false, trialsExecuted=0, observationsGenerated=0, ...
    algorithmDigest=v1.identity.algorithmDigest, ...
    designHash=v1.identity.designHash, ...
    statisticsVersion=protocol.statistics.version, ...
    statisticsHash=statisticsHash, ...
    r33Digest=v1.identity.r33Digest, r34Digest=v1.identity.r34Digest, ...
    frozenDependencyDigest=v1.identity.frozenDependencyDigest, ...
    inheritedV1SourceDigest=v1.identity.sourceDigest, ...
    sourceDigest=r32.sourceDigest(source), ...
    v1StatisticsVersion=v1.identity.statisticsVersion, ...
    v1StatisticsHash=v1.identity.statisticsHash, ...
    preparedAt=string(datetime("now", "TimeZone", "Asia/Shanghai")), ...
    finalResultsDirectoryCreated=false);

resultsRoot = fileparts(locations.protocolFolder);
staging = string(tempname(resultsRoot));
mkdir(staging);
cleanup = onCleanup(@() cleanupStaging(staging));
copyfile(v1Locations.designFile, fullfile(staging, "design.csv"));
writetable(hierarchyAudit, fullfile(staging, "hierarchy_change_audit.csv"));
writetable(v1Artifacts, fullfile(staging, "v1_artifact_hashes.csv"));
writetable(source, fullfile(staging, "complete_source_hashes.csv"));
save(fullfile(staging, "protocol.mat"), "identity", "protocol", ...
    "design", "source", "v1Artifacts", "hierarchyAudit", "-v7.3");
writelines([ ...
    "LOCKED R41 statistical protocol v2."; ...
    "R41 v1 remains permanently archived and unchanged."; ...
    "No authorization, observation, or formal final trial exists."; ...
    "Future v2 authorization phrase:"; ...
    protocol.execution.authorizationPhrase], ...
    fullfile(staging, "LOCKED_README.txt"));
movefile(staging, locations.protocolFolder);
clear cleanup
output = struct(identity=identity, protocol=protocol, design=design, ...
    hierarchyAudit=hierarchyAudit, folder=locations.protocolFolder);
fprintf("R41_V2_PROTOCOL_PREPARED_LOCKED rows=%d trials=0\n", ...
    height(design));
end

function audit = hierarchyIdentity(v1, protocol, design)
check = ["design hash unchanged"; "algorithm digest unchanged"; ...
    "positions and trial seeds unchanged"; "shard assignment unchanged"; ...
    "methods unchanged"; "observation and estimator protocols unchanged"; ...
    "bootstrap seed unchanged"; "bootstrap count unchanged"; ...
    "per-SNR family definitions unchanged"; ...
    "source dependencies unchanged"; "execution core source unchanged"];
pass = [r41.designHash(design) == v1.identity.designHash; ...
    protocol.algorithm.schemeGDigest == v1.identity.algorithmDigest; ...
    isequaln(protocol.design, v1.protocol.design); ...
    isequal(design.shardId, v1.design.shardId); ...
    isequaln(protocol.algorithm, v1.protocol.algorithm); ...
    isequaln(protocol.schemeG, v1.protocol.schemeG) ...
        && isequaln(protocol.r34, v1.protocol.r34); ...
    protocol.statistics.bootstrapSeed ...
        == v1.protocol.statistics.bootstrapSeed; ...
    protocol.statistics.bootstrapCount ...
        == v1.protocol.statistics.bootstrapCount; ...
    protocol.statistics.familyA == v1.protocol.statistics.familyA ...
        && protocol.statistics.familyB == v1.protocol.statistics.familyB ...
        && protocol.statistics.familyMultiplicity ...
        == v1.protocol.statistics.familyMultiplicity; ...
    v1.identity.frozenDependencyDigest ...
        == "779778d36a18dc904cfed079e392d5c84515ebf067a5061ee2b0977d41ec6239"; ...
    v1.identity.sourceDigest ...
        == "5700bf99a29708045efb3ae5ee6c20f1422db663dba79e1229571f4fb906b162"];
audit = table(check, pass);
if ~all(pass)
    error("r41v2:HierarchyOnlyInvariant", ...
        "A non-statistical R41 identity changed during v2 preparation.");
end
end

function cleanupStaging(staging)
if isfolder(staging)
    rmdir(staging, "s");
end
end
