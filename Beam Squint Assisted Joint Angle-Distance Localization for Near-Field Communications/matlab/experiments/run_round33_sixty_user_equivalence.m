function run_round33_sixty_user_equivalence()
%RUN_ROUND33_SIXTY_USER_EQUIVALENCE Regress AB on the existing 60 users.

project = string(fileparts(fileparts(mfilename("fullpath"))));
addpath(project);
nineFile = fullfile(project, "results", "full_spectrum", ...
    "round33_equivalent_acceleration_v1", ...
    "nine_user_acceptance_v2", "result.mat");
requireNineUserPass(nineFile);
raw = r31.loadRound30Raw(project);
controlFile = fullfile(project, "results", "full_spectrum", ...
    "round31_angle_controls_v2", "result.mat");
control = load(controlFile, "identity", "results");
protocol = r33.config();
cfg = raw.pilot.expected.cfg;
scan = fsjad.prepareScan(cfg);
rows = table();
counts = table();
failure = table('Size', [0, 4], ...
    'VariableTypes', {'double', 'double', 'string', 'string'}, ...
    'VariableNames', {'seed', 'snrDb', 'errorIdentifier', 'errorMessage'});

for index = 1:height(raw.pilot.design)
    design = raw.pilot.design(index, :);
    try
        replay = fsjad.replayRound27Data(cfg, scan, design);
        fast = r33.sharedRegressionSet(cfg, replay.observation, ...
            replay.snapshots, scan, protocol);
        reference = referenceData(raw, control, index);
        rows = [rows; compareMethods(design, fast, reference, ...
            protocol.validation)]; %#ok<AGROW>
        counts = [counts; countRow(design, fast)]; %#ok<AGROW>
    catch exception
        failure = [failure; table(design.seed, design.snrDb, ...
            string(exception.identifier), string(getReport(exception, ...
            "extended", "hyperlinks", "off")), 'VariableNames', ...
            failure.Properties.VariableNames)]; %#ok<AGROW>
    end
end

summary = summarize(rows);
pass = height(failure) == 0 ...
    && height(rows) == 4*height(raw.pilot.design) && all(rows.pass);
folder = fullfile(project, "results", "full_spectrum", ...
    "round33_equivalent_acceleration_v1", "sixty_user_equivalence");
if ~isfolder(folder)
    mkdir(folder);
end
writetable(rows, fullfile(folder, "per_method_equivalence.csv"));
writetable(counts, fullfile(folder, "per_user_actual_counts.csv"));
writetable(summary, fullfile(folder, "maximum_differences.csv"));
writetable(failure, fullfile(folder, "failures.csv"));
source = r33.manifest(project);
writetable(source, fullfile(folder, "source_hashes.csv"));
identity = struct(version="R33-existing-60-user-equivalence-v1", ...
    role="existing-development-data-numerical-regression-only", ...
    protocol=protocol, pilotHash=raw.pilotHash, ...
    baselineHash=raw.baselineHash, controlIdentity=control.identity, ...
    passed=pass);
save(fullfile(folder, "result.mat"), "identity", "rows", "counts", ...
    "summary", "failure", "source", "-v7.3");
if ~pass
    error("r33:SixtyUserEquivalenceFailed", ...
        "The combined implementation failed the frozen 60-user regression.");
end
fprintf("ROUND33_SIXTY_USER_EQUIVALENCE_COMPLETE rows=%d fallbacks=%d\n", ...
    height(rows), sum(counts.enhancedFallbackCount ...
    + counts.publicFallbackCount));
end

function requireNineUserPass(file)
if ~isfile(file)
    error("r33:NineUserAcceptanceMissing", ...
        "Run the nine-user acceptance before the 60-user regression.");
end
data = load(file, "variantPass", "identity");
selected = data.variantPass.variant == "AB_combined";
isV2 = isfield(data, "identity") ...
    && data.identity.version == "R33-nine-existing-user-acceptance-v2";
if ~isV2 || nnz(selected) ~= 1 || ~data.variantPass.pass(selected)
    error("r33:NineUserAcceptanceNotPassed", ...
        "The combined implementation did not pass the nine-user gate.");
end
end

function reference = referenceData(raw, control, index)
pilot = raw.pilot.results{index}.candidateResults{raw.l06PilotIndex};
baseline = raw.baselines.results{index, raw.l06BaselineIndex};
reference.front = pilot.front;
reference.control = control.results{index};
reference.enhancedVectors = baseline.enhancedBaseline.estimate.signalVectors;
reference.publicVectors = baseline.publicBaseline.estimate.signalVectors;
reference.publicThetaDeg = baseline.publicBaseline.estimate.thetaDeg;
reference.publicRangeM = baseline.publicBaseline.estimate.rangeM;
end

function rows = compareMethods(design, fast, reference, tolerance)
methods = ["C_enhanced", "H_A", "P_A", "C_public"];
rows = table();
for method = methods
    actual = fast.(method);
    [expectedTheta, expectedRange, expectedVectors, state, musicCfg] = ...
        expected(method, fast, reference);
    projection = sum(conj(expectedVectors).*state.signalVectors, 1);
    projectionDifference = max(abs(1-abs(projection).^2));
    referenceState = state;
    referenceState.signalVectors = expectedVectors;
    scoreRange = fast.front.selected.rangeM;
    if method == "C_enhanced" || method == "C_public"
        scoreRange = expectedRange;
    end
    scoreDifference = abs(jad.localMusicLogScore( ...
        musicCfg, state, expectedTheta, scoreRange) ...
        - jad.localMusicLogScore(musicCfg, referenceState, ...
        expectedTheta, scoreRange));
    thetaDifference = abs(actual.thetaDeg-expectedTheta);
    rangeDifference = abs(actual.rangeM-expectedRange);
    pass = thetaDifference <= tolerance.thetaToleranceDeg ...
        && rangeDifference <= tolerance.rangeToleranceM ...
        && projectionDifference <= tolerance.projectionTolerance ...
        && scoreDifference <= tolerance.profileScoreTolerance;
    rows = [rows; table(design.seed, design.snrDb, method, ...
        thetaDifference, rangeDifference, projectionDifference, ...
        scoreDifference, pass, 'VariableNames', {'seed', 'snrDb', ...
        'method', 'absoluteThetaDifferenceDeg', ...
        'absoluteRangeDifferenceM', 'signalProjectionDifference', ...
        'musicScoreDifference', 'pass'})]; %#ok<AGROW>
end
end

function [thetaDeg, rangeM, vectors, state, musicCfg] = ...
    expected(method, fast, reference)
if method == "C_public"
    thetaDeg = reference.publicThetaDeg;
    rangeM = reference.publicRangeM;
    vectors = reference.publicVectors;
    state = fast.publicState;
    musicCfg = fast.publicCfg;
else
    if method == "C_enhanced"
        column = 1;
    elseif method == "H_A"
        column = 2;
    else
        column = 3;
    end
    thetaDeg = reference.control.thetaDeg(column);
    rangeM = reference.control.rangeM(column);
    vectors = reference.enhancedVectors;
    state = fast.enhancedState;
    musicCfg = fast.enhancedCfg;
end
end

function row = countRow(design, fast)
count = fast.counts;
row = table(design.seed, design.snrDb, count.sparseResponseCalls, ...
    count.frontFullResponseCalls, count.derivativeFrontResponseCalls, ...
    count.qOnlyFrontResponseCalls, count.profileResponseCalls, ...
    count.enhancedSearchEvaluationsC, ...
    count.enhancedSearchEvaluationsA, ...
    count.publicSearchEvaluations, ...
    fast.enhancedStateCost.fallbackCount, ...
    fast.publicStateCost.fallbackCount, ...
    fast.enhancedStateCost.gramSuccessCount, ...
    fast.publicStateCost.gramSuccessCount, ...
    fast.enhancedStateCost.matrixFormationMacs, ...
    fast.enhancedStateCost.evdCubicUnits, ...
    fast.enhancedStateCost.recoveryMacs, ...
    fast.publicStateCost.matrixFormationMacs, ...
    fast.publicStateCost.evdCubicUnits, ...
    fast.publicStateCost.recoveryMacs, ...
    'VariableNames', {'seed', 'snrDb', 'Es', 'Ef', ...
    'frontDerivativeCalls', 'frontQOnlyCalls', 'Er', 'G_C', 'G_A', ...
    'G_public', 'enhancedFallbackCount', 'publicFallbackCount', ...
    'enhancedGramSuccessCount', 'publicGramSuccessCount', ...
    'enhancedMatrixFormationMacs', 'enhancedEvdCubicUnits', ...
    'enhancedRecoveryMacs', 'publicMatrixFormationMacs', ...
    'publicEvdCubicUnits', 'publicRecoveryMacs'});
end

function summary = summarize(rows)
summary = table();
for method = unique(rows.method, "stable").'
    selected = rows.method == method;
    summary = [summary; table(method, nnz(selected), ...
        max(rows.absoluteThetaDifferenceDeg(selected)), ...
        max(rows.absoluteRangeDifferenceM(selected)), ...
        max(rows.signalProjectionDifference(selected)), ...
        max(rows.musicScoreDifference(selected)), all(rows.pass(selected)), ...
        'VariableNames', {'method', 'n', ...
        'maximumThetaDifferenceDeg', 'maximumRangeDifferenceM', ...
        'maximumProjectionDifference', 'maximumScoreDifference', ...
        'pass'})]; %#ok<AGROW>
end
end
