function output = run_round39_aperture_vpml_ablation(options)
%RUN_ROUND39_APERTURE_VPML_ABLATION Run the fixed existing-60 factorial.

arguments
    options.NumWorkers (1, 1) double {mustBeInteger, mustBePositive} = 8
    options.BatchSize (1, 1) double {mustBeInteger, mustBePositive} = 6
    options.PoolType (1, 1) string ...
        {mustBeMember(options.PoolType, ["Threads", "Processes"])} = "Threads"
end

project = string(fileparts(fileparts(mfilename("fullpath"))));
addpath(project);
addpath(fullfile(project, "+r35", "common"));
addpath(fullfile(project, "+r38", "common"));
addpath(fullfile(project, "+r38", "schemeF"));
addpath(fullfile(project, "+r39", "common"));
addpath(fullfile(project, "+r39", "ablation"));
protocol = r39AblationProtocol();

inputFile = fullfile(project, "results", "full_spectrum", ...
    "round38_schemeF_raw_array_vpml_development_v1", "result.mat");
baseline = load(inputFile, "identity", "design", "results");
cfg = jad.defaultConfig();
validateFrozenInput(project, inputFile, baseline, cfg, protocol);
scan = fsjad.prepareScan(cfg);

frozenSource = frozenManifest(project);
frozenSourceDigest = r32.sourceDigest(frozenSource);
algorithmSource = algorithmManifest(project);
algorithmSourceDigest = r32.sourceDigest(algorithmSource);
reportingSource = reportingManifest(project);
reportingSourceDigest = r32.sourceDigest(reportingSource);
identity = struct(version=protocol.version, date=protocol.date, ...
    dataRole=protocol.evidenceRole, studyLabel=protocol.studyLabel, ...
    protocol=protocol, inputResultSha256=protocol.input.resultSha256, ...
    frozenReadOnlySourceDigest=frozenSourceDigest, ...
    algorithmSourceDigest=algorithmSourceDigest, ...
    reportingSourceDigest=reportingSourceDigest, ...
    developmentUsersAuthorized=protocol.input.users, ...
    developmentUsersExecuted=0, calibrationRowsReadForEstimation=0, ...
    calibrationRowsReadForReporting=0, finalTrialsReadOrExecuted=0, ...
    newUsersGenerated=0, parameterTuningPerformed=false, ...
    variantsExecuted=protocol.factor.executedVariants, ...
    variantReused=protocol.factor.reusedVariant);

folder = fullfile(project, "results", "full_spectrum", ...
    "round39_aperture_vpml_factorial_ablation_development_v1");
if ~isfolder(folder)
    mkdir(folder);
end
checkpointFile = fullfile(folder, "checkpoint.mat");
results = cell(height(baseline.design), 1);
environment = struct();
if isfile(checkpointFile)
    saved = load(checkpointFile, "identity", "design", ...
        "results", "environment");
    if ~checkpointCompatible(saved.identity, identity) ...
            || ~isequaln(saved.design, baseline.design)
        error("r39:StaleAblationCheckpoint", ...
            "The R39 checkpoint has a different frozen identity.");
    end
    results = saved.results;
    environment = saved.environment;
end

pool = [];
pending = find(cellfun(@isempty, results));
if ~isempty(pending)
    pool = preparePool(options.PoolType, options.NumWorkers);
    for first = 1:options.BatchSize:numel(pending)
        rows = pending(first:min(first+options.BatchSize-1, numel(pending)));
        rowDesign = baseline.design(rows, :);
        rowBaseline = baseline.results(rows);
        batch = cell(numel(rows), 1);
        parfor index = 1:numel(rows)
            batch{index} = r39AblationTrial(cfg, scan, ...
                rowDesign(index, :), rowBaseline{index}, rows(index), ...
                r34.config(), protocol);
        end
        results(rows) = batch;
        environment = environmentRecord(pool, options.BatchSize);
        design = baseline.design; %#ok<NASGU>
        save(checkpointFile, "identity", "design", "results", ...
            "environment", "-v7.3");
        fprintf("R39 FACTORIAL: %d/%d\n", ...
            nnz(~cellfun(@isempty, results)), height(baseline.design));
    end
end
if ~isempty(pool)
    environment = environmentRecord(pool, options.BatchSize);
    delete(pool);
end

failures = failureTable(baseline.design, results);
writeLabeled(failures, fullfile(folder, "failures.csv"), ...
    protocol.studyLabel);
if height(failures) > 0
    design = baseline.design; %#ok<NASGU>
    save(fullfile(folder, "result.mat"), "identity", "design", ...
        "results", "failures", "environment", "algorithmSource", ...
        "reportingSource", "frozenSource", "-v7.3");
    error("r39:AblationTrialFailure", ...
        "At least one fixed R39 development row failed.");
end

if r32.sourceDigest(frozenManifest(project)) ~= frozenSourceDigest ...
        || r32.sourceDigest(algorithmManifest(project)) ...
        ~= algorithmSourceDigest
    error("r39:SourceDriftDuringRun", ...
        "A frozen or R39 algorithm source changed during execution.");
end
summary = r39SummarizeAblation(baseline.design, results, protocol);
writeSummaryTables(folder, summary, protocol.studyLabel);
figureManifest = r39BuildAblationFigures(summary, folder);

calibrationFile = fullfile(project, "results", "full_spectrum", ...
    "round38_schemeF_raw_array_vpml_calibration600_v1", "result.mat");
calibrationHash = fsjad.sourceHashManifest(project, replace( ...
    extractAfter(calibrationFile, strlength(project)+1), ...
    string(filesep), "/"));
if calibrationHash.sha256 ~= protocol.reporting.calibrationResultSha256
    error("r39:CalibrationReportingInputMismatch", ...
        "The frozen calibration result does not match the reporting hash.");
end
calibration = load(calibrationFile, "identity", "summary");
if calibration.identity.completedUsers ~= protocol.reporting.calibrationRows ...
        || calibration.identity.finalTrialsReadOrExecuted ~= 0 ...
        || calibration.identity.newUsersGenerated ~= 0
    error("r39:CalibrationReportingIdentityMismatch", ...
        "The reporting-only calibration input identity is invalid.");
end
efpaFigureManifest = r39BuildEfPaCalibrationFigures( ...
    calibration.summary, folder);

writetable(algorithmSource, fullfile(folder, ...
    "algorithm_source_hashes.csv"));
writetable(reportingSource, fullfile(folder, ...
    "reporting_source_hashes.csv"));
writetable(frozenSource, fullfile(folder, ...
    "frozen_readonly_source_hashes.csv"));
identity.developmentUsersExecuted = height(baseline.design);
identity.completedUsers = height(baseline.design);
identity.calibrationRowsReadForReporting = ...
    protocol.reporting.calibrationRows;
identity.diagnosticGatePassed = all(summary.gate.pass);
design = baseline.design; %#ok<NASGU>
save(checkpointFile, "identity", "design", "results", ...
    "environment", "-v7.3");
save(fullfile(folder, "result.mat"), "identity", "design", ...
    "results", "summary", "failures", "environment", ...
    "algorithmSource", "reportingSource", "frozenSource", ...
    "figureManifest", "efpaFigureManifest", "-v7.3");
output = struct(identity=identity, summary=summary, folder=folder, ...
    figureManifest=figureManifest, ...
    efpaFigureManifest=efpaFigureManifest);
fprintf("ROUND39_FACTORIAL_COMPLETE users=%d calibration_estimation=0 " + ...
    "calibration_reporting=%d final=0 new=0\n", height(design), ...
    identity.calibrationRowsReadForReporting);
end

function validateFrozenInput(project, inputFile, baseline, cfg, protocol)
relative = replace(extractAfter(inputFile, strlength(project)+1), ...
    string(filesep), "/");
inputHash = fsjad.sourceHashManifest(project, relative);
counts = groupcounts(baseline.design, "snrDb");
identityPass = inputHash.sha256 == protocol.input.resultSha256 ...
    && baseline.identity.completedUsers == protocol.input.users ...
    && baseline.identity.calibrationUsersReadOrExecuted == 0 ...
    && baseline.identity.finalTrialsReadOrExecuted == 0 ...
    && baseline.identity.newUsersGenerated == 0 ...
    && height(baseline.design) == protocol.input.users ...
    && numel(baseline.results) == protocol.input.users ...
    && all(cellfun(@(x) x.success, baseline.results)) ...
    && numel(unique(baseline.design.seed)) == protocol.input.users ...
    && isequal(sort(counts.snrDb).', sort(protocol.input.snrDb)) ...
    && all(counts.GroupCount == protocol.input.usersPerSnr);
if ~identityPass
    error("r39:FrozenDevelopmentInputMismatch", ...
        "The fixed R38 development input identity is invalid.");
end
r35AssertCommonProtocol(cfg, r35CommonProtocol());
frozen = r34.config();
systemPass = cfg.numAntennas == protocol.system.N ...
    && cfg.numSubcarriers == protocol.system.M ...
    && frozen.r32.music.carrierCount == protocol.system.K ...
    && frozen.r32.music.subarraySize == protocol.system.L ...
    && frozen.r32.music.numSubarrays == protocol.system.P;
if ~systemPass
    error("r39:FrozenSystemMismatch", ...
        "R39 does not match the frozen P_A system.");
end
end

function failures = failureTable(design, results)
failed = cellfun(@isempty, results);
for index = find(~failed).'
    failed(index) = ~results{index}.success;
end
failures = design(failed, ["seed", "trialIndex", "snrDb"]);
failures.errorIdentifier = strings(height(failures), 1);
failures.errorMessage = strings(height(failures), 1);
failedResults = results(failed);
for index = 1:numel(failedResults)
    if isempty(failedResults{index})
        failures.errorIdentifier(index) = "r39:MissingResult";
        failures.errorMessage(index) = "The required row was not produced.";
    else
        failures.errorIdentifier(index) = ...
            failedResults{index}.errorIdentifier;
        failures.errorMessage(index) = failedResults{index}.errorMessage;
    end
end
end

function writeSummaryTables(folder, summary, label)
writeLabeled(summary.perUser, fullfile(folder, ...
    "per_user_outputs.csv"), label);
writeLabeled(summary.methodSummary, fullfile(folder, ...
    "method_summary.csv"), label);
writeLabeled(summary.factorial, fullfile(folder, ...
    "factorial_effects.csv"), label);
writeLabeled(summary.comparisons, fullfile(folder, ...
    "paired_factor_comparisons.csv"), label);
writeLabeled(summary.diagnostics, fullfile(folder, ...
    "variant_diagnostics.csv"), label);
writeLabeled(summary.gate, fullfile(folder, ...
    "diagnostic_engineering_gate.csv"), label);
end

function writeLabeled(input, file, label)
input.studyLabel = repmat(label, height(input), 1);
writetable(input, file);
end

function pool = preparePool(poolType, workers)
pool = gcp("nocreate");
requiredClass = "parallel.ThreadPool";
if poolType == "Processes"
    requiredClass = "parallel.ProcessPool";
end
if ~isempty(pool) && (pool.NumWorkers ~= workers ...
        || string(class(pool)) ~= requiredClass)
    delete(pool);
    pool = [];
end
if isempty(pool)
    pool = parpool(poolType, workers);
end
end

function environment = environmentRecord(pool, batchSize)
environment = struct(matlabVersion=version, computer=computer, ...
    workers=pool.NumWorkers, poolClass=class(pool), batchSize=batchSize, ...
    timestamp=string(datetime("now")));
end

function pass = checkpointCompatible(saved, current)
pass = saved.version == current.version ...
    && saved.inputResultSha256 == current.inputResultSha256 ...
    && saved.frozenReadOnlySourceDigest ...
    == current.frozenReadOnlySourceDigest ...
    && saved.algorithmSourceDigest == current.algorithmSourceDigest ...
    && saved.calibrationRowsReadForEstimation == 0 ...
    && saved.finalTrialsReadOrExecuted == 0 ...
    && saved.newUsersGenerated == 0 ...
    && ~saved.parameterTuningPerformed ...
    && isequaln(saved.protocol, current.protocol);
end

function source = algorithmManifest(project)
listing = [dir(fullfile(project, "+r39", "common", "*.m")); ...
    dir(fullfile(project, "+r39", "ablation", ...
    "r39PrepareProjectionContext.m")); ...
    dir(fullfile(project, "+r39", "ablation", ...
    "r39ProjectionScore.m")); ...
    dir(fullfile(project, "+r39", "ablation", ...
    "r39AblationTrial.m"))];
source = sourceFromListing(project, listing);
end

function source = reportingManifest(project)
listing = [dir(fullfile(project, "+r39", "**", "*.m")); ...
    dir(fullfile(project, "experiments", ...
    "run_round39_aperture_vpml_ablation.m")); ...
    dir(fullfile(project, "tests", "round39*.m"))];
source = sourceFromListing(project, listing);
end

function source = frozenManifest(project)
listing = [dir(fullfile(project, "+r32", "**", "*.m")); ...
    dir(fullfile(project, "+r33", "**", "*.m")); ...
    dir(fullfile(project, "+r34", "**", "*.m")); ...
    dir(fullfile(project, "+r35", "**", "*.m")); ...
    dir(fullfile(project, "+r36", "**", "*.m")); ...
    dir(fullfile(project, "+r37", "**", "*.m")); ...
    dir(fullfile(project, "+r38", "**", "*.m"))];
source = sourceFromListing(project, listing);
end

function source = sourceFromListing(project, listing)
paths = strings(numel(listing), 1);
for index = 1:numel(listing)
    file = string(fullfile(listing(index).folder, listing(index).name));
    paths(index) = replace(extractAfter(file, strlength(project)+1), ...
        string(filesep), "/");
end
source = fsjad.sourceHashManifest(project, sort(unique(paths)));
end
