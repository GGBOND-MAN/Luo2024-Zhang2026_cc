function authorize_round46_pfa_final(approvalPhrase)
%AUTHORIZE_ROUND46_PFA_FINAL Create the exact one-time authorization.

arguments
    approvalPhrase (1, 1) string
end

project = string(fileparts(fileparts(mfilename("fullpath"))));
r41.addPaths(project);
locations = r46.paths(project);
if isfolder(locations.executionFolder)
    error("r46:ExistingFinalResultDirectory", ...
        "The R46 final execution folder already exists.");
end
if isfile(locations.authorizationFile)
    error("r46:AuthorizationAlreadyExists", ...
        "The immutable R46 authorization already exists.");
end
saved = r46.validateProtocolPackage(project);
if approvalPhrase ~= saved.protocol.execution.authorizationPhrase
    error("r46:ExplicitApprovalPhraseRequired", ...
        "The exact explicit R46 approval phrase is required.");
end
authorization = struct(approved=true, ...
    protocolVersion=saved.identity.protocolVersion, ...
    designHash=saved.identity.designHash, ...
    statisticsHash=saved.identity.statisticsHash, ...
    sourceDigest=saved.identity.sourceDigest, ...
    calibrationSourceDigest=saved.identity.calibrationSourceDigest, ...
    statement= ...
    "user-explicitly-authorized-one-frozen-R46-1400-trial-final", ...
    authorized=true, trialsExecuted=0, ...
    approvedAt=string(datetime("now", "TimeZone", "Asia/Shanghai")));
save(locations.authorizationFile, "authorization");
fprintf("ROUND46_FINAL_AUTHORIZED design=%s trials=0\n", ...
    authorization.designHash);
end
