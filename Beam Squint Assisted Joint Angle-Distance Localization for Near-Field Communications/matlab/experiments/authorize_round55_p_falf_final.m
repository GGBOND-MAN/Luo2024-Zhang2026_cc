function authorize_round55_p_falf_final(approvalPhrase)
%AUTHORIZE_ROUND55_P_FALF_FINAL Create one manual-run authorization.

arguments
    approvalPhrase (1, 1) string
end

project = string(fileparts(fileparts(mfilename("fullpath"))));
r41.addPaths(project);
locations = r55.paths(project);
if isfolder(locations.executionFolder) || isfile(locations.authorizationFile)
    error("r55:ExistingFinalState", ...
        "R55 execution or authorization already exists.");
end
saved = r55.validateProtocolPackage(project);
if approvalPhrase ~= saved.protocol.execution.authorizationPhrase
    error("r55:ExplicitApprovalPhraseRequired", ...
        "The exact explicit R55 approval phrase is required.");
end
authorization = struct(approved=true, ...
    protocolVersion=saved.identity.protocolVersion, ...
    designHash=saved.identity.designHash, ...
    statisticsHash=saved.identity.statisticsHash, ...
    sourceDigest=saved.identity.sourceDigest, ...
    statement="user-authorized-manual-R55-1400-final", ...
    trialsExecuted=0, ...
    approvedAt=string(datetime("now", "TimeZone", "Asia/Shanghai")));
save(locations.authorizationFile, "authorization");
fprintf("ROUND55_FINAL_AUTHORIZED_MANUAL design=%s trials=0\n", ...
    authorization.designHash);
end
