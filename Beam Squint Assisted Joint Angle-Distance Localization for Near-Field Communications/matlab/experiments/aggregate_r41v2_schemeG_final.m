function output = aggregate_r41v2_schemeG_final()
%AGGREGATE_R41V2_SCHEMEG_FINAL Apply the frozen v2 statistical hierarchy.

project = string(fileparts(fileparts(mfilename("fullpath"))));
r41.addPaths(project);
saved = r41statsv2.validateProtocolPackage(project);
locations = r41statsv2.paths(project);
authorization = r41.assertAuthorized( ...
    locations.protocolFolder, saved.identity);
payloads = cell(2, 1);
for shardId = 1:2
    folder = fullfile(locations.executionFolder, ...
        sprintf("shard_%02d_of_02", shardId));
    if ~isfile(fullfile(folder, "COMPLETE.mat")) ...
            || ~isfile(fullfile(folder, "result.mat"))
        error("r41v2:IncompleteFinalShard", ...
            "R41 v2 shard %d is not complete.", shardId);
    end
    payloads{shardId} = load(fullfile(folder, "result.mat"), ...
        "identity", "design", "results", "environment", "failures");
end
results = r41.mergeShardPayloads(saved.design, payloads, saved.identity);
failed = cellfun(@(item) ~item.success, results);
if any(failed)
    error("r41v2:FinalFailuresStopPrimaryInference", ...
        "At least one frozen final row failed. Do not replace or rerun it.");
end
analysis = r41statsv2.summarizeFinal( ...
    saved.design, results, saved.protocol);
folder = fullfile(locations.executionFolder, "aggregate");
if isfolder(folder)
    error("r41v2:AggregateAlreadyExists", ...
        "The R41 v2 aggregate cannot be overwritten.");
end
mkdir(folder);
writetable(analysis.perUser, fullfile(folder, "per_user.csv"));
writetable(analysis.summary, fullfile(folder, "descriptive_summary.csv"));
writetable(analysis.paired, fullfile(folder, "paired_wtl.csv"));
writetable(analysis.coPrimaryGlobal, ...
    fullfile(folder, "co_primary_global_endpoints.csv"));
writetable(analysis.pointwiseConsistency, ...
    fullfile(folder, "pointwise_consistency_gate.csv"));
writetable(analysis.perSnrConfirmatoryFamilies, ...
    fullfile(folder, "per_snr_simultaneous_characterization.csv"));
writetable(analysis.interpretation, ...
    fullfile(folder, "frozen_interpretation.csv"));
writetable(analysis.complexityCounts, ...
    fullfile(folder, "complexity_counts.csv"));
identity = struct( ...
    version="R41-independent-final-aggregate-v2", ...
    protocolVersion=saved.identity.protocolVersion, ...
    authorized=true, trialsExecuted=height(saved.design), ...
    algorithmDigest=saved.identity.algorithmDigest, ...
    designHash=saved.identity.designHash, ...
    statisticsVersion=saved.identity.statisticsVersion, ...
    statisticsHash=saved.identity.statisticsHash, ...
    sourceDigest=saved.identity.sourceDigest, ...
    r33Digest=saved.identity.r33Digest, r34Digest=saved.identity.r34Digest, ...
    frozenDependencyDigest=saved.identity.frozenDependencyDigest, ...
    authorizationDigest=r41.structHash(authorization), ...
    coreFinalStatisticalSuccess=analysis.coreFinalStatisticalSuccess, ...
    pointwiseConsistencyPass=analysis.pointwiseConsistencyPass, ...
    strongAllSnrSuccess=analysis.strongAllSnrSuccess, ...
    timestamp=string(datetime("now", "TimeZone", "Asia/Shanghai")));
source = r41statsv2.sourceManifest(project);
save(fullfile(folder, "result.mat"), "identity", "analysis", ...
    "source", "-v7.3");
output = struct(identity=identity, analysis=analysis, folder=folder);
fprintf("R41_V2_FINAL_AGGREGATE_COMPLETE trials=%d core=%d strong=%d\n", ...
    identity.trialsExecuted, identity.coreFinalStatisticalSuccess, ...
    identity.strongAllSnrSuccess);
end
