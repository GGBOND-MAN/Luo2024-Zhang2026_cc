function aggregate_round31_fixed_n256_timing()
%AGGREGATE_ROUND31_FIXED_N256_TIMING Summarize corrected N256/L160 timing.

project = string(fileparts(fileparts(mfilename("fullpath"))));
addpath(project);
folder = fullfile(project, "results", "full_spectrum", ...
    "round31_fixed_n256_timing_v2");
saved = load(fullfile(folder, "result.mat"), ...
    "identity", "output", "environment");
output = saved.output;
if any(output.numAntennas ~= 256 | output.subarraySize ~= 160 ...
        | output.numSubarrays ~= 97)
    error("r31:TimingConfigurationDrift", ...
        "Every corrected timing row must use N256/L160/P97.");
end

raw = r31.loadRound30Raw(project, IncludeBaselineResults=false);
baselineFile = matfile(raw.baselineFile);
consistency = table();
for seed = unique(output.seed).'
    designIndex = find(raw.pilot.design.seed == seed, 1);
    baselineCell = baselineFile.results( ...
        designIndex, raw.l06BaselineIndex);
    expected = baselineCell{1}.enhancedBaseline.estimate;
    rows = output(output.seed == seed & output.method == "C_enhanced", :);
    entry = table(seed, expected.thetaDeg, expected.rangeM, ...
        max(abs(rows.thetaDeg-expected.thetaDeg)), ...
        max(abs(rows.rangeM-expected.rangeM)), ...
        'VariableNames', {'seed', 'storedThetaDeg', 'storedRangeM', ...
        'maximumThetaDifferenceDeg', 'maximumRangeDifferenceM'});
    consistency = [consistency; entry]; %#ok<AGROW>
end
if any(consistency.maximumThetaDifferenceDeg > 1e-12 ...
        | consistency.maximumRangeDifferenceM > 1e-12)
    error("r31:TimingControlMismatch", ...
        "The corrected C timing path does not reproduce the saved control.");
end

summary = table();
for method = unique(output.method, "stable").'
    rows = output(output.method == method, :);
    entry = table(method, height(rows), rows.numAntennas(1), ...
        rows.subarraySize(1), rows.numSubarrays(1), rows.carrierCount(1), ...
        mean(rows.stateSeconds), mean(rows.searchSeconds), ...
        mean(rows.profileSeconds), mean(rows.backendSeconds), ...
        median(rows.backendSeconds), std(rows.backendSeconds), ...
        mean(rows.endToEndUsingHistoricalFrontSeconds), ...
        median(rows.endToEndUsingHistoricalFrontSeconds), ...
        mean(rows.searchEvaluations), mean(rows.profileEvaluations), ...
        'VariableNames', {'method', 'nTimingRows', 'numAntennas', ...
        'subarraySize', 'numSubarrays', 'carrierCount', ...
        'meanStateSeconds', 'meanSearchSeconds', 'meanProfileSeconds', ...
        'meanBackendSeconds', 'medianBackendSeconds', ...
        'stdBackendSeconds', 'meanEndToEndUsingHistoricalFrontSeconds', ...
        'medianEndToEndUsingHistoricalFrontSeconds', ...
        'meanSearchEvaluations', 'meanProfileEvaluations'});
    summary = [summary; entry]; %#ok<AGROW>
end

control = output(output.method == "C_enhanced", ...
    {'seed', 'repetition', 'backendSeconds', ...
    'endToEndUsingHistoricalFrontSeconds'});
control.Properties.VariableNames(3:4) = ...
    {'controlBackendSeconds', 'controlEndToEndSeconds'};
speedup = table();
for method = unique(output.method, "stable").'
    rows = output(output.method == method, ...
        {'seed', 'repetition', 'backendSeconds', ...
        'endToEndUsingHistoricalFrontSeconds'});
    rows.Properties.VariableNames(3:4) = ...
        {'methodBackendSeconds', 'methodEndToEndSeconds'};
    paired = innerjoin(control, rows, Keys={'seed', 'repetition'});
    backendRatio = paired.controlBackendSeconds ...
        ./paired.methodBackendSeconds;
    endToEndRatio = paired.controlEndToEndSeconds ...
        ./paired.methodEndToEndSeconds;
    entry = table(method, mean(backendRatio), median(backendRatio), ...
        mean(endToEndRatio), median(endToEndRatio), ...
        'VariableNames', {'method', 'meanBackendSpeedupVsC', ...
        'medianBackendSpeedupVsC', 'meanEndToEndSpeedupVsC', ...
        'medianEndToEndSpeedupVsC'});
    speedup = [speedup; entry]; %#ok<AGROW>
end

projection = groupsummary(output, "seed", "max", ...
    "maximumProjectionDifference");
writetable(summary, fullfile(folder, "timing_summary.csv"));
writetable(speedup, fullfile(folder, "paired_speedup_vs_C.csv"));
writetable(consistency, fullfile(folder, "stored_control_consistency.csv"));
writetable(projection, fullfile(folder, ...
    "phase_invariant_projection_check.csv"));
identity = saved.identity;
environment = saved.environment;
save(fullfile(folder, "aggregate.mat"), "identity", "environment", ...
    "summary", "speedup", "consistency", "projection");
fprintf("ROUND31_FIXED_N256_TIMING_AGGREGATE_COMPLETE maxCThetaDiff=%g maxCRangeDiff=%g\n", ...
    max(consistency.maximumThetaDifferenceDeg), ...
    max(consistency.maximumRangeDifferenceM));
end
