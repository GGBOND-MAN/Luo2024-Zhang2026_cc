function output = aggregate_round41_schemeG_final()
%AGGREGATE_ROUND41_SCHEMEG_FINAL Aggregate one complete authorized final.

project = string(fileparts(fileparts(mfilename("fullpath"))));
r41.addPaths(project);
saved = r41.validateProtocolPackage(project);
locations = r41.paths(project);
authorization = r41.assertAuthorized( ...
    locations.protocolFolder, saved.identity);
payloads = cell(2, 1);
for shardId = 1:2
    folder = fullfile(locations.executionFolder, ...
        sprintf("shard_%02d_of_02", shardId));
    if ~isfile(fullfile(folder, "COMPLETE.mat")) ...
            || ~isfile(fullfile(folder, "result.mat"))
        error("r41:IncompleteFinalShard", ...
            "R41 shard %d is not complete.", shardId);
    end
    payloads{shardId} = load(fullfile(folder, "result.mat"), ...
        "identity", "design", "results", "environment", "failures");
end
results = r41.mergeShardPayloads(saved.design, payloads, saved.identity);
failed = cellfun(@(item) ~item.success, results);
if any(failed)
    error("r41:FinalFailuresStopPrimaryInference", ...
        "At least one frozen final row failed. Primary inference stops; " + ...
        "do not delete, replace, or rerun the failed seed.");
end
analysis = r41.summarizeFinal(saved.design, results, saved.protocol);
folder = fullfile(locations.executionFolder, "aggregate");
if isfolder(folder)
    error("r41:AggregateAlreadyExists", ...
        "The R41 aggregate is immutable and cannot be overwritten.");
end
mkdir(folder);
writetable(analysis.perUser, fullfile(folder, "per_user.csv"));
writetable(analysis.summary, fullfile(folder, "descriptive_summary.csv"));
writetable(analysis.paired, fullfile(folder, "paired_wtl.csv"));
writetable(analysis.primaryFamilies, ...
    fullfile(folder, "primary_simultaneous_families.csv"));
writetable(analysis.globalSecondary, ...
    fullfile(folder, "global_secondary_endpoints.csv"));
writetable(analysis.complexityCounts, ...
    fullfile(folder, "complexity_counts.csv"));
identity = struct( ...
    version="R41-independent-final-aggregate-v1", ...
    protocolVersion=saved.identity.protocolVersion, ...
    authorized=true, trialsExecuted=height(saved.design), ...
    observationsRepresented=height(saved.design), ...
    algorithmDigest=saved.identity.algorithmDigest, ...
    designHash=saved.identity.designHash, ...
    statisticsVersion=saved.identity.statisticsVersion, ...
    statisticsHash=saved.identity.statisticsHash, ...
    sourceDigest=saved.identity.sourceDigest, ...
    r33Digest=saved.identity.r33Digest, ...
    r34Digest=saved.identity.r34Digest, ...
    frozenDependencyDigest=saved.identity.frozenDependencyDigest, ...
    authorizationDigest=r41.structHash(authorization), ...
    primaryOverallPass=analysis.primaryOverallPass, ...
    timestamp=string(datetime("now", "TimeZone", "Asia/Shanghai")));
source = r41.sourceManifest(project);
save(fullfile(folder, "result.mat"), "identity", "analysis", ...
    "source", "-v7.3");
output = struct(identity=identity, analysis=analysis, folder=folder);
fprintf("ROUND41_FINAL_AGGREGATE_COMPLETE authorized=1 trials=%d pass=%d\n", ...
    identity.trialsExecuted, identity.primaryOverallPass);
end
